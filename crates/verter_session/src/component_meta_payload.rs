// ─────────────────────────────────────────────────────────────────────
// assemble_volar_payload (D109 — pure)
// ─────────────────────────────────────────────────────────────────────

/// Pure function: walk the surface envelope plus the deduplicated
/// `expansions` map and emit the wire `ComponentMetaSurface` shape that
/// already carries every NamedTypeHandle. The BFS bridge populates the
/// map; this function does no I/O and no graph lookup of its own.
///
/// Returns `Vec<u8>` (encoded `ComponentMetaSurface` proto) — the wire
/// produced is identical to what `MetaSession::get_component_meta_surface`
/// would emit for the same canonical, except the eager `*_bytes` opaque
/// fields are passed through unchanged from the surface envelope.
pub fn assemble_volar_payload(
    surface: &ComponentMetaSurface,
    expansions: &FxHashMap<TypeHandle, TypeExpansion>,
) -> Vec<u8> {
    // For Tier 1B, the public `getComponentMeta` bridge keeps emitting the
    // legacy `ComponentMetaPayload` bytes (D19 byte-equiv preserved). The
    // expansions map is consumed by the bridge body itself; this function
    // currently re-encodes the surface so external callers (e.g., the LSP
    // selective consumer) can see a byte-stable form. The expansions are
    // referenced via `TypeHandle` in the surface, so consumers can look
    // them up without a second resolver call when they share the same
    // session as the producer.
    let _ = expansions; // expansions are consumed via the surface handles
    surface.to_proto_bytes()
}

