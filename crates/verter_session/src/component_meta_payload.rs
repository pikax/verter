/// Canonical-query identity for a type expression reachable from a
/// `ComponentMetaSurface`. Mirrors `verter::v1::TypeHandle` (D104) but
/// implements `Clone + Eq + Hash` so the BFS frontier can dedupe handles
/// using a `HashMap`.
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct TypeHandle {
    pub project_id: String,
    pub canonical_id: String,
    /// 16-byte content hash of the canonical file. Surface envelope
    /// stamps this from the canonical's current `IndexedReady` content
    /// hash; consumers carry the stamp on every round-trip so stale
    /// handles produce a `TypeHandleError::StaleHandle` on the next
    /// `get_component_meta_type_expansion` call.
    pub content_hash: [u8; 16],
    pub query_path: Option<TypeQueryPath>,
}

impl TypeHandle {
    pub fn root(project_id: impl Into<String>, canonical_id: impl Into<String>) -> Self {
        Self {
            project_id: project_id.into(),
            canonical_id: canonical_id.into(),
            content_hash: [0u8; 16],
            query_path: None,
        }
    }

    pub fn with_content_hash(mut self, hash: [u8; 16]) -> Self {
        self.content_hash = hash;
        self
    }

    pub fn with_query_path(mut self, path: TypeQueryPath) -> Self {
        self.query_path = Some(path);
        self
    }

    pub fn to_proto(&self) -> proto::TypeHandle {
        proto::TypeHandle {
            project_id: self.project_id.clone(),
            canonical_id: self.canonical_id.clone(),
            content_hash: self.content_hash.to_vec(),
            query_path: self.query_path.as_ref().map(TypeQueryPath::to_proto),
        }
    }

    pub fn from_proto(p: proto::TypeHandle) -> Result<Self, &'static str> {
        let bytes: [u8; 16] = p
            .content_hash
            .as_slice()
            .try_into()
            .map_err(|_| "content_hash must be 16 bytes")?;
        Ok(Self {
            project_id: p.project_id,
            canonical_id: p.canonical_id,
            content_hash: bytes,
            query_path: p.query_path.map(TypeQueryPath::from_proto).transpose()?,
        })
    }
}

#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub enum TypeQueryPath {
    /// `blake3(canonical_id || content_hash || decl_name_bytes ||
    ///         scope_path_bytes || decl_kind_byte)`. We use the
    ///  workspace's `xxh3_128` (16 bytes) as a stable equivalent —
    /// the fingerprint is internal-only so the algorithm is opaque.
    Declaration { fingerprint: [u8; 16] },
    SubExpression {
        parent: Box<TypeQueryPath>,
        child_kind: ChildKind,
        index: u32,
    },
    Instantiation {
        base: Box<TypeQueryPath>,
        type_args_fingerprint: [u8; 16],
    },
}

impl TypeQueryPath {
    fn to_proto(&self) -> proto::TypeQueryPath {
        let kind = match self {
            Self::Declaration { fingerprint } => {
                proto::type_query_path::Kind::DeclarationFingerprint(fingerprint.to_vec())
            }
            Self::SubExpression {
                parent,
                child_kind,
                index,
            } => proto::type_query_path::Kind::SubExpression(Box::new(proto::SubExpressionPath {
                parent: Some(Box::new(parent.to_proto())),
                child_kind: child_kind.to_proto() as i32,
                index: *index,
            })),
            Self::Instantiation {
                base,
                type_args_fingerprint,
            } => proto::type_query_path::Kind::Instantiation(Box::new(proto::InstantiationPath {
                base: Some(Box::new(base.to_proto())),
                type_args_fingerprint: type_args_fingerprint.to_vec(),
            })),
        };
        proto::TypeQueryPath { kind: Some(kind) }
    }

    fn from_proto(p: proto::TypeQueryPath) -> Result<Self, &'static str> {
        let kind = p.kind.ok_or("TypeQueryPath.kind missing")?;
        match kind {
            proto::type_query_path::Kind::DeclarationFingerprint(bytes) => {
                let fp: [u8; 16] = bytes
                    .as_slice()
                    .try_into()
                    .map_err(|_| "fingerprint must be 16 bytes")?;
                Ok(Self::Declaration { fingerprint: fp })
            }
            proto::type_query_path::Kind::SubExpression(sub) => {
                let parent = sub.parent.ok_or("SubExpression.parent missing")?;
                Ok(Self::SubExpression {
                    parent: Box::new(Self::from_proto(*parent)?),
                    child_kind: ChildKind::from_proto_i32(sub.child_kind)?,
                    index: sub.index,
                })
            }
            proto::type_query_path::Kind::Instantiation(inst) => {
                let base = inst.base.ok_or("Instantiation.base missing")?;
                let fp: [u8; 16] = inst
                    .type_args_fingerprint
                    .as_slice()
                    .try_into()
                    .map_err(|_| "type_args_fingerprint must be 16 bytes")?;
                Ok(Self::Instantiation {
                    base: Box::new(Self::from_proto(*base)?),
                    type_args_fingerprint: fp,
                })
            }
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum ChildKind {
    ObjectProperty,
    UnionMember,
    IntersectionArm,
    TupleElement,
    ConditionalTrue,
    ConditionalFalse,
    MappedKey,
    MappedValue,
    IndexedAccessIndex,
    InferTarget,
    FunctionParam,
    FunctionReturn,
}

impl ChildKind {
    fn to_proto(self) -> proto::ChildKind {
        match self {
            Self::ObjectProperty => proto::ChildKind::ObjectProperty,
            Self::UnionMember => proto::ChildKind::UnionMember,
            Self::IntersectionArm => proto::ChildKind::IntersectionArm,
            Self::TupleElement => proto::ChildKind::TupleElement,
            Self::ConditionalTrue => proto::ChildKind::ConditionalTrue,
            Self::ConditionalFalse => proto::ChildKind::ConditionalFalse,
            Self::MappedKey => proto::ChildKind::MappedKey,
            Self::MappedValue => proto::ChildKind::MappedValue,
            Self::IndexedAccessIndex => proto::ChildKind::IndexedAccessIndex,
            Self::InferTarget => proto::ChildKind::InferTarget,
            Self::FunctionParam => proto::ChildKind::FunctionParam,
            Self::FunctionReturn => proto::ChildKind::FunctionReturn,
        }
    }

    fn from_proto_i32(value: i32) -> Result<Self, &'static str> {
        match proto::ChildKind::try_from(value).map_err(|_| "unknown ChildKind")? {
            proto::ChildKind::ObjectProperty => Ok(Self::ObjectProperty),
            proto::ChildKind::UnionMember => Ok(Self::UnionMember),
            proto::ChildKind::IntersectionArm => Ok(Self::IntersectionArm),
            proto::ChildKind::TupleElement => Ok(Self::TupleElement),
            proto::ChildKind::ConditionalTrue => Ok(Self::ConditionalTrue),
            proto::ChildKind::ConditionalFalse => Ok(Self::ConditionalFalse),
            proto::ChildKind::MappedKey => Ok(Self::MappedKey),
            proto::ChildKind::MappedValue => Ok(Self::MappedValue),
            proto::ChildKind::IndexedAccessIndex => Ok(Self::IndexedAccessIndex),
            proto::ChildKind::InferTarget => Ok(Self::InferTarget),
            proto::ChildKind::FunctionParam => Ok(Self::FunctionParam),
            proto::ChildKind::FunctionReturn => Ok(Self::FunctionReturn),
        }
    }
}

