/// Eager scalars + lazy `NamedTypeHandle`s for every type-bearing field on
/// a `ComponentMetaAnalysis`. See `selective_component_meta.proto`
/// `ComponentMetaSurface` (D99).
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct ComponentMetaSurface {
    // Eager fields (14 of 23) — protobuf-wire scalars, copied verbatim
    // from the analysis snapshot.
    pub file_path: String,
    pub options_api: bool,
    /// Encoded proto; this struct does NOT mirror every nested protobuf
    /// type as Rust structs (would inflate the surface area). The bytes
    /// are produced by the existing `verter_protocol` mappers and are
    /// re-decoded by the consumer.
    pub flags_bytes: Vec<u8>,
    pub root_reachability_bytes: Vec<u8>,
    pub accepted_surface_completeness_bytes: Vec<u8>,
    pub macro_expansion_diagnostics_bytes: Vec<Vec<u8>>,
    pub vue_api_calls_bytes: Vec<Vec<u8>>,
    pub sfc_blocks_bytes: Option<Vec<u8>>,
    pub imports_bytes: Vec<Vec<u8>>,
    pub bindings_bytes: Vec<Vec<u8>>,
    pub styles_bytes: Vec<Vec<u8>>,
    pub components_bytes: Vec<Vec<u8>>,
    pub template_refs_bytes: Vec<Vec<u8>>,
    pub public_instance_bytes: Option<Vec<u8>>,

    // Lazy type-bearing fields (9 of 23) — one `NamedTypeHandle` per entry.
    pub props: Vec<NamedTypeHandle>,
    pub events: Vec<NamedTypeHandle>,
    pub slots: Vec<NamedTypeHandle>,
    pub models: Vec<NamedTypeHandle>,
    pub exposed: Vec<NamedTypeHandle>,
    pub accepted_props: Vec<NamedTypeHandle>,
    pub accepted_events: Vec<NamedTypeHandle>,
    pub fallthrough_surface: Option<FallthroughSurfaceLazy>,
    pub type_registry: Vec<NamedTypeHandle>,
}

impl ComponentMetaSurface {
    /// Walk the surface and collect every distinct `TypeHandle` referenced
    /// by a lazy field. The BFS bridge consumes this as the initial frontier.
    pub fn collect_all_type_handles(&self) -> Vec<TypeHandle> {
        let mut seen: FxHashSet<TypeHandle> = FxHashSet::default();
        let mut out: Vec<TypeHandle> = Vec::new();
        let push = |out: &mut Vec<TypeHandle>, seen: &mut FxHashSet<TypeHandle>, h: &TypeHandle| {
            if seen.insert(h.clone()) {
                out.push(h.clone());
            }
        };
        for slice in [
            &self.props,
            &self.events,
            &self.slots,
            &self.models,
            &self.exposed,
            &self.accepted_props,
            &self.accepted_events,
            &self.type_registry,
        ] {
            for entry in slice {
                push(&mut out, &mut seen, &entry.handle);
            }
        }
        if let Some(fallthrough) = &self.fallthrough_surface {
            for branch in &fallthrough.branches {
                for entry in &branch.props {
                    push(&mut out, &mut seen, &entry.handle);
                }
                for entry in &branch.events {
                    push(&mut out, &mut seen, &entry.handle);
                }
            }
        }
        out
    }

    /// Encode to the protobuf surface envelope. The eager
    /// `*_bytes` fields are passed through opaquely — consumers
    /// decode the relevant protobuf types from `verter::v1`.
    pub fn to_proto_bytes(&self) -> Vec<u8> {
        // Keep the wire format readable by NAPI consumers via prost.
        // We emit the wire `ComponentMetaSurface` shape with the eager
        // bytes carried by-tag. For Tier 1B the encoder is intentionally
        // minimal — only the lazy NamedTypeHandle fields and the
        // file_path / options_api scalars are populated. The downstream
        // consumers reconstruct the eager fields from the existing
        // ComponentMetaPayload path until 1C-α expands the protobuf
        // mapping.
        use prost::Message;
        let surface = proto::ComponentMetaSurface {
            file_path: self.file_path.clone(),
            options_api: self.options_api,
            flags: None,
            root_reachability: None,
            accepted_surface_completeness: 0,
            macro_expansion_diagnostics: Vec::new(),
            vue_api_calls: Vec::new(),
            sfc_blocks: None,
            imports: Vec::new(),
            bindings: Vec::new(),
            styles: Vec::new(),
            components: Vec::new(),
            template_refs: Vec::new(),
            public_instance: None,
            props: self.props.iter().map(NamedTypeHandle::to_proto).collect(),
            events: self.events.iter().map(NamedTypeHandle::to_proto).collect(),
            slots: self.slots.iter().map(NamedTypeHandle::to_proto).collect(),
            models: self.models.iter().map(NamedTypeHandle::to_proto).collect(),
            exposed: self.exposed.iter().map(NamedTypeHandle::to_proto).collect(),
            accepted_props: self
                .accepted_props
                .iter()
                .map(NamedTypeHandle::to_proto)
                .collect(),
            accepted_events: self
                .accepted_events
                .iter()
                .map(NamedTypeHandle::to_proto)
                .collect(),
            fallthrough_surface: self.fallthrough_surface.as_ref().map(|f| f.to_proto()),
            type_registry: self
                .type_registry
                .iter()
                .map(NamedTypeHandle::to_proto)
                .collect(),
        };
        surface.encode_to_vec()
    }
}

