// ─────────────────────────────────────────────────────────────────────
// MAX_BRIDGE_DEPTH (D125)
// ─────────────────────────────────────────────────────────────────────

/// Hard upper bound on the number of BFS layers the public
/// `getComponentMeta` bridge will walk before emitting a typed
/// `BridgeError::DepthExceeded` envelope.
///
/// Empirical max observed across the validated 179-fixture corpus + 5
/// representative chat-message families is 11 (D115). The constant is
/// pinned at ~3x safety margin so pathological generic-recursion shapes
/// emit a distinguishable error envelope (D114) rather than spinning.
pub const MAX_BRIDGE_DEPTH: usize = 32;

// ─────────────────────────────────────────────────────────────────────
// TypeHandle (Rust-side wrapper)
