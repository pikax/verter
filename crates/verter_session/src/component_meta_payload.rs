/// One-layer expansion of a `TypeHandle`. Mirrors `verter::v1::TypeExpansion`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TypeExpansion {
    pub handle: TypeHandle,
    pub shape: ShapeOutline,
    pub children: Vec<NamedTypeHandle>,
}

impl TypeExpansion {
    pub fn to_proto(&self) -> proto::TypeExpansion {
        proto::TypeExpansion {
            handle: Some(self.handle.to_proto()),
            shape: Some(self.shape.to_proto()),
            children: self
                .children
                .iter()
                .map(NamedTypeHandle::to_proto)
                .collect(),
        }
    }

    /// The lazy children of this expansion form the next BFS frontier.
    pub fn lazy_children(&self) -> Vec<TypeHandle> {
        self.children.iter().map(|c| c.handle.clone()).collect()
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ShapeOutline {
    Object { property_count: u32 },
    Function { param_count: u32, has_return: bool },
    Union { arm_count: u32 },
    Intersection { arm_count: u32 },
    Tuple { element_count: u32 },
    Literal(LiteralShape),
    Primitive(PrimitiveKind),
}

impl ShapeOutline {
    pub fn to_proto(&self) -> proto::ShapeOutline {
        use proto::shape_outline::Kind;
        let kind = match self {
            Self::Object { property_count } => Kind::Object(proto::ObjectShape {
                property_count: *property_count,
            }),
            Self::Function {
                param_count,
                has_return,
            } => Kind::Function(proto::FunctionShape {
                param_count: *param_count,
                has_return: *has_return,
            }),
            Self::Union { arm_count } => Kind::Union(proto::UnionShape {
                arm_count: *arm_count,
            }),
            Self::Intersection { arm_count } => Kind::Intersection(proto::IntersectionShape {
                arm_count: *arm_count,
            }),
            Self::Tuple { element_count } => Kind::Tuple(proto::TupleShape {
                element_count: *element_count,
            }),
            Self::Literal(lit) => Kind::Literal(lit.to_proto()),
            Self::Primitive(prim) => Kind::Primitive(proto::PrimitiveShape {
                kind: prim.to_proto() as i32,
            }),
        };
        proto::ShapeOutline { kind: Some(kind) }
    }
}

