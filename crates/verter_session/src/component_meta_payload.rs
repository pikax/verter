#[derive(Clone, Debug, PartialEq, Eq)]
pub enum BridgeError {
    DepthExceeded {
        depth: u32,
        max: u32,
    },
    StaleAtFrontier {
        handle: TypeHandle,
        reason: BatchExpandError,
    },
    FileNotFound {
        canonical_id: String,
    },
}

impl BridgeError {
    pub fn to_proto(&self) -> proto::BridgeError {
        use proto::bridge_error::Kind;
        let kind = match self {
            Self::DepthExceeded { depth, max } => Kind::DepthExceeded(proto::DepthExceeded {
                depth: *depth,
                max: *max,
            }),
            Self::StaleAtFrontier { handle, reason } => {
                Kind::StaleAtFrontier(proto::StaleAtFrontier {
                    handle: Some(handle.to_proto()),
                    reason: reason.to_proto() as i32,
                })
            }
            Self::FileNotFound { canonical_id } => Kind::FileNotFound(proto::FileNotFound {
                canonical_id: canonical_id.clone(),
            }),
        };
        proto::BridgeError { kind: Some(kind) }
    }

    /// D114 magic-byte-prefixed buffer:
    /// `[0xFF][prost-encoded BridgeError bytes]`.
    pub fn to_error_envelope(&self) -> Vec<u8> {
        use prost::Message;
        let mut buf = Vec::with_capacity(64);
        buf.push(0xFFu8);
        self.to_proto()
            .encode(&mut buf)
            .expect("BridgeError encode is infallible for owned bytes");
        buf
    }
}

