//! Selective component-meta surface API types (Tier 1B / D102 / D125).
//!
//! This module holds:
//! - The `MAX_BRIDGE_DEPTH` constant (D125).
//! - Rust-side wrappers over the protobuf types declared in
//!   `crates/verter_protocol/proto/verter/v1/selective_component_meta.proto`
//!   that expose ergonomic Rust constructors and `to_proto()` / `from_proto()`
//!   methods for the BFS bridge in `MetaSession::get_component_meta_payload`.
//! - The `assemble_volar_payload(surface, expansions)` pure function (D109).
//!
//! The wire types live under `verter_protocol::verter::v1::*` and are
//! generated by the `prost-build` step in `crates/verter_protocol/build.rs`
//! (D100).

use rustc_hash::{FxHashMap, FxHashSet};

