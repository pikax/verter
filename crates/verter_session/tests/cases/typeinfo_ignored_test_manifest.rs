/// ENGINE (§11.5 done-predicate part 3): a `Landed` block's required
/// guards must all be `Live` in the executable registry — an `Owed` or
/// unregistered required guard on a `Landed` block is a violation.
fn landed_blocks_with_unlive_required_guards(
    blocks: &[BlockContractRow],
    specs: &[GuardSpec],
) -> Vec<String> {
    let by_id: BTreeMap<GuardId, &GuardSpec> = specs.iter().map(|s| (s.id, s)).collect();
    let mut failures = Vec::new();
    for block in blocks {
        if !matches!(block.status, BlockLandingStatus::Landed) {
            continue;
        }
        for id in block.required_guards {
            match by_id.get(id) {
                None => failures.push(format!(
                    "{:?} is Landed but required guard {id:?} has NO GuardSpec \
                     in the executable registry",
                    block.block_id,
                )),
                Some(spec) if matches!(spec.disposition, GuardDisposition::Owed) => {
                    failures.push(format!(
                        "{:?} is Landed but required guard {id:?} is Owed \
                         (owner {:?}) — no executable implementation exists",
                        block.block_id, spec.owner,
                    ));
                }
                Some(_) => {}
            }
        }
    }
    failures
}

