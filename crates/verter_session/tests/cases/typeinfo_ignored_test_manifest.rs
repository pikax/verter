/// Normalize a `live_guard!`-recorded path to the harness's test-name
/// form: strip whitespace and the `crate::` prefix.
fn harness_test_name(recorded: &str) -> String {
    let compact: String = recorded.chars().filter(|c| !c.is_whitespace()).collect();
    compact
        .strip_prefix("crate::")
        .unwrap_or(&compact)
        .to_string()
}

/// Ask THIS test binary's own libtest harness for its inventory.
fn harness_inventory(extra_args: &[&str]) -> BTreeSet<String> {
    let exe = std::env::current_exe().expect("current_exe");
    let mut cmd = std::process::Command::new(&exe);
    cmd.arg("--list")
        .args(extra_args)
        .args(["--format", "terse"]);
    let out = cmd.output().expect("self --list");
    assert!(
        out.status.success(),
        "self harness --list failed: {}",
        String::from_utf8_lossy(&out.stderr),
    );
    String::from_utf8_lossy(&out.stdout)
        .lines()
        .filter_map(|l| l.strip_suffix(": test"))
        .map(|s| s.to_string())
        .collect()
}

/// Every bound live integration guard is REGISTERED in this binary's own
/// harness inventory and NOT ignored — execution/default-gate-membership
/// proof from the execution universe itself, not from source text. The
/// negative controls prove the oracle discriminates: a real non-test fn
/// is absent from the inventory, and a real `#[ignore]`d test shows up in
/// the ignored inventory.
#[test]
fn live_integration_guards_are_harness_registered_and_not_ignored() {
    let all = harness_inventory(&[]);
    let ignored = harness_inventory(&["--ignored"]);

    // Negative controls (the oracle discriminates).
    assert!(
        !all.contains("cases::typeinfo_ignored_test_manifest::workspace_root"),
        "negative control: a plain fn must NOT appear in the harness inventory",
    );
    assert!(
        all.contains("cases::typeinfo_ignored_test_manifest::emit_lifted_row_migrations"),
        "negative-control setup: the known-ignored test is in the inventory",
    );
    assert!(
        ignored.contains("cases::typeinfo_ignored_test_manifest::emit_lifted_row_migrations"),
        "negative control: a known-#[ignore]d test must appear in the \
         ignored inventory",
    );

    let mut failures: Vec<String> = Vec::new();
    for binding in INTEGRATION_LIVE_GUARD_BINDINGS {
        let name = harness_test_name(binding.test_path);
        if !all.contains(&name) {
            failures.push(format!(
                "{:?}: bound path `{name}` is NOT a registered test in this \
                 binary's harness inventory",
                binding.id,
            ));
        }
        if ignored.contains(&name) {
            failures.push(format!(
                "{:?}: bound test `{name}` is #[ignore]d — a live guard must \
                 run in the default gate",
                binding.id,
            ));
        }
    }
    assert!(
        failures.is_empty(),
        "live integration guards not proven executable in the default gate \
         ({}):\n  {}",
        failures.len(),
        failures.join("\n  "),
    );
}
