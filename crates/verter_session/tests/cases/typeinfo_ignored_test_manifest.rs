fn row_identity(file: &'static str, function: &'static str) -> (String, String) {
    (file.to_string(), function.to_string())
}

/// Build the block prereq adjacency from `TYPEINFO_PARITY_BLOCKS`.
fn build_prereq_map() -> BTreeMap<TypeInfoParityBlockId, Vec<TypeInfoParityBlockId>> {
    TYPEINFO_PARITY_BLOCKS
        .iter()
        .map(|b| (b.block_id, b.prereqs.to_vec()))
        .collect()
}

/// Transitive-prereq closure: is `target` == `from` or a transitive
/// prerequisite of `from`?
fn reaches(
    from: TypeInfoParityBlockId,
    target: TypeInfoParityBlockId,
    prereqs: &BTreeMap<TypeInfoParityBlockId, Vec<TypeInfoParityBlockId>>,
) -> bool {
    if from == target {
        return true;
    }
    let mut seen: BTreeSet<TypeInfoParityBlockId> = BTreeSet::new();
    let mut frontier = vec![from];
    while let Some(cur) = frontier.pop() {
        if !seen.insert(cur) {
            continue;
        }
        if cur == target {
            return true;
        }
        if let Some(edges) = prereqs.get(&cur) {
            frontier.extend(edges.iter().copied());
        }
    }
    false
}

/// The per-row prerequisite-consistency checks (checks 2–4) for ONE
/// row's `(block_id, dominant mechanism, consumed mechanisms, consumed
/// keys)`. Returns the list of failure strings (empty == consistent).
///
/// This is the SHARED engine the real guard and the discrimination
/// tests both drive: the discrimination tests prove a row with a
/// deliberately-wrong `block_id` (check 2) or whose block's prereqs do
/// NOT cover its mechanism's keys (check 4) yields a non-empty failure
/// list, while the correct table yields empty.
fn dag_row_consistency_failures(
    what: &str,
    block_id: TypeInfoParityBlockId,
    dominant: MechanismId,
    consumed_mechs: &[MechanismId],
    keys: &[SemanticQueryName],
    prereqs: &BTreeMap<TypeInfoParityBlockId, Vec<TypeInfoParityBlockId>>,
) -> Vec<String> {
    let mut failures: Vec<String> = Vec::new();
    // Check 2: dominant-mechanism owner == block. The mechanism is a
    // ROW-LEVEL fact (derived from capability/`file::function`, NOT from
    // `block_id`), so this is NOT tautological: a mis-assigned `block_id`
    // whose value disagrees with `mechanism_owning_block(mechanism_id)`
    // FAILS here.
    let owner = mechanism_owning_block(dominant);
    if owner != block_id {
        failures.push(format!(
            "{what}: dominant mechanism {dominant:?} is owned by {owner:?}, \
             not the row's block {block_id:?} (check 2)"
        ));
    }
    // Check 3: every consumed mechanism's owner is itself or a prereq.
    for &m in consumed_mechs {
        let m_owner = mechanism_owning_block(m);
        if !reaches(block_id, m_owner, prereqs) {
            failures.push(format!(
                "{what}: consumes mechanism {m:?} owned by {m_owner:?}, which \
                 is NOT block {block_id:?} nor a transitive prerequisite \
                 (check 3); missing prereq edge {block_id:?} -> … -> {m_owner:?}"
            ));
        }
    }
    // Check 4: every consumed key's owner is itself or a prereq. The key
    // set is the FULL set the row's MECHANISM dispatches (no per-block
    // narrowing), so a wrong `block_id` whose prereqs do not cover the
    // mechanism's keys FAILS here.
    for &k in keys {
        let k_owner = key_owning_block(k);
        if !reaches(block_id, k_owner, prereqs) {
            failures.push(format!(
                "{what}: consumes key {k:?} owned by {k_owner:?}, which is NOT \
                 block {block_id:?} nor a transitive prerequisite (check 4); \
                 missing prereq edge {block_id:?} -> … -> {k_owner:?}"
            ));
        }
    }
    failures
}

/// Every row-registry count DERIVES from the append-only partition
/// registry: the `IgnoredTestRow` table recounted per status must equal
/// the generated [`ROW_REGISTRY_COUNTS`] totals AND the generated
/// [`ROW_REGISTRY_PER_BLOCK`] per-block counts, the per-status counts must
/// PARTITION the baseline, and the table stays DISJOINT from the
/// `AdditionalProofRow` table. No independent count literal exists on
/// either side — a registry identity added, removed, or re-statused
/// without regeneration FAILS here (and a hand-edit to either generated
/// side fails the byte-equal freshness guard).
#[test]
fn row_registry_counts_derive_from_partition() {
    let recount = recount_rows(EXPECTED_IGNORE_MANIFEST);
    assert_eq!(
        EXPECTED_IGNORE_MANIFEST.len(),
        ROW_REGISTRY_COUNTS.baseline,
        "the `IgnoredTestRow` table length must equal the registry baseline \
         (registry cardinality {}); got {}",
        ROW_REGISTRY_COUNTS.baseline,
        EXPECTED_IGNORE_MANIFEST.len(),
    );
    assert_eq!(
        (
            recount.ignored,
            recount.running_unratified,
            recount.lifted,
            recount.superseded
        ),
        (
            ROW_REGISTRY_COUNTS.ignored,
            ROW_REGISTRY_COUNTS.running_unratified,
            ROW_REGISTRY_COUNTS.lifted,
            ROW_REGISTRY_COUNTS.superseded
        ),
        "per-status recount of the IgnoredTestRow table must equal the \
         generated ROW_REGISTRY_COUNTS",
    );
    assert_eq!(
        recount.ignored + recount.running_unratified + recount.lifted + recount.superseded,
        ROW_REGISTRY_COUNTS.baseline,
        "the per-status counts must PARTITION the baseline",
    );
    assert_eq!(
        EXPECTED_TOTAL_IGNORED_COUNT, ROW_REGISTRY_COUNTS.ignored,
        "EXPECTED_TOTAL_IGNORED_COUNT is DERIVED as count(status == Ignored) \
         and must equal the registry-derived ignored count",
    );

    // Per-block derivation: recount the table per block and compare against
    // the generated per-block table (which the generator derives from the
    // SAME registry).
    let mut per_block: BTreeMap<TypeInfoParityBlockId, (usize, usize, usize, usize, usize)> =
        TYPEINFO_PARITY_BLOCKS
            .iter()
            .map(|b| (b.block_id, (0, 0, 0, 0, 0)))
            .collect();
    for row in EXPECTED_IGNORE_MANIFEST {
        let bucket = per_block
            .get_mut(&row.block_id)
            .unwrap_or_else(|| panic!("row {}::{} names unknown block", row.file, row.function));
        bucket.0 += 1;
        match row.status {
            IgnoreStatus::Ignored => bucket.1 += 1,
            IgnoreStatus::RunningUnratified { .. } => bucket.2 += 1,
            IgnoreStatus::Lifted { .. } => bucket.3 += 1,
            IgnoreStatus::SupersededBy { .. } => bucket.4 += 1,
        }
    }
    assert_eq!(
        ROW_REGISTRY_PER_BLOCK.len(),
        TYPEINFO_PARITY_BLOCKS.len(),
        "ROW_REGISTRY_PER_BLOCK must carry one entry per block (zero-row \
         blocks included)",
    );
    for entry in ROW_REGISTRY_PER_BLOCK {
        let recounted = per_block
            .get(&entry.block_id)
            .unwrap_or_else(|| panic!("per-block entry {:?} not in the DAG", entry.block_id));
        assert_eq!(
            (
                entry.total,
                entry.ignored,
                entry.running_unratified,
                entry.lifted,
                entry.superseded
            ),
            *recounted,
            "per-block registry counts for {:?} must equal the table recount",
            entry.block_id,
        );
    }

    // Disjointness: no `(file, function)` in both tables. A
    // submatrix/additional fixture corresponding to an existing
    // ignored row stays an `IgnoredTestRow`, never duplicated as an
    // `AdditionalProofRow`.
    let ignored: BTreeSet<(String, String)> = EXPECTED_IGNORE_MANIFEST
        .iter()
        .map(|r| row_identity(r.file, r.function))
        .collect();
    let additional: BTreeSet<(String, String)> = ADDITIONAL_PROOF_ROWS
        .iter()
        .map(|r| row_identity(r.file, r.function))
        .collect();
    let overlap: Vec<(String, String)> = ignored.intersection(&additional).cloned().collect();
    assert!(
        overlap.is_empty(),
        "the `IgnoredTestRow` and `AdditionalProofRow` tables must be \
         DISJOINT — a `(file, function)` in both means a coverage fixture \
         was double-counted. Overlap:\n  {}",
        overlap
            .iter()
            .map(|(f, fnm)| format!("{f} :: {fnm}"))
            .collect::<Vec<_>>()
            .join("\n  "),
    );
}

