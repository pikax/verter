/// `verification_labels` (verification command labels) it runs.
///
/// `required_guards` is a list of [`GuardId`]s — every entry resolves to a
/// `GuardSpec` in the executable [`GUARD_REGISTRY`], which records the
/// guard's owner block and disposition (`Live { target }` with a
/// fn-pointer binding verified against the target harness's own inventory,
/// or `Owed` — retained valid work for the owning block). A contract may
/// carry `Owed` guards while the block is NOT `Landed`; the
/// `landed_typeinfo_blocks_have_required_guards` done-predicate forbids a
/// `Landed` status while any required guard is `Owed`. Contract changes
/// (removing, replacing, or adding a requirement) happen only through a
/// recorded [`ContractAmendment`]. The list is authored in
/// `scripts/gen-typeinfo-ignore-manifest.mjs` (`BLOCK_TO_REQUIRED_GUARDS` +
/// `GUARD_REGISTRY_DATA`) and regenerated into
/// `manifest_data/typeinfo_parity_blocks.rs` /
/// `manifest_data/typeinfo_guard_registry.rs`.
#[derive(Clone, Copy, Debug)]
#[allow(dead_code)]
struct BlockContractRow {
    block_id: TypeInfoParityBlockId,
    owning_u_block: UBlock,
    organ: ArchitectureOrgan,
    status: BlockLandingStatus,
    prereqs: &'static [TypeInfoParityBlockId],
    mechanism_id: MechanismId,
    consumed_mechanisms: &'static [MechanismId],
    required_guards: &'static [GuardId],
    verification_labels: &'static [&'static str],
}

/// The single block that OWNS (produces) each `SemanticQueryName`.
/// The owner is the block whose subplan "SemanticQueryKey/facts
/// touched:" line lists the key WITH ITS VALUE DOMAIN (the PRODUCER), NOT a
/// block that lists it under "Facts read" or among "all EXISTING keys" (a
/// CONSUMER). Each owner below is cited by its STABLE subplan block heading
/// (its `SemanticQueryKey/facts touched:` producer line), NOT an absolute doc
/// line number — line numbers drift as the docs are edited, the block heading
/// does not:
/// - foundational decl/value keys (`ResolveDecl`, `TypeOf`, `NormalizeUnion`,
///   `NormalizeIntersection`) PLUS `Instantiate` at
///   `U2.QUERY_VALUE_DOMAIN` (its `Context` adds/upgrades the U2 key surface +
///   value-domain arms; generic substitution is a value-domain instantiation,
///   not a relation inference);
/// - relation / conditional at `U2.RELATION_INFER`;
/// - indexed-access / keyof / member / path at `U2.INDEXED_ACCESS`;
/// - mapped + template-literal reduction at `U2.MAPPED_TEMPLATE`;
/// - class-surface projection PLUS `ApparentType` (lib-wrapper member lookup)
///   and `ResolveOverloadSet` (ordered-signature SHAPE) at `U2.CLASS_SURFACES`
///   (its `SemanticQueryKey/facts touched:` line lists `ResolveClassSurface`,
///   `ApparentType`, `ResolveOverloadSet` with their value domains; the
///   `U6.CALL_RESOLVE` subplan confirms U2.CLASS_SURFACES owns the overload-set
///   SHAPE while U6 only CONSUMES it and produces `ResolveCall`);
/// - enum value/type duality at `U2.ENUMS`;
/// - ambient-namespace at `U2.MODULE_AUGMENTATION` (its
///   `SemanticQueryKey/facts touched:` line lists `ResolveAmbientNamespace`
///   with value domain `TypeNode`; the `U2.JSX_FOUNDATIONS` subplan lists it
///   among "all EXISTING keys (no JSX key)" — JSX CONSUMES it, owns nothing);
/// - flow narrowing at `U6.FLOW_RETURN_SUBSTRATE` (the flow-frame substrate
///   every narrowing mechanism composes on);
/// - contextual typing at `U6.CONTEXTUAL_CALLBACK` (owns the published
///   `ContextualTypeAt` query);
/// - macro payload at `U14.MACRO_ADAPTER`;
/// - the locator-shape body lowering (`LowerLocator`) at
///   `U2.QUERY_VALUE_DOMAIN` — it extends the foundational decl/value key
///   surface that block owns (the strictly-unsubstituted authored-body
///   shape `Instantiate` composes; no manifest row consumes it).
fn key_owning_block(key: SemanticQueryName) -> TypeInfoParityBlockId {
    use SemanticQueryName::*;
    use TypeInfoParityBlockId::*;
    match key {
        ResolveDecl
        | TypeOf
        | NormalizeUnion
        | NormalizeIntersection
        | Instantiate
        | LowerLocator => U2QueryValueDomain,
        Relate | Conditional => U2RelationInfer,
        IndexedAccess | KeyOf | ProjectMember | ProjectPath => U2IndexedAccess,
        // The correlated object-spread projection is core query-value
        // machinery: relation, paths, excess, and enumeration all consume
        // its evidence through canonical dispatch.
        ProjectObjectSpread => U2QueryValueDomain,
        MappedType | TemplateLiteralReduce => U2MappedTemplate,
        ResolveClassSurface | ApparentType | ResolveOverloadSet => U2ClassSurfaces,
        ResolveEnum => U2Enums,
        ResolveAmbientNamespace => U2ModuleAugmentation,
        FlowNarrowingAt => U6FlowReturnSubstrate,
        FlowReturn => U6FlowReturnSubstrate,
        ContextualTypeAt => U6ContextualCallback,
        // The terminal broad-runtime-kind classifier is macro-adapter
        // work: it exists to give the Vue macro runtime-shape projection
        // its per-member constructor verdicts through canonical dispatch.
        ResolveMacroPayload | ClassifyBroadRuntime => U14MacroAdapter,
        // The materialization cycle gate is core query-value machinery:
        // a sealed classifier family whose `Decided` verdicts admit
        // through the family singleflight.
        ClassifyMaterializationCycleGate => U2QueryValueDomain,
    }
}

