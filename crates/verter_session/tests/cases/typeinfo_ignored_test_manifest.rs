/// `const fn` count of `IgnoredTestRow`s whose `status == Ignored`.
/// This is the DERIVED source of `EXPECTED_TOTAL_IGNORED_COUNT` — it is
/// NOT a frozen literal. A block branch that flips its rows
/// `Ignored → Lifted` decrements this automatically in the same branch,
/// so every committed state is count-consistent.
const fn count_ignored_rows(rows: &[IgnoredTestRow]) -> usize {
    let mut count = 0usize;
    let mut i = 0usize;
    while i < rows.len() {
        if matches!(rows[i].status, IgnoreStatus::Ignored) {
            count += 1;
        }
        i += 1;
    }
    count
}

/// Total ignored typeinfo test sites — DERIVED as
/// `count(IgnoredTestRow where status == Ignored)`, NOT a frozen
/// literal. It tracks the live ignore set (recomputed as blocks lift
/// rows and as same-file overload retention adds new ones) and is
/// cross-checked against the registry-derived `ROW_REGISTRY_COUNTS`
/// ignored count. `Lifted` / `RunningUnratified` / `SupersededBy` rows
/// carry no live `#[ignore]`; every other `IgnoredTestRow` is `Ignored`.
///
/// Table-total note: the substrate's macro-driven test families emit
/// expanded `#[ignore = "..."]` annotations at their call sites; those
/// expansion sites ARE counted (they are real ignore annotations). What
/// the manifest does NOT count are the `#[ignore = $reason]` patterns
/// INSIDE `macro_rules!` bodies — those describe how the macro expands,
/// not the test sites themselves.
const EXPECTED_TOTAL_IGNORED_COUNT: usize = count_ignored_rows(EXPECTED_IGNORE_MANIFEST);

/// Per-status recount of the `IgnoredTestRow` table — the table-side half
/// of the derived-count comparison in
/// `row_registry_counts_derive_from_partition` (the registry-side half is
/// the generated [`ROW_REGISTRY_COUNTS`]).
fn recount_rows(rows: &[IgnoredTestRow]) -> RowRegistryCounts {
    let mut counts = RowRegistryCounts {
        baseline: rows.len(),
        ignored: 0,
        running_unratified: 0,
        lifted: 0,
        superseded: 0,
    };
    for row in rows {
        match row.status {
            IgnoreStatus::Ignored => counts.ignored += 1,
            IgnoreStatus::RunningUnratified { .. } => counts.running_unratified += 1,
            IgnoreStatus::Lifted { .. } => counts.lifted += 1,
            IgnoreStatus::SupersededBy { .. } => counts.superseded += 1,
        }
    }
    counts
}

/// Reason-strings shorter than this are rejected — every
/// `#[ignore = "..."]` must carry a meaningful sentence.
const MIN_REASON_LENGTH: usize = 16;

fn read_dir_files(dir: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let entries = match fs::read_dir(dir) {
        Ok(e) => e,
        Err(err) => panic!("read_dir {}: {err}", dir.display()),
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_file()
            && path
                .extension()
                .and_then(|e| e.to_str())
                .map(|ext| ext == "rs")
                .unwrap_or(false)
        {
            out.push(path);
        }
    }
    out.sort();
    out
}

/// Extract `(reason, fn_name)` for every literal-string
/// `#[ignore = "..."]` annotation in `source`. The function name is
/// the next `fn <name>` token after the annotation (up to ~5 lines
/// of attribute stacking — `#[test]`, `#[ignore]`, doc-comments).
/// Bare `#[ignore]` (without a reason) is counted in the `bare`
/// return value so the guard rejects it.
///
/// Macro-defined patterns (`#[ignore = $reason]` inside a
/// `macro_rules!` body) are not test sites; they describe the
/// macro's expansion. Each expansion eventually emits a real
/// `#[ignore = "..."]` annotation that the parser counts at its
/// expansion site.
fn extract_ignored_test_sites(source: &str) -> (Vec<(String, String)>, usize) {
    let mut sites = Vec::new();
    let mut bare = 0usize;
    let lines: Vec<&str> = source.lines().collect();
    for (i, raw_line) in lines.iter().enumerate() {
        let line = raw_line.trim();
        if let Some(rest) = line.strip_prefix("#[ignore") {
            let rest = rest.trim_start();
            if let Some(after_eq) = rest.strip_prefix("=") {
                let after_eq = after_eq.trim_start();
                if let Some(after_quote) = after_eq.strip_prefix('"') {
                    if let Some(end) = after_quote.rfind('"') {
                        let reason = after_quote[..end].to_string();
                        // Scan forward for the next `fn <name>` line.
                        let mut fn_name: Option<String> = None;
                        let look_end = (i + 6).min(lines.len());
                        for next_line in lines.iter().take(look_end).skip(i + 1) {
                            if let Some(name) = parse_fn_name(next_line) {
                                fn_name = Some(name);
                                break;
                            }
                        }
                        if let Some(name) = fn_name {
                            sites.push((reason, name));
                        }
                        continue;
                    }
                }
                // Macro-body `#[ignore = $reason]` — skip.
                continue;
            }
            if line.starts_with("#[ignore]") || line.starts_with("#[ignore ") {
                bare += 1;
            }
        }
    }
    (sites, bare)
}

/// Parse the function name from a line of the form
/// `(async? )?(pub[(vis)]? )?(async )?fn <name>(`.
fn parse_fn_name(line: &str) -> Option<String> {
    fn strip_vis(line: &str) -> &str {
        if let Some(rest) = line.strip_prefix("pub ") {
            return rest;
        }
        if let Some(rest) = line.strip_prefix("pub(") {
            if let Some(close) = rest.find(')') {
                return rest[close + 1..].trim_start();
            }
        }
        line
    }
    let trimmed = line.trim_start();
    let after_async = trimmed.strip_prefix("async ").unwrap_or(trimmed);
    let after_pub = strip_vis(after_async);
    let after_async = after_pub.strip_prefix("async ").unwrap_or(after_pub);
    let after_const = after_async.strip_prefix("const ").unwrap_or(after_async);
    let after_fn = after_const.strip_prefix("fn ")?;
    let name_end = after_fn
        .find(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
        .unwrap_or(after_fn.len());
    if name_end == 0 {
        return None;
    }
    Some(after_fn[..name_end].to_string())
}

