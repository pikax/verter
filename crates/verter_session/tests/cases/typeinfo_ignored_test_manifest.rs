//! The two-table manifest ledger for typeinfo full-parity tracking.
//!
//! Two tables live in this one module:
//!
//! - `IgnoredTestRow` — one row per identity in the APPEND-ONLY row
//!   registry (`scripts/manifests/typeinfo-row-block-partition.json`);
//!   every count derives from that registry (`ROW_REGISTRY_COUNTS` /
//!   `ROW_REGISTRY_PER_BLOCK` — no frozen count literal on either side).
//!   `Ignored` rows are bijective with the live `#[ignore = "..."]`
//!   annotations inside
//!   `crates/verter_session/src/typeinfo/typeinfo_tests/**/*.rs`;
//!   `RunningUnratified` rows run in the default suite while their
//!   programme obligation awaits ratification (a test becoming
//!   always-running is a status transition, never identity erasure);
//!   `Lifted` rows are oracle-backed lifts; `SupersededBy` rows preserve
//!   the identity and name an equivalent-or-stronger successor row.
//!   Each row carries the full 13-column schema: `file`, `function`,
//!   `substrate`, `capability`, `organ`, `owning_u_block`, `block_id`,
//!   `semantic_queries`, `proof`, `status`, `mechanism_id`,
//!   `consumed_mechanisms`, `unblocker`.
//! - `AdditionalProofRow` — the CLOSED set of 7 coverage-only rows (the
//!   6 JSX no-new-key submatrix rows owned by `U2.JSX_FOUNDATIONS` + the
//!   1 mapped companion owned by `U2.MAPPED_TEMPLATE`). Same schema
//!   minus `status` / `unblocker`; EXCLUDED from the ignored count +
//!   bijection.
//!
//! Both tables, the `TYPEINFO_PARITY_BLOCKS` DAG, and the typed
//! `GuardId` registry are GENERATED by
//! `scripts/gen-typeinfo-ignore-manifest.mjs` (`pnpm gen:typeinfo-manifest`).
//! The authoritative append-only row registry is the source for each
//! `IgnoredTestRow`'s `block_id` AND `status`: the generator PARSES it
//! (`parsePartition`) and joins it with the live `#[ignore]` discovery +
//! the Capability Map to emit `typeinfo_ignored_test_manifest_rows.rs`;
//! block landing statuses / contract amendments / landing transactions
//! come from `scripts/manifests/typeinfo-programme-reconciliation.json`.
//! The `AdditionalProofRow` table, the `TYPEINFO_PARITY_BLOCKS` DAG (each
//! block's `required_guards`/`verification_labels`/prereqs/mechanisms),
//! and the guard registry are authored in the generator's own data maps
//! (`buildAdditionalRows` / `JSX_NO_NEW_KEY_ROWS`; `emitBlockRows`,
//! `BLOCK_TO_REQUIRED_GUARDS`, `GUARD_REGISTRY_DATA`,
//! `BLOCK_VERIFICATION_LABELS`, the prereq/mechanism maps), NOT from the
//! row registry. The guards below only diff/fail — they never write the
//! generated source (repo rule: generators are scripts, not tests).
//!
//! `EXPECTED_TOTAL_IGNORED_COUNT` is DERIVED as
//! `count(IgnoredTestRow where status == Ignored)`, not a
//! frozen literal; it tracks the live ignore set as blocks lift rows
//! (and as same-file overload retention adds new ones) and is
//! cross-checked against the registry-derived `ROW_REGISTRY_COUNTS`.
//!
//! Guards:
//!
//! Carried-forward bijection / quality guards
//! (`every_ignored_typeinfo_test_has_a_manifest_row`,
//! `every_manifest_row_corresponds_to_a_live_ignored_test`,
//! `every_manifest_row_lists_a_valid_substrate`,
//! `every_manifest_row_has_non_empty_unblocker`,
//! `every_manifest_row_unblocker_matches_live_ignore_reason`,
//! `per_file_ignored_test_counts_match_manifest`,
//! `total_ignored_typeinfo_test_count_matches_expected`,
//! `manifest_length_matches_documented_total`,
//! `every_ignored_typeinfo_test_carries_a_reason_string`,
//! `every_ignore_reason_meets_minimum_quality_bar`) plus the
//! two-table manifest guards
//! (`row_registry_counts_derive_from_partition`,
//! `additional_proof_row_table_holds_exactly_7_rows`,
//! `typeinfo_parity_block_dag_is_acyclic_and_consumed_keys_and_mechanisms_are_prereqs`)
//! plus the executable landing-enforcement rail
//! (`landed_typeinfo_blocks_have_required_guards`,
//! `no_landed_typeinfo_block_has_live_ignored_rows`,
//! `no_vacuous_parent_u_block_landing`, `zero_row_blocks_land_exactly_once`,
//! `typeinfo_block_landing_transactions_are_atomic_and_trailer_backed`)
//! plus the Q4 independence rails
//! (`row_registry_matches_discovered_tests`,
//! `row_registry_contains_pinned_baseline_cohort` — the append-only rail,
//! containment against the pinned immutable cohort in
//! `scripts/manifests/typeinfo-row-baseline-cohort.json`, git-independent —
//! and `row_registry_is_append_only_against_head`, the early dirty-tree
//! tripwire) and the live-guard binding
//! meta-guards (`guard_registry_live_integration_bindings_are_complete`,
//! `live_integration_guards_are_harness_registered_and_not_ignored`; the
//! lib-target twins live in
//! `crates/verter_session/src/typeinfo_guard_bindings_tests.rs`).

