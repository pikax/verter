/// The block prerequisite DAG is acyclic AND every consumed
/// key / mechanism's owning block is the consuming block itself or a
/// transitive prerequisite of it. Models BOTH the semantic-query-key
/// owner edges AND the block-mechanism dependencies.
///
/// Five checks:
/// 1. Block DAG acyclic.
/// 2. Every row's dominant `mechanism_id` is owned by its own
///    `block_id`.
/// 3. Every consumed mechanism's owner is itself or a transitive
///    prerequisite.
/// 4. Every consumed key's owner is itself or a transitive
///    prerequisite.
/// 5. Diagnostic on failure.
#[test]
fn typeinfo_parity_block_dag_is_acyclic_and_consumed_keys_and_mechanisms_are_prereqs() {
    use std::collections::BTreeMap as Map;

    // Build the prereq adjacency from TYPEINFO_PARITY_BLOCKS.
    let prereqs = build_prereq_map();

    // No duplicate `block_id` rows in the contract table.
    assert_eq!(
        prereqs.len(),
        TYPEINFO_PARITY_BLOCKS.len(),
        "TYPEINFO_PARITY_BLOCKS must hold one row per block_id (no \
         duplicate block_id rows)",
    );

    // ── Check 0: every block REFERENCED anywhere must have a
    //    `BlockContractRow`. A referenced-but-missing block is NOT a
    //    leaf — deleting a referenced contract row (e.g. one that another
    //    block lists in `prereqs`, or that owns a consumed key /
    //    mechanism, or that a row's `block_id` / `owning_u_block` names)
    //    must FAIL the guard, not pass silently. We collect every
    //    referenced `TypeInfoParityBlockId` and assert each has a row.
    let contract_blocks: BTreeSet<TypeInfoParityBlockId> =
        TYPEINFO_PARITY_BLOCKS.iter().map(|b| b.block_id).collect();
    let mut referenced: BTreeSet<TypeInfoParityBlockId> = BTreeSet::new();
    for b in TYPEINFO_PARITY_BLOCKS {
        referenced.insert(b.block_id);
        for &p in b.prereqs {
            referenced.insert(p);
        }
        referenced.insert(mechanism_owning_block(b.mechanism_id));
        for &m in b.consumed_mechanisms {
            referenced.insert(mechanism_owning_block(m));
        }
    }
    for row in EXPECTED_IGNORE_MANIFEST {
        referenced.insert(row.block_id);
        referenced.insert(mechanism_owning_block(row.mechanism_id));
        for &m in row.consumed_mechanisms {
            referenced.insert(mechanism_owning_block(m));
        }
        for &k in row.semantic_queries {
            referenced.insert(key_owning_block(k));
        }
    }
    for row in ADDITIONAL_PROOF_ROWS {
        referenced.insert(row.block_id);
        referenced.insert(mechanism_owning_block(row.mechanism_id));
        for &m in row.consumed_mechanisms {
            referenced.insert(mechanism_owning_block(m));
        }
        for &k in row.semantic_queries {
            referenced.insert(key_owning_block(k));
        }
    }
    let missing_contract: Vec<TypeInfoParityBlockId> =
        referenced.difference(&contract_blocks).copied().collect();
    assert!(
        missing_contract.is_empty(),
        "block-DAG: {} block(s) are REFERENCED (by a prereq edge, a \
         key/mechanism owner, or a row's block_id / owning_u_block) but \
         have NO `BlockContractRow` — a referenced block is not a leaf, it \
         is a missing contract. Deleting a referenced contract row \
         must fail here. Missing: {:?} (check 0)",
        missing_contract.len(),
        missing_contract,
    );

    // ── Check 1: acyclicity (DFS three-colour). ──
    #[derive(Clone, Copy, PartialEq)]
    enum Color {
        White,
        Gray,
        Black,
    }
    fn visit(
        node: TypeInfoParityBlockId,
        prereqs: &Map<TypeInfoParityBlockId, Vec<TypeInfoParityBlockId>>,
        color: &mut Map<TypeInfoParityBlockId, Color>,
        stack: &mut Vec<TypeInfoParityBlockId>,
    ) -> Result<(), Vec<TypeInfoParityBlockId>> {
        color.insert(node, Color::Gray);
        stack.push(node);
        if let Some(edges) = prereqs.get(&node) {
            for &dep in edges {
                match color.get(&dep).copied().unwrap_or(Color::White) {
                    Color::Gray => {
                        let mut cyc = stack.clone();
                        cyc.push(dep);
                        return Err(cyc);
                    }
                    Color::White => visit(dep, prereqs, color, stack)?,
                    Color::Black => {}
                }
            }
        }
        stack.pop();
        color.insert(node, Color::Black);
        Ok(())
    }
    let mut color: Map<TypeInfoParityBlockId, Color> = Map::new();
    for &b in prereqs.keys() {
        if color.get(&b).copied().unwrap_or(Color::White) == Color::White {
            let mut stack = Vec::new();
            if let Err(cyc) = visit(b, &prereqs, &mut color, &mut stack) {
                panic!("block prerequisite DAG has a CYCLE: {:?} (check 1)", cyc);
            }
        }
    }

    // ── Checks 2-4 over every IgnoredTestRow + AdditionalProofRow +
    //    BlockContractRow, via the shared `dag_row_consistency_failures`
    //    engine (the same engine the discrimination tests drive). ──
    let mut failures: Vec<String> = Vec::new();

    for row in EXPECTED_IGNORE_MANIFEST {
        let what = format!("IgnoredTestRow {}::{}", row.file, row.function);
        failures.extend(dag_row_consistency_failures(
            &what,
            row.block_id,
            row.mechanism_id,
            row.consumed_mechanisms,
            row.semantic_queries,
            &prereqs,
        ));
    }
    for row in ADDITIONAL_PROOF_ROWS {
        let what = format!("AdditionalProofRow {}::{}", row.file, row.function);
        failures.extend(dag_row_consistency_failures(
            &what,
            row.block_id,
            row.mechanism_id,
            row.consumed_mechanisms,
            row.semantic_queries,
            &prereqs,
        ));
    }
    for block in TYPEINFO_PARITY_BLOCKS {
        let what = format!("BlockContractRow {:?}", block.block_id);
        // Block-level dominant + consumed mechanisms (check 2/3). Blocks
        // declare no consumed keys directly (keys ride rows).
        failures.extend(dag_row_consistency_failures(
            &what,
            block.block_id,
            block.mechanism_id,
            block.consumed_mechanisms,
            &[],
            &prereqs,
        ));
    }

    assert!(
        failures.is_empty(),
        "block-DAG / consumed-key / consumed-mechanism prerequisite \
         consistency FAILED:\n  {}",
        failures.join("\n  "),
    );
}

/// The manifest's `SemanticQueryName` mirror is BIJECTIVE with the
/// live `SemanticQueryKeyTag::ALL` discriminant set. The mirror keys queries
/// by NAME for the block-DAG guard's consumed-key check; if it drifts behind
/// the live key surface, a row could consume a live key the mirror does not
/// name (so `key_owning_block` could not be exercised for it) and the DAG
/// guard's consumed-key prerequisite check would silently never fire for that
/// key — a false pass. This guard pins the two sets equal so that can never
/// happen: a live tag absent from the mirror (or a mirror name with no live
/// tag) FAILS here, naming the exact offenders.
#[test]
fn semantic_query_name_mirror_matches_live_tag_set() {
    let live: BTreeSet<String> = SemanticQueryKeyTag::ALL
        .iter()
        .map(|tag| tag.name().to_string())
        .collect();
    let mirror: BTreeSet<String> = SEMANTIC_QUERY_NAME_ALL
        .iter()
        .map(|name| semantic_query_name_str(*name).to_string())
        .collect();

    let missing_from_mirror: Vec<&String> = live.difference(&mirror).collect();
    let extra_in_mirror: Vec<&String> = mirror.difference(&live).collect();

    assert!(
        missing_from_mirror.is_empty() && extra_in_mirror.is_empty(),
        "the manifest `SemanticQueryName` mirror has drifted from the live \
         `SemanticQueryKeyTag::ALL` set. Extend the single \
         `semantic_query_names!` invocation (which generates the enum, the \
         `SEMANTIC_QUERY_NAME_ALL` witness array, and `semantic_query_name_str` \
         together) and add a `key_owning_block` arm for every added live key in \
         the same change.\n  \
         live tags missing from the mirror: {missing_from_mirror:?}\n  \
         mirror names with no live tag: {extra_in_mirror:?}",
    );

    // Sanity floor: the live set is non-empty and the mirror array has no
    // duplicate names (a duplicated variant would shrink the set and could
    // mask a missing one).
    assert_eq!(
        mirror.len(),
        SEMANTIC_QUERY_NAME_ALL.len(),
        "`SEMANTIC_QUERY_NAME_ALL` contains duplicate variants",
    );
    assert!(
        !live.is_empty(),
        "`SemanticQueryKeyTag::ALL` must be non-empty"
    );
}

/// `key_owning_block` is LIVE authority: the block-DAG guard
/// (`typeinfo_parity_block_dag_is_acyclic_and_consumed_keys_and_mechanisms_are_prereqs`)
/// consumes it to check that every key a row consumes is produced by a prereq
/// block. But several `SemanticQueryName` keys (the apparent-type / class-surface
/// / enum / ambient-namespace / overload-set / flow / contextual reducer keys)
/// appear in NO row's `semantic_queries`, so their `key_owning_block` arms are
/// reached ONLY by compile-time match-exhaustiveness — a WRONG owner
/// (e.g. `ContextualTypeAt => U2QueryValueDomain`) would still COMPILE and every
/// other test would still pass. This test is the CLOSED-SET, DISCRIMINATING pin
/// that catches a mis-mapped owner: it asserts, for EVERY `SemanticQueryName`
/// variant, that `key_owning_block` returns the EXACT owning block the
/// mechanism-first layering assigns it (the block whose dominant mechanism
/// PRODUCES that key's result). The expected table is the closed source of truth
/// taken from the `key_owning_block` doc comment + the mechanism→block
/// partition; a wrong arm FAILS this test even though it compiles.
///
/// Closed-set completeness: the expected table's key set is asserted EQUAL to
/// `SEMANTIC_QUERY_NAME_ALL`, so adding a new `SemanticQueryName` variant
/// without a table entry here FAILS the set-equality assertion (in addition to
/// the wildcard-free `key_owning_block` match forcing a new arm to compile).
/// Each expected owner is also asserted to exist in `TYPEINFO_PARITY_BLOCKS`.
#[test]
fn key_owning_block_owner_mapping_is_pinned_closed_set() {
    use SemanticQueryName::*;
    use TypeInfoParityBlockId::*;

    // EXPECTED (key → owning block) — the mechanism-first layering.
    // The block whose dominant mechanism PRODUCES the key's result, NOT where
    // the key's shape was first declared. Encoded explicitly so a wrong arm in
    // `key_owning_block` FAILS even when match-exhaustiveness alone passes.
    let expected: &[(SemanticQueryName, TypeInfoParityBlockId)] = &[
        // Owners cited by STABLE subplan block heading (its
        // `SemanticQueryKey/facts touched:` producer line), not an absolute
        // doc line number — line numbers drift as docs are edited.
        // Foundational decl/value keys at U2.QUERY_VALUE_DOMAIN.
        (ResolveDecl, U2QueryValueDomain),
        (TypeOf, U2QueryValueDomain),
        (NormalizeUnion, U2QueryValueDomain),
        (NormalizeIntersection, U2QueryValueDomain),
        // Generic substitution (`Instantiate`) is a value-domain instantiation
        // produced by U2.QUERY_VALUE_DOMAIN's foundation, NOT a relation
        // inference — it joins the foundational decl/value keys here.
        (Instantiate, U2QueryValueDomain),
        // The correlated object-spread projection is query-value machinery:
        // relation, paths, excess, and enumeration all consume its evidence
        // through canonical dispatch.
        (ProjectObjectSpread, U2QueryValueDomain),
        // Relation / conditional at U2.RELATION_INFER.
        (Relate, U2RelationInfer),
        (Conditional, U2RelationInfer),
        // Indexed-access / keyof / member / path at U2.INDEXED_ACCESS.
        (IndexedAccess, U2IndexedAccess),
        (KeyOf, U2IndexedAccess),
        (ProjectMember, U2IndexedAccess),
        (ProjectPath, U2IndexedAccess),
        // Mapped + template-literal reduction at U2.MAPPED_TEMPLATE.
        (MappedType, U2MappedTemplate),
        (TemplateLiteralReduce, U2MappedTemplate),
        // Class-surface projection PLUS the apparent-member lookup and the
        // ordered-overload-set SHAPE at U2.CLASS_SURFACES (its
        // `SemanticQueryKey/facts touched:` line produces ResolveClassSurface /
        // ApparentType / ResolveOverloadSet; the U6.CALL_RESOLVE subplan
        // confirms U6 only CONSUMES ResolveOverloadSet).
        (ResolveClassSurface, U2ClassSurfaces),
        (ApparentType, U2ClassSurfaces),
        (ResolveOverloadSet, U2ClassSurfaces),
        // Enum value/type duality at U2.ENUMS.
        (ResolveEnum, U2Enums),
        // Ambient-namespace at U2.MODULE_AUGMENTATION (its
        // `SemanticQueryKey/facts touched:` line produces ResolveAmbientNamespace;
        // the U2.JSX_FOUNDATIONS subplan lists it among "all EXISTING keys (no
        // JSX key)" — JSX_FOUNDATIONS consumes it, owns nothing).
        (ResolveAmbientNamespace, U2ModuleAugmentation),
        // Flow narrowing on the flow-frame substrate at
        // U6.FLOW_RETURN_SUBSTRATE.
        (FlowNarrowingAt, U6FlowReturnSubstrate),
        // The whole-function return producer on the flow substrate at
        // U6.FLOW_RETURN_SUBSTRATE.
        (FlowReturn, U6FlowReturnSubstrate),
        // Contextual typing at U6.CONTEXTUAL_CALLBACK.
        (ContextualTypeAt, U6ContextualCallback),
        // Macro payload at U14.MACRO_ADAPTER.
        (ResolveMacroPayload, U14MacroAdapter),
        // Locator-shape body lowering at U2.QUERY_VALUE_DOMAIN — it extends
        // the foundational decl/value key surface (the
        // strictly-unsubstituted authored-body shape `Instantiate`
        // composes; no manifest row consumes it).
        (LowerLocator, U2QueryValueDomain),
        (ClassifyBroadRuntime, U14MacroAdapter),
        // The materialization cycle gate at U2.QUERY_VALUE_DOMAIN — a
        // sealed classifier family over the family memo (the retired
        // `RefCycleResultDb`'s replacement); its `Decided` verdicts
        // admit through the singleflight like every other value-domain
        // family.
        (ClassifyMaterializationCycleGate, U2QueryValueDomain),
    ];

    // DISCRIMINATING per-key pin: a wrong `key_owning_block` arm FAILS here.
    let mut mismatches: Vec<String> = Vec::new();
    for (key, expected_owner) in expected {
        let actual = key_owning_block(*key);
        if actual != *expected_owner {
            mismatches.push(format!(
                "{key:?}: key_owning_block returned {actual:?}, expected {expected_owner:?}",
            ));
        }
    }
    assert!(
        mismatches.is_empty(),
        "key_owning_block owner mapping diverged from the pinned table \
         ({} mismatch(es)):\n  {}",
        mismatches.len(),
        mismatches.join("\n  "),
    );

    // CLOSED-SET completeness: the expected table's key set == the full
    // `SemanticQueryName` mirror set. A newly-added key with no table entry
    // FAILS here (and the wildcard-free `key_owning_block` match also forces a
    // new arm to compile, so an added key cannot silently inherit an owner).
    let expected_keys: BTreeSet<SemanticQueryName> = expected.iter().map(|(k, _)| *k).collect();
    let all_keys: BTreeSet<SemanticQueryName> = SEMANTIC_QUERY_NAME_ALL.iter().copied().collect();
    assert_eq!(
        expected_keys.len(),
        expected.len(),
        "the expected key→owner table contains a duplicate key — each key \
         must be pinned exactly once",
    );
    let missing_from_table: Vec<&SemanticQueryName> = all_keys.difference(&expected_keys).collect();
    let extra_in_table: Vec<&SemanticQueryName> = expected_keys.difference(&all_keys).collect();
    assert!(
        missing_from_table.is_empty() && extra_in_table.is_empty(),
        "the pinned key→owner table is not a closed set over \
         `SEMANTIC_QUERY_NAME_ALL` — add a table entry for every new key (and \
         a `key_owning_block` arm) in the same change.\n  \
         keys missing from the table: {missing_from_table:?}\n  \
         table keys with no mirror variant: {extra_in_table:?}",
    );

    // Each pinned owner must be a real block in the DAG.
    let known_blocks: BTreeSet<TypeInfoParityBlockId> =
        TYPEINFO_PARITY_BLOCKS.iter().map(|b| b.block_id).collect();
    let unknown_owners: Vec<String> = expected
        .iter()
        .filter(|(_, owner)| !known_blocks.contains(owner))
        .map(|(key, owner)| format!("{key:?} → {owner:?} (not in TYPEINFO_PARITY_BLOCKS)"))
        .collect();
    assert!(
        unknown_owners.is_empty(),
        "pinned owner block(s) absent from `TYPEINFO_PARITY_BLOCKS`:\n  {}",
        unknown_owners.join("\n  "),
    );
}

/// Every `BlockContractRow` CARRIES its contract metadata: a non-empty,
/// deduplicated typed `required_guards` list and a non-empty
/// `verification_labels` list — and the typed guard registry is CLOSED
/// over the contracts: every `GuardId` variant has exactly one
/// `GuardSpec`, every required id resolves to that spec, and every
/// registry entry is required by at least one block (no dead
/// obligations). The LANDING-time enforcement (a landed block's required
/// guards are all `Live`) is `landed_typeinfo_blocks_have_required_guards`.
#[test]
fn every_block_contract_row_carries_required_guards() {
    const MIN_LABEL_LENGTH: usize = 8;
    let mut violations: Vec<String> = Vec::new();

    // Registry closure over the GuardId enum: one GuardSpec per variant.
    let mut spec_ids: Vec<GuardId> = GUARD_REGISTRY.iter().map(|s| s.id).collect();
    spec_ids.sort();
    let unique_spec_ids: BTreeSet<GuardId> = spec_ids.iter().copied().collect();
    if unique_spec_ids.len() != GUARD_REGISTRY.len() {
        violations.push("GUARD_REGISTRY carries a duplicate GuardSpec id".to_string());
    }
    let all_ids: BTreeSet<GuardId> = GUARD_ID_ALL.iter().copied().collect();
    if all_ids.len() != GUARD_ID_ALL.len() {
        violations.push("GUARD_ID_ALL carries a duplicate variant".to_string());
    }
    if unique_spec_ids != all_ids {
        violations.push(format!(
            "GUARD_REGISTRY ids must equal the GuardId variant set exactly; \
             spec-only={:?} variant-only={:?}",
            unique_spec_ids.difference(&all_ids).collect::<Vec<_>>(),
            all_ids.difference(&unique_spec_ids).collect::<Vec<_>>(),
        ));
    }

    let mut required_anywhere: BTreeSet<GuardId> = BTreeSet::new();
    for block in TYPEINFO_PARITY_BLOCKS {
        if block.required_guards.is_empty() {
            violations.push(format!(
                "{:?}: empty `required_guards` — a block contract must name at \
                 least the guard(s) that gate its landing",
                block.block_id,
            ));
        }
        if block.verification_labels.is_empty() {
            violations.push(format!(
                "{:?}: empty `verification_labels` — a block contract must name \
                 the verification commands it runs",
                block.block_id,
            ));
        }
        let unique: BTreeSet<GuardId> = block.required_guards.iter().copied().collect();
        if unique.len() != block.required_guards.len() {
            violations.push(format!(
                "{:?}: duplicate required guard(s) — each GuardId must appear once",
                block.block_id,
            ));
        }
        required_anywhere.extend(block.required_guards.iter().copied());
        for l in block.verification_labels {
            if l.trim().len() < MIN_LABEL_LENGTH {
                violations.push(format!(
                    "{:?}: verification label {l:?} is empty / too short",
                    block.block_id,
                ));
            }
        }
        let unique_labels: BTreeSet<&str> = block.verification_labels.iter().copied().collect();
        if unique_labels.len() != block.verification_labels.len() {
            violations.push(format!(
                "{:?}: duplicate verification label(s) — each label must appear once",
                block.block_id,
            ));
        }
    }

    // No dead obligations: every registry entry is required somewhere.
    let dead: Vec<GuardId> = all_ids.difference(&required_anywhere).copied().collect();
    if !dead.is_empty() {
        violations.push(format!(
            "guard registry entries required by NO block contract: {dead:?}",
        ));
    }

    // Amendment discipline: contract changes exist only as recorded
    // amendments — a `Replaced` amendment names a registered replacement
    // GuardId, `Removed`/`Added` carry none, every amendment names a real
    // block and a non-empty authority, and an `Added` amendment's guard is
    // a registered requirement on that block (the generator enforces the
    // label↔registry closure at emission time).
    for amendment in CONTRACT_AMENDMENTS {
        if !known_blocks_for_amendments().contains(&amendment.block_id) {
            violations.push(format!(
                "amendment for {:?} names a block outside TYPEINFO_PARITY_BLOCKS",
                amendment.guard_label,
            ));
        }
        if amendment.authority.trim().len() < MIN_LABEL_LENGTH {
            violations.push(format!(
                "amendment for {:?} carries an empty/too-short authority",
                amendment.guard_label,
            ));
        }
        match amendment.action {
            AmendmentAction::Replaced => {
                let Some(replacement) = amendment.replacement else {
                    violations.push(format!(
                        "Replaced amendment for {:?} names no replacement GuardId",
                        amendment.guard_label,
                    ));
                    continue;
                };
                if !GUARD_REGISTRY.iter().any(|s| s.id == replacement) {
                    violations.push(format!(
                        "Replaced amendment for {:?} names unregistered \
                         replacement {replacement:?}",
                        amendment.guard_label,
                    ));
                }
            }
            AmendmentAction::Removed | AmendmentAction::Added => {
                if amendment.replacement.is_some() {
                    violations.push(format!(
                        "{:?} amendment for {:?} must not carry a replacement",
                        amendment.action, amendment.guard_label,
                    ));
                }
            }
        }
    }
    // Every registry owner is a real DAG block.
    let known_blocks: BTreeSet<TypeInfoParityBlockId> =
        TYPEINFO_PARITY_BLOCKS.iter().map(|b| b.block_id).collect();
    for spec in GUARD_REGISTRY {
        if !known_blocks.contains(&spec.owner) {
            violations.push(format!(
                "GuardSpec {:?} owner {:?} is not a block in TYPEINFO_PARITY_BLOCKS",
                spec.id, spec.owner,
            ));
        }
    }

    assert!(
        violations.is_empty(),
        "block contract metadata incomplete ({} violation(s)):\n  {}",
        violations.len(),
        violations.join("\n  "),
    );
}

