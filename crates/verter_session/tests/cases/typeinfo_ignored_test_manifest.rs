/// ENGINE (§11.10): zero-row blocks (derived from the LIVE row table, not
/// a hand list) land exactly once — `Landed` ⇔ exactly one transaction;
/// any other status ⇔ zero. Re-selection/duplication is the duplicate-
/// transaction arm of the shared transaction engine.
fn zero_row_landing_violations(
    blocks: &[BlockContractRow],
    rows: &[IgnoredTestRow],
    transactions: &[LandingTransaction],
) -> Vec<String> {
    let row_owning: BTreeSet<TypeInfoParityBlockId> = rows.iter().map(|r| r.block_id).collect();
    let mut failures = Vec::new();
    for block in blocks {
        if row_owning.contains(&block.block_id) {
            continue;
        }
        let tx_count = transactions
            .iter()
            .filter(|t| t.block_id == block.block_id)
            .count();
        let expected = usize::from(matches!(block.status, BlockLandingStatus::Landed));
        if tx_count != expected {
            failures.push(format!(
                "zero-row block {:?} (status {:?}) has {tx_count} landing \
                 transaction(s); exactly {expected} required — a zero-row \
                 block lands exactly once, through one trailer-carrying \
                 squash commit, and is never re-selected",
                block.block_id, block.status,
            ));
        }
    }
    failures
}

