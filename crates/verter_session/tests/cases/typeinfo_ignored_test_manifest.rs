/// Lifecycle status of a row-registry identity. There is no tracked
/// `Verifying` transient; the in-flight state is the block's unmerged
/// branch.
///
/// - `Ignored` — the test carries a live `#[ignore = "..."]`.
/// - `RunningUnratified` — the test runs in the default suite (no live
///   `#[ignore]`) but the programme obligation is NOT yet ratified
///   `Lifted`; a test becoming always-running is a status transition, not
///   permission to erase the registry identity.
/// - `Lifted` — oracle-backed lift ratified through the lifted-row proof
///   rail.
/// - `SupersededBy` — identity preserved; a NAMED equivalent-or-stronger
///   successor row carries the obligation.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
#[allow(dead_code)]
enum IgnoreStatus {
    Ignored,
    RunningUnratified {
        block_id: TypeInfoParityBlockId,
    },
    Lifted {
        block_id: TypeInfoParityBlockId,
    },
    SupersededBy {
        successor_file: &'static str,
        successor_function: &'static str,
    },
}

/// The executable proof a row resolves to. There is NO
