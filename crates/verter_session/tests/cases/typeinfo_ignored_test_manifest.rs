/// ENGINE (§11.9): parent U-block done-ness is DERIVED-ONLY — a parent is
/// done iff it has at least one child block, EVERY child block is
/// `Landed`, and every row in the union of child rows is discharged
/// (`Lifted` / `SupersededBy`). Never row-vacuously.
fn parent_u_block_is_done(
    parent: UBlock,
    blocks: &[BlockContractRow],
    rows: &[IgnoredTestRow],
) -> bool {
    let children: Vec<&BlockContractRow> = blocks
        .iter()
        .filter(|b| b.owning_u_block == parent)
        .collect();
    if children.is_empty() {
        return false;
    }
    let all_children_landed = children
        .iter()
        .all(|b| matches!(b.status, BlockLandingStatus::Landed));
    let union_discharged = rows.iter().filter(|r| r.owning_u_block == parent).all(|r| {
        matches!(
            r.status,
            IgnoreStatus::Lifted { .. } | IgnoreStatus::SupersededBy { .. }
        )
    });
    all_children_landed && union_discharged
}

/// The UNSOUND rows-only predicate §11.9 forbids: "every row in the
/// parent's union is Lifted" — vacuously true for a zero-row parent.
/// Kept ONLY as the discrimination counter-model for
/// `no_vacuous_parent_u_block_landing`; no production predicate reads it.
fn parent_u_block_rows_only_predicate(parent: UBlock, rows: &[IgnoredTestRow]) -> bool {
    rows.iter().filter(|r| r.owning_u_block == parent).all(|r| {
        matches!(
            r.status,
            IgnoreStatus::Lifted { .. } | IgnoreStatus::SupersededBy { .. }
        )
    })
}

/// §11.9: a parent U-block token is never vacuously satisfiable. Parent
/// done-ness is derived-only (no parent status is stored anywhere — the
/// contract table holds child blocks only), and the derived predicate
/// requires child-block landing evidence: every parent the derived
/// predicate reports done must consist entirely of `Landed` children,
/// each backed by a landing transaction. The constructed counter-model
/// proves the derived predicate is NOT the rows-only vacuous one.
#[test]
fn no_vacuous_parent_u_block_landing() {
    let parents: BTreeSet<UBlock> = TYPEINFO_PARITY_BLOCKS
        .iter()
        .map(|b| b.owning_u_block)
        .collect();
    let tx_blocks: BTreeSet<TypeInfoParityBlockId> =
        LANDING_TRANSACTIONS.iter().map(|t| t.block_id).collect();
    let mut failures: Vec<String> = Vec::new();
    for parent in &parents {
        if parent_u_block_is_done(*parent, TYPEINFO_PARITY_BLOCKS, EXPECTED_IGNORE_MANIFEST) {
            for child in TYPEINFO_PARITY_BLOCKS
                .iter()
                .filter(|b| b.owning_u_block == *parent)
            {
                if !matches!(child.status, BlockLandingStatus::Landed) {
                    failures.push(format!(
                        "parent {parent:?} derives done but child {:?} is {:?}",
                        child.block_id, child.status,
                    ));
                }
                if !tx_blocks.contains(&child.block_id) {
                    failures.push(format!(
                        "parent {parent:?} derives done but child {:?} has no \
                         recorded landing transaction",
                        child.block_id,
                    ));
                }
            }
        }
    }
    assert!(
        failures.is_empty(),
        "vacuous / unevidenced parent landing derivations ({}):\n  {}",
        failures.len(),
        failures.join("\n  "),
    );

    // Counter-model: a parent with ONE Pending zero-row child. The
    // rows-only predicate is vacuously satisfied; the derived predicate
    // must NOT be. If both agreed, the engine would be the unsound one.
    let mut child = TYPEINFO_PARITY_BLOCKS[0];
    child.status = BlockLandingStatus::Pending;
    let constructed = [child];
    let parent = child.owning_u_block;
    let no_rows: [IgnoredTestRow; 0] = [];
    assert!(
        parent_u_block_rows_only_predicate(parent, &no_rows),
        "counter-model setup: the rows-only predicate must be vacuously true",
    );
    assert!(
        !parent_u_block_is_done(parent, &constructed, &no_rows),
        "the derived parent predicate must NOT report a zero-row parent with \
         a Pending child as done — that is exactly the vacuous landing §11.9 \
         forbids",
    );
}

/// ENGINE (§11.10 + §11.11): landing transactions are atomic, unique,
/// and status-coupled — exactly one transaction per `Landed` block (any
/// block class), zero for every other status.
fn landing_transaction_violations(
    blocks: &[BlockContractRow],
    transactions: &[LandingTransaction],
) -> Vec<String> {
    let mut failures = Vec::new();
    let mut seen: BTreeSet<TypeInfoParityBlockId> = BTreeSet::new();
    for tx in transactions {
        if !seen.insert(tx.block_id) {
            failures.push(format!(
                "block {:?} has more than one landing transaction",
                tx.block_id,
            ));
        }
    }
    let known: BTreeSet<TypeInfoParityBlockId> = blocks.iter().map(|b| b.block_id).collect();
    for tx in transactions {
        if !known.contains(&tx.block_id) {
            failures.push(format!(
                "landing transaction names unknown block {:?}",
                tx.block_id,
            ));
        }
        if tx.commit.len() < 7 || !tx.commit.chars().all(|c| c.is_ascii_hexdigit()) {
            failures.push(format!(
                "landing transaction for {:?} carries malformed commit {:?}",
                tx.block_id, tx.commit,
            ));
        }
    }
    for block in blocks {
        let tx_count = transactions
            .iter()
            .filter(|t| t.block_id == block.block_id)
            .count();
        match block.status {
            BlockLandingStatus::Landed => {
                if tx_count != 1 {
                    failures.push(format!(
                        "{:?} is Landed but has {tx_count} landing transaction(s) \
                         (exactly one squash-merge commit with the \
                         `Typeinfo-Block:` trailer is required)",
                        block.block_id,
                    ));
                }
            }
            BlockLandingStatus::Pending
            | BlockLandingStatus::LandingUnverified
            | BlockLandingStatus::ImplementedUnlandedRebaseRequired => {
                if tx_count != 0 {
                    failures.push(format!(
                        "{:?} is {:?} but has {tx_count} landing transaction(s) — \
                         a transaction is minted only at a ratified landing",
                        block.block_id, block.status,
                    ));
                }
            }
        }
    }
    // A LandingUnverified block must carry recorded reconciliation
    // evidence (the historical record that put it in that state).
    let evidenced: BTreeSet<TypeInfoParityBlockId> =
        BLOCK_STATUS_EVIDENCE.iter().map(|e| e.block_id).collect();
    for block in blocks {
        if matches!(block.status, BlockLandingStatus::LandingUnverified)
            && !evidenced.contains(&block.block_id)
        {
            failures.push(format!(
                "{:?} is LandingUnverified with NO recorded reconciliation \
                 evidence",
                block.block_id,
            ));
        }
    }
    failures
}

/// Locate a runnable `git` on `PATH` (mirrors the node lookup in the
/// manifest freshness guard). `None` ⇒ the git-backed checks skip
/// gracefully.
fn locate_git() -> Option<PathBuf> {
    let path = std::env::var_os("PATH")?;
    for dir in std::env::split_paths(&path) {
        let base = dir.join("git");
        if base.is_file() {
            return Some(base);
        }
        if cfg!(windows) {
            for ext in ["exe", "bat", "cmd"] {
                let candidate = base.with_extension(ext);
                if candidate.is_file() {
                    return Some(candidate);
                }
            }
        }
    }
    None
}

/// The landing-transaction check: transactions are atomic, unique,
/// status-coupled (engine above) AND — when git is available — each
/// recorded transaction commit exists in history, is an ancestor of
/// `HEAD`, and its message carries the block's `Typeinfo-Block:` trailer.
/// Trailers are enforced prospectively: no historical landing has one,
/// which is exactly why no block may currently hold `Landed`.
#[test]
fn typeinfo_block_landing_transactions_are_atomic_and_trailer_backed() {
    let failures = landing_transaction_violations(TYPEINFO_PARITY_BLOCKS, LANDING_TRANSACTIONS);
    assert!(
        failures.is_empty(),
        "landing-transaction violations ({}):\n  {}",
        failures.len(),
        failures.join("\n  "),
    );

    if LANDING_TRANSACTIONS.is_empty() {
        return;
    }
    let Some(git) = locate_git() else {
        eprintln!("skipping trailer verification: no `git` on PATH");
        return;
    };
    let root = workspace_root();
    for tx in LANDING_TRANSACTIONS {
        let message = std::process::Command::new(&git)
            .args(["log", "-1", "--format=%B", tx.commit])
            .current_dir(&root)
            .output();
        let Ok(out) = message else {
            eprintln!("skipping trailer verification: git invocation failed");
            return;
        };
        assert!(
            out.status.success(),
            "landing transaction for {:?} names commit {} which git cannot resolve",
            tx.block_id,
            tx.commit,
        );
        let body = String::from_utf8_lossy(&out.stdout);
        let trailer = format!("Typeinfo-Block: {}", block_trailer_token(tx.block_id));
        assert!(
            body.lines().any(|l| l.trim() == trailer),
            "commit {} for {:?} lacks the `{trailer}` trailer",
            tx.commit,
            tx.block_id,
        );
        let ancestor = std::process::Command::new(&git)
            .args(["merge-base", "--is-ancestor", tx.commit, "HEAD"])
            .current_dir(&root)
            .status();
        if let Ok(status) = ancestor {
            assert!(
                status.success(),
                "landing-transaction commit {} for {:?} is not an ancestor of HEAD",
                tx.commit,
                tx.block_id,
            );
        }
    }
}

