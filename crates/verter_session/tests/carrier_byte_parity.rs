// ── Case 1 — style `v-bind` feeding carrier bytes (THE load-bearing case) ──

/// `accent` is referenced NOWHERE except a `<style> v-bind(accent)`, yet it must
/// stay LIVE: its value-read entry appears in the generated `shallowUnwrapRef`
/// object + the destructure (host side `virtual_file_pipeline.rs` builds
/// `style_v_bind_vars`; codegen side `ide/script/setup.rs` gates omission on
/// usage). Because the carrier is acquired THROUGH the host here, the host's
/// `style_v_bind_vars` extraction is exercised end-to-end: if style-v-bind liveness
/// tracking regresses, `accent` is dropped from the carrier and these bytes vanish
/// -> the golden flips RED. This is the case a later Batch/`--api` block will try to
/// mutate; the golden is tight enough that dropping `accent`'s entry breaks it.
#[test]
fn style_v_bind_ide_carrier_matches_golden() {
    let code = norm(&ide_tsx(
        &[("/proj/Accent.vue", STYLE_V_BIND, FileLanguage::vue())],
        "/proj/Accent.vue",
    ));
    let golden = norm(include_str!("carrier_byte_parity/style_v_bind.tsx.golden"));
    assert_eq!(
        code, golden,
        "style-v-bind IDE carrier drifted from the golden. If intentional, regenerate \
         tests/carrier_byte_parity/style_v_bind.tsx.golden.\n--- ACTUAL ---\n{code}"
    );
    // Explicit liveness pin: the load-bearing bytes that keep a style-only `accent`
    // live. A regression that drops style-v-bind tracking removes exactly these.
    assert!(
        code.contains("accent: accent as unknown as typeof accent"),
        "REGRESSION: style-only `accent` lost its `shallowUnwrapRef` value-read entry \
         (style-v-bind liveness dropped)\n--- ACTUAL ---\n{code}"
    );
    assert!(
        code.contains("accent } = ___VERTER___unwrapped"),
        "REGRESSION: style-only `accent` lost its destructure binding\n--- ACTUAL ---\n{code}"
    );
}

