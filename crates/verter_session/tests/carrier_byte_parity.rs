//! PERF-0 Rail A — carrier-byte parity characterization (hermetic, deterministic).
//!
//! Pins the CURRENT ("Full-mode", `HostConfig::default()`) carrier bytes for the
//! two carrier surfaces the verter-tsc / LSP pipeline ships to tsgo:
//!   - the IDE TSX carrier (`.vue.tsx`), produced THROUGH `VerterHost`'s shared
//!     IDE-carrier path (`ensure_ide_compiled` + `get_ide`) — the EXACT path the
//!     LSP ships to tsgo (`crates/verter_lsp/src/background_init.rs` `get_ide`);
//!     NOT a direct `verter_compiler::compile()` call (which would bypass the host
//!     and silently miss a host-side Batch regression); and
//!   - the public-API stub (`.vue.verter.ts`), generated by
//!     `VerterHost::get_public_api` — the cross-component surface tsgo resolves
//!     sibling `.vue` imports against.
//!
//! WHY THIS EXISTS (the parity oracle): the perf campaign (see
//! `docs/arch/host-mode-perf-design.md`) will add a Batch `HostConfig` preset, a
//! stateless `BareCompiler`, and swap verter-tsc's checker backend to an
//! in-memory tsgo `--api` client. The codex ruling (§3, "Full <-> Batch — SAME
//! carrier bytes") requires every one of those changes to be PROVABLY
//! byte-identical on the carrier surface. These goldens are that proof: any later
//! block that drifts a carrier byte fails here, fail-before / pass-after. Because
//! the IDE carrier is acquired THROUGH the host (not a direct `compile()`), a
//! host-side regression — e.g. dropping the style-`v-bind` extraction the host
//! feeds into codegen — flips the golden, which a direct-`compile()` oracle could
//! not catch.
//!
//! DISCRIMINATING: each test pins the COMPLETE carrier bytes of one case against a
//! committed golden, so ANY change (a dropped binding, a reordered member, a
//! renamed helper) flips it RED. The goldens were produced by the current codegen
//! itself; they are not hand-authored. Line endings are normalized (CRLF -> LF) on
//! BOTH sides so a CRLF checkout of a golden cannot spuriously fail the byte
//! comparison (cross-platform portability rule). Canonical IDs are STABLE
//! forward-slash paths (`/proj/Foo.vue`) so the bytes — including the stub's inline
//! base64 source map, whose `sources` is the canonical ID — embed no
//! machine-specific absolute path and reproduce on macOS / Windows / Linux.

use std::sync::Arc;

use verter_session::{
    CompileProfile, CompileTarget, FileLanguage, HostConfig, UpsertRequest, VerterHost,
};

// ── Carrier generation helpers (mirror the LSP / verter-tsc carrier paths) ──

/// IDE TSX carrier bytes — produced THROUGH `VerterHost`'s shared IDE-carrier path
/// (`ensure_ide_compiled` + `get_ide`), the EXACT path the LSP ships to tsgo
/// (`crates/verter_lsp/src/background_init.rs` calls `host.get_ide(..)`), NOT a
/// direct `verter_compiler::compile()` call. Routing through the host is what lets
/// this oracle guard the future Batch (`HostConfig::batch_typecheck()`) / Bare seam
/// and exercise the host-side style-`v-bind` extraction
/// (`virtual_file_pipeline.rs`), whose facts the host feeds into codegen under its
/// analysis scope — a direct `compile()` call cannot see a host-side regression.
///
/// `files` are upserted into one host (stable canonical IDs); the IDE carrier for
/// `target` is then ensured + read. `get_ide` returns `None` only when the file is
/// not a resolvable carrier — a panic here is a real regression, not flake.
///
/// Defaults to the Full / `HostConfig::default()` preset (the golden baseline).
fn ide_tsx(files: &[(&str, &str, FileLanguage)], target: &str) -> String {
    ide_tsx_with(HostConfig::default(), files, target)
}

/// `ide_tsx` parametrised on the host preset, so the Full-vs-Batch parity test can
/// build the SAME carrier under `HostConfig::batch_typecheck()` and byte-compare it
/// against the `lsp_interactive()` (= default / golden) output.
fn ide_tsx_with(config: HostConfig, files: &[(&str, &str, FileLanguage)], target: &str) -> String {
    let host = VerterHost::new_standalone(config);
    for (canonical, source, lang) in files {
        let _ = host.upsert(UpsertRequest {
            canonical_id: Some((*canonical).to_string()),
            input_id: (*canonical).to_string(),
            source: Arc::<str>::from(*source),
            file_language: lang.clone(),
            aliases: Vec::new(),
        });
    }
    // The IDE/LSP carrier profile: the TSX surface tsgo type-checks
    // (`CompileTarget::IDE == TSX`). `source_map: true` matches the LSP `tsx_profile`
    // and verter-tsc's `generate_all_tsx`. The host normalizes the profile to add
    // the TSX bit internally, so `ensure_ide_compiled` populates exactly the slot
    // `get_ide` peeks.
    let profile = CompileProfile {
        source_map: true,
        target: CompileTarget::IDE,
        ..CompileProfile::default()
    };
    // Oracle extension points (the seams this pins): PERF-1 adds a parallel
    // assertion building this same carrier under HostConfig::batch_typecheck() and
    // asserting byte-equality vs this Full/default golden; PERF-4 adds BareCompiler
    // carrier parity for the single-file-applicable cases.
    host.ensure_ide_compiled(target, &profile)
        .unwrap_or_else(|e| panic!("ensure_ide_compiled failed for {target}: {e:?}"));
    host.get_ide(target, &profile)
        .unwrap_or_else(|| panic!("get_ide returned None for {target}"))
        .code
        .to_string()
}

/// Public-API stub bytes — mirrors the verter-tsc stub stage
/// (`crates/verter_tsc/src/checker.rs:269` upsert idiom + `get_public_api`).
/// `files` are upserted into one host (stable canonical IDs); the stub for
/// `target` is then read. `get_public_api` returns `None` only when the file is
/// not a resolvable carrier — a panic here is a real regression, not flake.
///
/// Defaults to the Full / `HostConfig::default()` preset (the golden baseline).
fn public_api_stub(files: &[(&str, &str, FileLanguage)], target: &str) -> String {
    public_api_stub_with(HostConfig::default(), files, target)
}

/// `public_api_stub` parametrised on the host preset, for the Full-vs-Batch parity
/// test (same cross-component stub under `batch_typecheck()` vs `lsp_interactive()`).
fn public_api_stub_with(
    config: HostConfig,
    files: &[(&str, &str, FileLanguage)],
    target: &str,
) -> String {
    let host = VerterHost::new_standalone(config);
    for (canonical, source, lang) in files {
        let _ = host.upsert(UpsertRequest {
            canonical_id: Some((*canonical).to_string()),
            input_id: (*canonical).to_string(),
            source: Arc::<str>::from(*source),
            file_language: lang.clone(),
            aliases: Vec::new(),
        });
    }
    host.get_public_api(target)
        .unwrap_or_else(|| panic!("get_public_api returned None for {target}"))
        .code
        .to_string()
}

/// CRLF -> LF normalization (cross-platform byte-comparison rule).
///
/// Normalizing (rather than asserting raw CRLF bytes) is MANDATED by the
/// "Cross-Platform Portability (CRITICAL)" rule: byte-equality comparisons over
/// checked-out text must normalize line endings (CRLF<->LF) or compare as text,
/// never raw bytes embedding EOL. `.gitattributes` pins `*.golden eol=lf`; this
/// normalizes BOTH sides so a CRLF checkout of a golden cannot spuriously fail.
fn norm(s: &str) -> String {
    s.replace("\r\n", "\n")
}

