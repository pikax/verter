//! Architecture guards for the typeinfo wire surface.
//!
//! The wire-side of the typeinfo graph substrate is protobuf-
//! authoritative: Rust DTOs are generated from `.proto` via
//! `prost-build`; TypeScript DTOs are generated from the same
//! `.proto` via the existing protobuf-ts pipeline. `ts-rs` derives
//! are reserved for the audit envelope under `crates/verter_audit`
//! and MUST NOT appear on wire-side typeinfo DTOs. These guards
//! detect a regression where a future contributor reintroduces
//! `ts-rs` on the typeinfo wire-side or hand-edits the generated
//! TypeScript artifact.
//!
//! Discriminating shape: each guard scans a specific source surface
//! and asserts a structural property. Pre-substrate the surfaces do
//! not exist (the typeinfo proto file is the legacy 5-DTO schema,
//! the Rust submodule does not exist) and the scans fail. Post-
//! substrate the scans pass.

use std::path::PathBuf;

fn workspace_root() -> PathBuf {
    let crate_root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    crate_root
        .parent()
        .and_then(|p| p.parent())
        .expect("CARGO_MANIFEST_DIR must be `<workspace>/crates/verter_session`")
        .to_path_buf()
}

fn read_workspace_file(rel: &str) -> String {
    let path = workspace_root().join(rel);
    std::fs::read_to_string(&path).unwrap_or_else(|err| {
        panic!(
            "guard requires `{}` to exist and be readable: {err}",
            path.display()
        )
    })
}

#[test]
fn typeinfo_wire_dtos_are_proto_authoritative_with_no_ts_rs_derive() {
    let graph = read_workspace_file("crates/verter_protocol/src/typeinfo/graph.rs");
    // The Rust-side wire surface is a re-export module — every DTO
    // type is `pub use wire::...`, NOT a hand-rolled struct with
    // ts-rs derives.
    assert!(
        !graph.contains("ts_rs::TS"),
        "guard: typeinfo wire DTOs MUST NOT carry `ts_rs::TS` derives — \
         the wire surface is protobuf-authoritative",
    );
    assert!(
        !graph.contains("#[ts(export"),
        "guard: typeinfo wire DTOs MUST NOT carry `#[ts(export, ...)]` \
         attributes — `ts-rs` is reserved for the audit envelope",
    );
    // Sanity: the file actually re-exports from the generated module.
    assert!(
        graph.contains("use crate::verter::v1 as wire;"),
        "guard: typeinfo graph submodule must re-export from the prost-generated `wire` module",
    );
}

