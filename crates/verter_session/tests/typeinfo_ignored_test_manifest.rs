/// One block-contract row. Pins the block prerequisite
/// DAG (`prereqs`) + the block's dominant `mechanism_id` and
/// `consumed_mechanisms`, plus the contract metadata the parent requires:
/// the `required_guards` the block must carry green before it lands and
/// the `verification_labels` (verification command labels) it runs.
/// `required_guards` is the set of verbatim-named structural /
/// done-predicate guards from the block's documented "Required new
/// guards" section that are OWNED AND LANDABLE AT THIS BLOCK'S SCOPE — it
/// is NOT a claim of completeness or verbatim totality over the doc's full
/// guard list. Two scoping rules make this honest:
/// (a) A block intentionally scopes to the guards it owns at its own
///     boundary; guards a doc explicitly attributes to another owning block,
///     or that belong to a later substrate block, are forward-declared
///     elsewhere and excluded here. Concretely, `U0` scopes its
///     `required_guards` to its schema guards (its broader documented set —
///     proof / coverage / landing predicates — is owned by later blocks and
///     forward-declared there, not restated in this field), and
///     `U2.QUERY_VALUE_DOMAIN` omits the doc's ellipsized guard-name
///     prefixes that are not verbatim-copyable identifiers.
/// (b) Live existence + green is NOT enforced HERE. For a not-yet-landed
///     block these are forward declarations; the block FINALIZES and verifies
///     them live+green at landing via the deferred
///     `landed_typeinfo_blocks_have_required_guards` done-predicate (that
///     landing-enforcement guard itself lands in a later substrate block).
/// The list is authored in `scripts/gen-typeinfo-ignore-manifest.py`
/// (`BLOCK_TO_REQUIRED_GUARDS`) and regenerated into
/// `manifest_data/typeinfo_parity_blocks.rs`; row/test names and
/// doc-marked-not-landed phantom names are excluded. The
/// `every_block_contract_row_carries_required_guards` guard here pins only
/// that every block CARRIES non-empty, deduplicated labels — it does NOT
/// verify completeness against the doc, nor live existence/green.
#[derive(Clone, Copy, Debug)]
#[allow(dead_code)]
struct BlockContractRow {
    block_id: TypeInfoParityBlockId,
    owning_u_block: UBlock,
    organ: ArchitectureOrgan,
    prereqs: &'static [TypeInfoParityBlockId],
    mechanism_id: MechanismId,
    consumed_mechanisms: &'static [MechanismId],
    required_guards: &'static [&'static str],
    verification_labels: &'static [&'static str],
}

/// The single block that OWNS (produces) each `SemanticQueryName`.
/// The owner is the block whose subplan "SemanticQueryKey/facts
/// touched:" line lists the key WITH ITS VALUE DOMAIN (the PRODUCER), NOT a
/// block that lists it under "Facts read" or among "all EXISTING keys" (a
/// CONSUMER). Each owner below is cited by its STABLE subplan block heading
/// (its `SemanticQueryKey/facts touched:` producer line), NOT an absolute doc
/// line number — line numbers drift as the docs are edited, the block heading
/// does not:
/// - foundational decl/value keys (`ResolveDecl`, `TypeOf`, `NormalizeUnion`,
///   `NormalizeIntersection`, `ResolvedNamedType`) PLUS `Instantiate` at
///   `U2.QUERY_VALUE_DOMAIN` (its `Context` adds/upgrades the U2 key surface +
///   value-domain arms; generic substitution is a value-domain instantiation,
///   not a relation inference);
/// - relation / conditional at `U2.RELATION_INFER`;
/// - indexed-access / keyof / member / path at `U2.INDEXED_ACCESS`;
/// - mapped + template-literal reduction at `U2.MAPPED_TEMPLATE`;
/// - class-surface projection PLUS `ApparentType` (lib-wrapper member lookup)
///   and `ResolveOverloadSet` (ordered-signature SHAPE) at `U2.CLASS_SURFACES`
///   (its `SemanticQueryKey/facts touched:` line lists `ResolveClassSurface`,
///   `ApparentType`, `ResolveOverloadSet` with their value domains; the
