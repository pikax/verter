//! The two-table manifest ledger for typeinfo full-parity tracking.
//!
//! Two tables live in this one module:
//!
//! - `IgnoredTestRow` — EXACTLY 362 test-site rows total. 343 carry
//!   `status: Ignored` (one per live `#[ignore = "..."]` annotation inside
//!   `crates/verter_session/src/typeinfo/typeinfo_tests/**/*.rs`, bijective
//!   with the source `#[ignore]`s); the remainder carry `status: Lifted` (no
//!   live `#[ignore]`, each backed by an oracle row). The table length is
//!   count-guarded at 362; the live-ignore count is count-guarded at 343.
//!   Each row carries the full 13-column schema: `file`, `function`,
//!   `substrate`, `capability`, `organ`, `owning_u_block`, `block_id`,
//!   `semantic_queries`, `proof`, `status`, `mechanism_id`,
//!   `consumed_mechanisms`, `unblocker`.
//! - `AdditionalProofRow` — the CLOSED set of 7 coverage-only rows (the
//!   6 JSX no-new-key submatrix rows owned by `U2.JSX_FOUNDATIONS` + the
//!   1 mapped companion owned by `U2.MAPPED_TEMPLATE`). Same schema
//!   minus `status` / `unblocker`; EXCLUDED from the ignored count +
//!   bijection.
//!
//! Both tables and the `TYPEINFO_PARITY_BLOCKS` DAG are GENERATED by
//! `scripts/gen-typeinfo-ignore-manifest.py` (`pnpm gen:typeinfo-manifest`).
//! The authoritative row→block partition is the source ONLY for
//! each `IgnoredTestRow`'s `block_id`: the generator PARSES it
//! (`parse_partition`) and joins it with the live `#[ignore]` discovery +
//! the Capability Map to emit `typeinfo_ignored_test_manifest_rows.rs`. The
//! `AdditionalProofRow` table and the `TYPEINFO_PARITY_BLOCKS` DAG (each
//! block's `required_guards`/`verification_labels`/prereqs/mechanisms) are
//! authored in the generator's own Python maps (`build_additional_rows` /
//! `JSX_NO_NEW_KEY_ROWS`; `emit_block_rows`, `BLOCK_TO_REQUIRED_GUARDS`,
//! `BLOCK_VERIFICATION_LABELS`, the prereq/mechanism maps), NOT from the
//! partition. The guards below only diff/fail — they never write the
//! generated source (repo rule: generators are scripts, not tests).
//!
//! `EXPECTED_TOTAL_IGNORED_COUNT` is DERIVED as
//! `count(IgnoredTestRow where status == Ignored)`, not a
//! frozen literal; it tracks the live ignore set as blocks lift rows
//! (and as same-file overload retention adds new ones) and currently
//! resolves to 343 (362 rows total − 19 lifted).
//!
//! Guards:
//!
//! Carried-forward bijection / quality guards
//! (`every_ignored_typeinfo_test_has_a_manifest_row`,
//! `every_manifest_row_corresponds_to_a_live_ignored_test`,
//! `every_manifest_row_lists_a_valid_substrate`,
//! `every_manifest_row_has_non_empty_unblocker`,
//! `every_manifest_row_unblocker_matches_live_ignore_reason`,
//! `per_file_ignored_test_counts_match_manifest`,
//! `total_ignored_typeinfo_test_count_matches_expected`,
//! `manifest_length_matches_documented_total`,
//! `every_ignored_typeinfo_test_carries_a_reason_string`,
//! `every_ignore_reason_meets_minimum_quality_bar`) plus the
//! two-table manifest guards:
//!
//! - `ignored_test_row_table_holds_exactly_362_rows` (binding total +
//!   disjointness vs `AdditionalProofRow`),
//! - `additional_proof_row_table_holds_exactly_7_rows` (closed set),
//! - `typeinfo_parity_block_dag_is_acyclic_and_consumed_keys_and_mechanisms_are_prereqs`
//!   (block-DAG acyclicity + consumed-key + consumed-mechanism
//!   prerequisite consistency).

