/// The block prerequisite DAG is acyclic AND every consumed
/// key / mechanism's owning block is the consuming block itself or a
/// transitive prerequisite of it. Models BOTH the semantic-query-key
/// owner edges AND the block-mechanism dependencies.
///
/// Five checks:
/// 1. Block DAG acyclic.
/// 2. Every row's dominant `mechanism_id` is owned by its own
///    `block_id`.
/// 3. Every consumed mechanism's owner is itself or a transitive
///    prerequisite.
/// 4. Every consumed key's owner is itself or a transitive
///    prerequisite.
/// 5. Diagnostic on failure.
#[test]
fn typeinfo_parity_block_dag_is_acyclic_and_consumed_keys_and_mechanisms_are_prereqs() {
    use std::collections::BTreeMap as Map;

    // Build the prereq adjacency from TYPEINFO_PARITY_BLOCKS.
    let prereqs = build_prereq_map();

    // No duplicate `block_id` rows in the contract table.
    assert_eq!(
        prereqs.len(),
        TYPEINFO_PARITY_BLOCKS.len(),
        "TYPEINFO_PARITY_BLOCKS must hold one row per block_id (no \
         duplicate block_id rows)",
    );

    // ── Check 0: every block REFERENCED anywhere must have a
    //    `BlockContractRow`. A referenced-but-missing block is NOT a
    //    leaf — deleting a referenced contract row (e.g. one that another
    //    block lists in `prereqs`, or that owns a consumed key /
    //    mechanism, or that a row's `block_id` / `owning_u_block` names)
    //    must FAIL the guard, not pass silently. We collect every
    //    referenced `TypeInfoParityBlockId` and assert each has a row.
    let contract_blocks: BTreeSet<TypeInfoParityBlockId> =
        TYPEINFO_PARITY_BLOCKS.iter().map(|b| b.block_id).collect();
    let mut referenced: BTreeSet<TypeInfoParityBlockId> = BTreeSet::new();
    for b in TYPEINFO_PARITY_BLOCKS {
        referenced.insert(b.block_id);
        for &p in b.prereqs {
            referenced.insert(p);
        }
        referenced.insert(mechanism_owning_block(b.mechanism_id));
        for &m in b.consumed_mechanisms {
            referenced.insert(mechanism_owning_block(m));
        }
    }
    for row in EXPECTED_IGNORE_MANIFEST {
        referenced.insert(row.block_id);
        referenced.insert(mechanism_owning_block(row.mechanism_id));
        for &m in row.consumed_mechanisms {
            referenced.insert(mechanism_owning_block(m));
        }
        for &k in row.semantic_queries {
            referenced.insert(key_owning_block(k));
        }
    }
    for row in ADDITIONAL_PROOF_ROWS {
        referenced.insert(row.block_id);
        referenced.insert(mechanism_owning_block(row.mechanism_id));
        for &m in row.consumed_mechanisms {
            referenced.insert(mechanism_owning_block(m));
        }
        for &k in row.semantic_queries {
            referenced.insert(key_owning_block(k));
        }
    }
    let missing_contract: Vec<TypeInfoParityBlockId> =
        referenced.difference(&contract_blocks).copied().collect();
    assert!(
        missing_contract.is_empty(),
        "block-DAG: {} block(s) are REFERENCED (by a prereq edge, a \
         key/mechanism owner, or a row's block_id / owning_u_block) but \
         have NO `BlockContractRow` — a referenced block is not a leaf, it \
         is a missing contract. Deleting a referenced contract row \
         must fail here. Missing: {:?} (check 0)",
        missing_contract.len(),
        missing_contract,
    );

    // ── Check 1: acyclicity (DFS three-colour). ──
    #[derive(Clone, Copy, PartialEq)]
    enum Color {
        White,
        Gray,
        Black,
    }
    fn visit(
        node: TypeInfoParityBlockId,
        prereqs: &Map<TypeInfoParityBlockId, Vec<TypeInfoParityBlockId>>,
        color: &mut Map<TypeInfoParityBlockId, Color>,
        stack: &mut Vec<TypeInfoParityBlockId>,
    ) -> Result<(), Vec<TypeInfoParityBlockId>> {
        color.insert(node, Color::Gray);
        stack.push(node);
        if let Some(edges) = prereqs.get(&node) {
            for &dep in edges {
                match color.get(&dep).copied().unwrap_or(Color::White) {
                    Color::Gray => {
                        let mut cyc = stack.clone();
                        cyc.push(dep);
                        return Err(cyc);
                    }
                    Color::White => visit(dep, prereqs, color, stack)?,
                    Color::Black => {}
                }
            }
        }
        stack.pop();
        color.insert(node, Color::Black);
        Ok(())
    }
    let mut color: Map<TypeInfoParityBlockId, Color> = Map::new();
    for &b in prereqs.keys() {
        if color.get(&b).copied().unwrap_or(Color::White) == Color::White {
            let mut stack = Vec::new();
            if let Err(cyc) = visit(b, &prereqs, &mut color, &mut stack) {
                panic!("block prerequisite DAG has a CYCLE: {:?} (check 1)", cyc);
            }
        }
    }

    // ── Checks 2-4 over every IgnoredTestRow + AdditionalProofRow +
    //    BlockContractRow, via the shared `dag_row_consistency_failures`
    //    engine (the same engine the discrimination tests drive). ──
    let mut failures: Vec<String> = Vec::new();

    for row in EXPECTED_IGNORE_MANIFEST {
        let what = format!("IgnoredTestRow {}::{}", row.file, row.function);
        failures.extend(dag_row_consistency_failures(
            &what,
            row.block_id,
            row.mechanism_id,
            row.consumed_mechanisms,
            row.semantic_queries,
            &prereqs,
        ));
    }
    for row in ADDITIONAL_PROOF_ROWS {
        let what = format!("AdditionalProofRow {}::{}", row.file, row.function);
        failures.extend(dag_row_consistency_failures(
            &what,
            row.block_id,
            row.mechanism_id,
            row.consumed_mechanisms,
            row.semantic_queries,
            &prereqs,
        ));
    }
    for block in TYPEINFO_PARITY_BLOCKS {
        let what = format!("BlockContractRow {:?}", block.block_id);
        // Block-level dominant + consumed mechanisms (check 2/3). Blocks
        // declare no consumed keys directly (keys ride rows).
        failures.extend(dag_row_consistency_failures(
            &what,
            block.block_id,
            block.mechanism_id,
            block.consumed_mechanisms,
            &[],
            &prereqs,
        ));
    }

    assert!(
        failures.is_empty(),
        "block-DAG / consumed-key / consumed-mechanism prerequisite \
         consistency FAILED:\n  {}",
        failures.join("\n  "),
    );
}

