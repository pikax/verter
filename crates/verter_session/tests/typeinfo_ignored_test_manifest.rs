fn row_identity(file: &'static str, function: &'static str) -> (String, String) {
    (file.to_string(), function.to_string())
}

/// Build the block prereq adjacency from `TYPEINFO_PARITY_BLOCKS`.
fn build_prereq_map() -> BTreeMap<TypeInfoParityBlockId, Vec<TypeInfoParityBlockId>> {
    TYPEINFO_PARITY_BLOCKS
        .iter()
        .map(|b| (b.block_id, b.prereqs.to_vec()))
        .collect()
}

/// Transitive-prereq closure: is `target` == `from` or a transitive
/// prerequisite of `from`?
fn reaches(
    from: TypeInfoParityBlockId,
    target: TypeInfoParityBlockId,
    prereqs: &BTreeMap<TypeInfoParityBlockId, Vec<TypeInfoParityBlockId>>,
) -> bool {
    if from == target {
        return true;
    }
    let mut seen: BTreeSet<TypeInfoParityBlockId> = BTreeSet::new();
    let mut frontier = vec![from];
    while let Some(cur) = frontier.pop() {
        if !seen.insert(cur) {
            continue;
        }
        if cur == target {
            return true;
        }
        if let Some(edges) = prereqs.get(&cur) {
            frontier.extend(edges.iter().copied());
        }
    }
    false
}

/// The per-row prerequisite-consistency checks (checks 2–4) for ONE
/// row's `(block_id, dominant mechanism, consumed mechanisms, consumed
/// keys)`. Returns the list of failure strings (empty == consistent).
///
/// This is the SHARED engine the real guard and the discrimination
/// tests both drive: the discrimination tests prove a row with a
/// deliberately-wrong `block_id` (check 2) or whose block's prereqs do
/// NOT cover its mechanism's keys (check 4) yields a non-empty failure
/// list, while the correct table yields empty.
fn dag_row_consistency_failures(
    what: &str,
    block_id: TypeInfoParityBlockId,
    dominant: MechanismId,
    consumed_mechs: &[MechanismId],
    keys: &[SemanticQueryName],
    prereqs: &BTreeMap<TypeInfoParityBlockId, Vec<TypeInfoParityBlockId>>,
) -> Vec<String> {
    let mut failures: Vec<String> = Vec::new();
    // Check 2: dominant-mechanism owner == block. The mechanism is a
    // ROW-LEVEL fact (derived from capability/`file::function`, NOT from
    // `block_id`), so this is NOT tautological: a mis-assigned `block_id`
    // whose value disagrees with `mechanism_owning_block(mechanism_id)`
    // FAILS here.
    let owner = mechanism_owning_block(dominant);
    if owner != block_id {
        failures.push(format!(
            "{what}: dominant mechanism {dominant:?} is owned by {owner:?}, \
             not the row's block {block_id:?} (check 2)"
        ));
    }
    // Check 3: every consumed mechanism's owner is itself or a prereq.
    for &m in consumed_mechs {
        let m_owner = mechanism_owning_block(m);
        if !reaches(block_id, m_owner, prereqs) {
            failures.push(format!(
                "{what}: consumes mechanism {m:?} owned by {m_owner:?}, which \
                 is NOT block {block_id:?} nor a transitive prerequisite \
                 (check 3); missing prereq edge {block_id:?} -> … -> {m_owner:?}"
            ));
        }
    }
    // Check 4: every consumed key's owner is itself or a prereq. The key
    // set is the FULL set the row's MECHANISM dispatches (no per-block
    // narrowing), so a wrong `block_id` whose prereqs do not cover the
    // mechanism's keys FAILS here.
    for &k in keys {
        let k_owner = key_owning_block(k);
        if !reaches(block_id, k_owner, prereqs) {
            failures.push(format!(
                "{what}: consumes key {k:?} owned by {k_owner:?}, which is NOT \
                 block {block_id:?} nor a transitive prerequisite (check 4); \
                 missing prereq edge {block_id:?} -> … -> {k_owner:?}"
            ));
        }
    }
    failures
}

