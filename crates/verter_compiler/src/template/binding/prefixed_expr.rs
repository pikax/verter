//! The one rewriter of template expressions: binding prefixes and suffixes
//! spliced around authored identifiers.
//!
//! Produces a [`MappedGeneratedText`] — the resolved expression string plus an
//! ordered segment plan marking which byte runs are authored source (mapped)
//! and which are resolver scaffolding (unmapped) — or, through a zero-overhead
//! [`StringSink`], the flat text alone; both walk the same OXC binding data, so
//! the runtime path and the sourcemap path can never drift in their generated
//! bytes.
//!
//! The walk reads its prefix table through [`ExprBindings`], which the legacy
//! [`BindingResolver`] and the targets' [`VueBindingView`] both answer, so
//! every renderer and the IDE route share this one rewriter. Each identifier
//! is resolved with the access its occurrence has, read from the parser's
//! [`ReferenceUse`]: a read, a `new` constructor or a write.

use super::{is_simple_ident, BindingResolver};
use crate::code_transform::{EditRecorder, MappedGeneratedText};
use crate::emission::MapMode;
use crate::framework::vue::semantic::{BindingAccess, VueBindingView};
use crate::template::oxc::types::{OxcParsedElement, OxcParsedExpression, OxcParsedVFor};
use crate::types::{BindingType, NodeProp};
use crate::utils::oxc::bindings::keywords::{is_global, is_keyword};
use crate::utils::oxc::{Binding, BindingExtractionResult, ReferenceUse};

/// The binding facts the rewriter reads: the class of a name, the prefix and
/// suffix of an identifier used with an access, and the spelling of a loop
/// or slot local.
pub(crate) trait ExprBindings {
    fn get(&self, ident: &str) -> Option<BindingType>;
    fn resolve_prefix(&self, ident: &str, access: BindingAccess) -> &'static str;
    fn resolve_suffix(&self, ident: &str, access: BindingAccess) -> &'static str;
    /// The emitted spelling of a loop or slot local that is renamed.
    fn resolve_local(&self, name: &str) -> Option<&str>;
}

/// The legacy resolver writes one text for every access (see
/// [`BindingResolver`]), so it ignores the occurrence's.
impl ExprBindings for BindingResolver<'_> {
    fn get(&self, ident: &str) -> Option<BindingType> {
        BindingResolver::get(self, ident)
    }
    fn resolve_prefix(&self, ident: &str, _access: BindingAccess) -> &'static str {
        BindingResolver::resolve_prefix(self, ident)
    }
    fn resolve_suffix(&self, ident: &str, _access: BindingAccess) -> &'static str {
        BindingResolver::resolve_suffix(self, ident)
    }
    fn resolve_local(&self, name: &str) -> Option<&str> {
        self.resolve_for_local(name)
    }
}

/// The binding view resolves each identifier with its occurrence's access:
/// inline, a read of a binding that may hold a ref goes through `_unref` and
/// a write goes through `.value`. Template locals are spelled as authored;
/// the view itself leaves the names a template scope declares bare.
impl ExprBindings for VueBindingView<'_> {
    fn get(&self, ident: &str) -> Option<BindingType> {
        VueBindingView::get(self, ident)
    }
    fn resolve_prefix(&self, ident: &str, access: BindingAccess) -> &'static str {
        self.prefix(ident, access)
    }
    fn resolve_suffix(&self, ident: &str, access: BindingAccess) -> &'static str {
        self.suffix(ident, access)
    }
    fn resolve_local(&self, _name: &str) -> Option<&str> {
        None
    }
}

/// The access an identifier occurrence has, from the parser's record of how
/// the expression uses it.
fn access_of(binding: &Binding<'_>) -> BindingAccess {
    match binding.usage {
        ReferenceUse::Read => BindingAccess::Read,
        ReferenceUse::Construct => BindingAccess::Construct,
        ReferenceUse::Write => BindingAccess::Write,
    }
}

/// Ordered destination for the resolved-expression walk.
///
/// Two implementations: [`StringSink`] (flat string, ignores positions — the
/// runtime `build_prefixed_expr` path) and [`SegmentSink`] (records a
/// [`MappedGeneratedText`] plan). Keeping one walk over two sinks guarantees the
/// flat and segmented builders produce identical generated bytes.
pub(crate) trait ExprSink {
    /// Append authored source text whose first byte is at file offset
    /// `source_start`.
    fn push_source(&mut self, text: &str, source_start: u32);
    /// Append synthetic scaffolding text (binding prefix/suffix, keyword
    /// brackets, shorthand key) that must not map to source.
    fn push_synthetic(&mut self, text: &str);
}

/// Flat-string sink: both pushes append to the buffer; source positions are
/// discarded. Keeps `build_prefixed_expr` free of any segment-plan overhead.
pub(crate) struct StringSink<'a>(pub &'a mut String);

impl ExprSink for StringSink<'_> {
    #[inline]
    fn push_source(&mut self, text: &str, _source_start: u32) {
        self.0.push_str(text);
    }
    #[inline]
    fn push_synthetic(&mut self, text: &str) {
        self.0.push_str(text);
    }
}

/// Segment-recording sink: builds the [`MappedGeneratedText`] plan.
#[derive(Default)]
struct SegmentSink {
    out: MappedGeneratedText,
}

impl ExprSink for SegmentSink {
    #[inline]
    fn push_source(&mut self, text: &str, source_start: u32) {
        self.out.push(text, Some(source_start));
    }
    #[inline]
    fn push_synthetic(&mut self, text: &str) {
        self.out.push(text, None);
    }
}

/// Build the segmented plan for a resolved (possibly compound) expression.
///
/// `.text` is byte-identical to
/// `build_prefixed_expr(expr, inner_start, oxc, resolver, ts_skip_ranges)`.
pub(crate) fn build_prefixed_expr_segments<B: ExprBindings + ?Sized>(
    expr: &str,
    inner_start: u32,
    oxc: &OxcParsedExpression<'_>,
    resolver: &B,
    ts_skip_ranges: &[(u32, u32)],
) -> MappedGeneratedText {
    let mut sink = SegmentSink::default();
    write_prefixed_expr(&mut sink, expr, inner_start, oxc, resolver, ts_skip_ranges);
    sink.out
}

/// Build the segmented plan for a simple-identifier expression with no OXC
/// binding data (the resolver-only path).
///
/// `.text` is byte-identical to `resolver.resolve_simple_expr(expr)`.
pub(crate) fn resolve_simple_expr_segments<B: ExprBindings + ?Sized>(
    resolver: &B,
    expr: &str,
    inner_start: u32,
) -> MappedGeneratedText {
    let mut sink = SegmentSink::default();
    write_simple_expr(&mut sink, resolver, expr, inner_start);
    sink.out
}

/// Build a prefixed expression string using OXC binding extraction data.
///
/// For compound expressions (e.g., `a + b.x`), walks the extracted bindings
/// and inserts the correct prefix/suffix at each identifier's position.
/// For simple identifiers, falls back to `resolve_simple_expr`.
///
/// When `ts_skip_ranges` is non-empty, skips the specified byte ranges
/// (expression-relative) from verbatim chunks. Used by `force_js` to strip
/// TypeScript syntax from directive expressions without re-parsing.
pub(crate) fn build_prefixed_expr<B: ExprBindings + ?Sized>(
    expr: &str,
    inner_start: u32,
    oxc: &OxcParsedExpression<'_>,
    resolver: &B,
    ts_skip_ranges: &[(u32, u32)],
) -> String {
    // Pre-size to the original heuristic (one prefix/suffix budget per binding)
    // so the flat path keeps its allocation profile; the shared walk discards
    // segment positions through `StringSink`, so generated bytes are identical
    // to the segmented `build_prefixed_expr_segments`.
    let extra = oxc.bindings.as_ref().map_or(0, |b| b.bindings.len() * 8);
    let mut result = String::with_capacity(expr.len() + extra);
    let mut sink = StringSink(&mut result);
    write_prefixed_expr(&mut sink, expr, inner_start, oxc, resolver, ts_skip_ranges);
    result
}

/// Look up the OXC-parsed expression data for a given prop index.
///
/// `OxcParsedProp.prop_index` maps back to `ElementNode.props[prop_index]`. This
/// is an O(1) wrapper over the element's dense `prop_lookup` table
/// ([`OxcParsedElement::prop`]) — no linear scan over the sparse `props` vec.
pub(crate) fn find_prop_oxc_exp<'a, 'alloc>(
    oxc_el: Option<&'a OxcParsedElement<'alloc>>,
    prop_index: usize,
) -> Option<&'a OxcParsedExpression<'alloc>> {
    oxc_el?.prop(prop_index).and_then(|p| p.exp.as_ref())
}

/// Resolve an expression using OXC binding data when available, falling back
/// to simple identifier resolution.
///
/// Decodes HTML entities in the expression value first (e.g., `&quot;` → `"`),
/// since template attribute values may contain HTML-encoded characters from
/// preprocessor plugins (markdown, docs blocks, etc.).
pub(crate) fn resolve_expr(
    expr: &str,
    value_start: u32,
    oxc_exp: Option<&OxcParsedExpression<'_>>,
    resolver: &VueBindingView<'_>,
    force_js: bool,
) -> String {
    let ts_skip_ranges = expression_ts_removal_spans(oxc_exp, force_js);

    // When HTML entities are present (e.g., `&quot;` in template literal attributes),
    // we must keep binding positions aligned with the expression string passed to
    // build_prefixed_expr. OXC binding positions are relative to the original source
    // (with entities), so we pass the original expression for prefix insertion, then
    // decode entities in the final result.
    if crate::template::code_gen::shared::helpers::has_html_entities(expr) {
        if let Some(oxc) = oxc_exp {
            // Build prefixed output from original source (positions are correct)
            let prefixed = build_prefixed_expr(expr, value_start, oxc, resolver, &ts_skip_ranges);
            // Decode entities in the result
            let mut decoded = String::with_capacity(prefixed.len());
            crate::template::code_gen::shared::helpers::decode_html_entities_into(
                &mut decoded,
                &prefixed,
            );
            decoded
        } else {
            let mut decoded = String::with_capacity(expr.len());
            crate::template::code_gen::shared::helpers::decode_html_entities_into(
                &mut decoded,
                expr,
            );
            resolver.simple_expr(&decoded, BindingAccess::Read)
        }
    } else if let Some(oxc) = oxc_exp {
        build_prefixed_expr(expr, value_start, oxc, resolver, &ts_skip_ranges)
    } else {
        resolver.simple_expr(expr, BindingAccess::Read)
    }
}

/// Type-only ranges in the retained expression or statement-handler parse.
pub(crate) fn expression_ts_removal_spans(
    expression: Option<&OxcParsedExpression<'_>>,
    force_js: bool,
) -> Vec<(u32, u32)> {
    if !force_js {
        return Vec::new();
    }
    match expression {
        Some(oxc) if oxc.expression.is_some() => {
            crate::strip_types::typescript::collect_ts_removal_spans(
                oxc.expression.as_ref().unwrap(),
            )
        }
        Some(oxc) => oxc
            .statements
            .map(crate::strip_types::typescript::collect_program_ts_removal_spans)
            .unwrap_or_default(),
        None => Vec::new(),
    }
}

/// Resolve a loop source through the shared expression writer, reading the
/// loop's retained source inventory: every occurrence in the iterable,
/// including spread elements and callback bodies, with callback parameters
/// and enclosing template aliases marked local. Retained loop AST spans are
/// file-absolute; the writer's type-removal ranges are relative to the
/// iterable window. The caller retains the loop's source anchor.
pub(crate) fn build_prefixed_iterable(
    iterable: &str,
    source: &str,
    v_for: &NodeProp,
    vfor: &OxcParsedVFor<'_>,
    resolver: &VueBindingView<'_>,
    force_js: bool,
) -> String {
    let vfor_parsed = &vfor.parsed;
    let start = crate::template::vue_syntax::v_for_iterable_start(source, v_for, vfor_parsed);
    let end = start + iterable.len() as u32;
    let bindings = vfor
        .source_bindings
        .as_ref()
        .map_or(&[][..], |inventory| inventory.bindings.as_slice());
    let skips = if force_js {
        vfor_parsed
            .right()
            .map(crate::strip_types::typescript::collect_ts_removal_spans)
            .unwrap_or_default()
            .into_iter()
            .filter_map(|(s, e)| {
                let (s, e) = (s.max(start), e.min(end));
                (s < e).then(|| (s - start, e - start))
            })
            .collect::<Vec<_>>()
    } else {
        Vec::new()
    };
    // A parsed source with no identifier occurrence reads only literals, so
    // it is written as authored. The writer's empty-inventory fallback
    // resolves a bare identifier as a context read.
    let parsed = vfor_parsed.right().is_some()
        && !vfor_parsed.result.has_left_errors()
        && !vfor_parsed.result.has_right_errors();
    if parsed && bindings.is_empty() && skips.is_empty() {
        return iterable.to_string();
    }
    let mut result = String::with_capacity(iterable.len() + bindings.len() * 8);
    write_prefixed_bindings(
        &mut StringSink(&mut result),
        iterable,
        start,
        bindings,
        resolver,
        &skips,
    );
    result
}

/// The plan of a resolved expression under the request's map policy: the
/// segmented plan when a map is captured, the text alone otherwise, so a
/// text-only compile records no source segment.
pub(crate) fn prefixed_expr_plan<B: ExprBindings + ?Sized>(
    expr: &str,
    inner_start: u32,
    oxc: &OxcParsedExpression<'_>,
    resolver: &B,
    ts_skip_ranges: &[(u32, u32)],
    mode: MapMode,
) -> MappedGeneratedText {
    match mode {
        MapMode::Map => {
            build_prefixed_expr_segments(expr, inner_start, oxc, resolver, ts_skip_ranges)
        }
        MapMode::NoMap => MappedGeneratedText::synthetic(&build_prefixed_expr(
            expr,
            inner_start,
            oxc,
            resolver,
            ts_skip_ranges,
        )),
    }
}

/// [`resolve_simple_expr_segments`] under the request's map policy; see
/// [`prefixed_expr_plan`].
pub(crate) fn simple_expr_plan<B: ExprBindings + ?Sized>(
    resolver: &B,
    expr: &str,
    inner_start: u32,
    mode: MapMode,
) -> MappedGeneratedText {
    match mode {
        MapMode::Map => resolve_simple_expr_segments(resolver, expr, inner_start),
        MapMode::NoMap => {
            let mut text = String::with_capacity(expr.len() + 8);
            write_simple_expr(&mut StringSink(&mut text), resolver, expr, inner_start);
            MappedGeneratedText::synthetic(&text)
        }
    }
}

/// Whether the non-ignored bindings are in strictly increasing, non-overlapping
/// source order — the precondition [`write_prefixed_expr`]'s compound walk
/// consumes. Ignored bindings carry no prefix and pass through inside a verbatim
/// run, so they place no constraint.
///
/// Not `#[cfg(debug_assertions)]`: `debug_assert!` gates on `cfg!`, a runtime
/// constant, so its body is still compiled in release and would fail to resolve
/// a debug-only callee. The `if false` leaves nothing behind.
fn is_source_ordered(bindings: &[crate::utils::oxc::Binding<'_>]) -> bool {
    let mut end = 0u32;
    for binding in bindings.iter().filter(|b| !b.ignore) {
        if binding.pos < end {
            return false;
        }
        end = binding.pos + binding.span.len();
    }
    true
}

/// Core resolved-expression walk shared by the flat and segmented builders.
///
/// Mirrors `build_prefixed_expr` exactly: simple identifiers route through
/// [`write_simple_expr`]; compound expressions walk the OXC bindings, emitting
/// each binding's synthetic prefix/suffix around the mapped identifier plus the
/// verbatim source chunks between bindings (with TS-skip ranges removed).
pub(crate) fn write_prefixed_expr<S: ExprSink, B: ExprBindings + ?Sized>(
    sink: &mut S,
    expr: &str,
    inner_start: u32,
    oxc: &OxcParsedExpression<'_>,
    resolver: &B,
    ts_skip_ranges: &[(u32, u32)],
) {
    let bindings = oxc
        .bindings
        .as_ref()
        .map(|bindings| bindings.bindings.as_slice())
        .unwrap_or_default();
    write_prefixed_bindings(sink, expr, inner_start, bindings, resolver, ts_skip_ranges);
}

/// The common expression writer also accepts retained binding inventories directly.
pub(crate) fn write_prefixed_bindings<S: ExprSink, B: ExprBindings + ?Sized>(
    sink: &mut S,
    expr: &str,
    inner_start: u32,
    bindings: &[crate::utils::oxc::Binding<'_>],
    resolver: &B,
    ts_skip_ranges: &[(u32, u32)],
) {
    if bindings.is_empty() && ts_skip_ranges.is_empty() {
        return write_simple_expr(sink, resolver, expr, inner_start);
    }

    // Single binding spanning the whole simple identifier → simple resolution.
    // An ignored single binding (v-for/v-slot local) stays a bare mapped
    // identifier with no prefix — UNLESS it's a Vapor v-for loop variable
    // with an active rename (`item` → `_for_item0.value`), in which case
    // the renamed accessor is synthetic scaffolding, not authored source
    // (mirrors official's real `context.withId(fn, idMap)` substitution).
    if bindings.len() == 1 && is_simple_ident(expr) {
        if bindings[0].ignore {
            let trimmed = expr.trim();
            if !bindings[0].is_expression_local {
                if let Some(renamed) = resolver.resolve_local(trimmed) {
                    sink.push_synthetic(renamed);
                    return;
                }
            }
            let trim_offset = (expr.len() - expr.trim_start().len()) as u32;
            sink.push_source(trimmed, inner_start + trim_offset);
            return;
        }
        return write_simple_expr(sink, resolver, expr, inner_start);
    }

    // Compound walk: insert prefix/suffix at expression-relative offsets.
    //
    // The walk copies the verbatim source run in front of each binding, so it is
    // only correct in source order — which `BindingExtractionResult` guarantees
    // by recording bindings in order (`push_binding`). This pins the precondition
    // at the point it is CONSUMED, so a result assembled by some other route
    // fails loudly here instead of emitting text that has lost a source run.
    verter_debug_assert!(
        is_source_ordered(bindings),
        "resolved-expression bindings must be in source order, got {:?} for {expr:?}",
        bindings
            .iter()
            .map(|b| (b.name, b.pos, b.ignore))
            .collect::<Vec<_>>(),
    );

    let expr_start = inner_start as usize;
    let trim_offset = expr.len() - expr.trim_start().len();
    let trimmed = expr.trim();
    let mut last_end = 0usize;

    // Convert expression-relative skip ranges to trimmed-relative.
    let trimmed_skips: Vec<(usize, usize)> = if ts_skip_ranges.is_empty() {
        Vec::new()
    } else {
        ts_skip_ranges
            .iter()
            .filter_map(|&(s, e)| {
                let ts = (s as usize).saturating_sub(trim_offset);
                let te = (e as usize).saturating_sub(trim_offset);
                if te > ts && ts < trimmed.len() {
                    Some((ts, te.min(trimmed.len())))
                } else {
                    None
                }
            })
            .collect()
    };

    for binding in bindings {
        // An ignored binding (v-for/v-slot local) normally passes through
        // untouched inside a later verbatim chunk — UNLESS it's a Vapor
        // v-for loop variable with an active rename, in which case it needs
        // the SAME chunk-before + replacement-text + `last_end` handling as
        // a normal binding, just with synthetic renamed text instead of
        // `prefix + source + suffix`.
        let for_local_rename = if binding.ignore {
            if binding.is_expression_local {
                continue;
            }
            let Some(renamed) = resolver.resolve_local(binding.name) else {
                continue;
            };
            Some(renamed)
        } else {
            None
        };

        // Convert file-relative pos to expr-trimmed-relative offset.
        let rel_pos = (binding.pos as usize)
            .saturating_sub(expr_start)
            .saturating_sub(trim_offset);

        if rel_pos > trimmed.len() {
            continue; // out of range
        }

        // Verbatim source chunk before this binding, skipping TS-only ranges.
        if rel_pos > last_end {
            push_chunk_with_skips(
                sink,
                trimmed,
                last_end,
                rel_pos,
                &trimmed_skips,
                inner_start,
                trim_offset,
            );
        }

        if let Some(renamed) = for_local_rename {
            if binding.is_shorthand {
                sink.push_synthetic(binding.name);
                sink.push_synthetic(": ");
            }
            sink.push_synthetic(renamed);
            last_end = rel_pos + binding.span.len() as usize;
            continue;
        }

        let access = access_of(binding);
        let prefix = resolver.resolve_prefix(binding.name, access);
        let suffix = resolver.resolve_suffix(binding.name, access);

        // Shorthand `{ total }` with a prefix/suffix expands to
        // `{ total: _ctx.total }`. The leading key duplication is synthetic.
        if binding.is_shorthand && (!prefix.is_empty() || !suffix.is_empty()) {
            sink.push_synthetic(binding.name);
            sink.push_synthetic(": ");
        }

        sink.push_synthetic(prefix);
        sink.push_source(binding.name, binding.pos);
        sink.push_synthetic(suffix);

        // A token that spells a character as a Unicode escape is longer
        // than its name, so the walk resumes after the whole token.
        last_end = rel_pos + binding.span.len() as usize;
    }

    // Verbatim source tail after the last binding, skipping TS-only ranges.
    if last_end < trimmed.len() {
        push_chunk_with_skips(
            sink,
            trimmed,
            last_end,
            trimmed.len(),
            &trimmed_skips,
            inner_start,
            trim_offset,
        );
    }
}

/// Resolve a simple identifier (or pass-through) expression into `sink`.
///
/// Mirrors `BindingResolver::resolve_simple_expr` byte-for-byte: the prefix and
/// suffix (or keyword brackets) are synthetic; only the identifier itself maps.
/// A lone identifier is never assigned or constructed, so it is a read.
pub(crate) fn write_simple_expr<S: ExprSink, B: ExprBindings + ?Sized>(
    sink: &mut S,
    resolver: &B,
    expr: &str,
    inner_start: u32,
) {
    let trimmed = expr.trim();
    let trim_offset = (expr.len() - expr.trim_start().len()) as u32;
    let name_pos = inner_start + trim_offset;

    if !is_simple_ident(trimmed) {
        // Non-identifier expression passes through verbatim as authored source.
        sink.push_source(trimmed, name_pos);
        return;
    }

    if let Some(local) = resolver.resolve_local(trimmed) {
        sink.push_synthetic(local);
        return;
    }
    let is_kw = is_keyword(trimmed.as_bytes());

    // Keywords that are not registered bindings, globals, and `$event` pass
    // through unchanged (e.g. `true`, `false`, `window`).
    if (is_kw && resolver.get(trimmed).is_none())
        || is_global(trimmed.as_bytes())
        || trimmed == "$event"
    {
        sink.push_source(trimmed, name_pos);
        return;
    }

    let prefix = resolver.resolve_prefix(trimmed, BindingAccess::Read);
    let suffix = resolver.resolve_suffix(trimmed, BindingAccess::Read);

    if is_kw && !prefix.is_empty() {
        // Keyword member access uses bracket notation: `$props["class"]`.
        let base = prefix.trim_end_matches('.');
        sink.push_synthetic(base);
        sink.push_synthetic("[\"");
        sink.push_source(trimmed, name_pos);
        sink.push_synthetic("\"]");
        sink.push_synthetic(suffix);
    } else {
        sink.push_synthetic(prefix);
        sink.push_source(trimmed, name_pos);
        sink.push_synthetic(suffix);
    }
}

/// Copy an authored expression through the same range-skipping writer,
/// preserving a context where the caller intentionally supplies no prefixes.
pub(crate) fn write_source_expr<S: ExprSink>(
    sink: &mut S,
    text: &str,
    start: u32,
    skips: &[(u32, u32)],
) {
    struct Authored;
    impl ExprBindings for Authored {
        fn get(&self, _: &str) -> Option<BindingType> {
            None
        }
        fn resolve_prefix(&self, _: &str, _: BindingAccess) -> &'static str {
            ""
        }
        fn resolve_suffix(&self, _: &str, _: BindingAccess) -> &'static str {
            ""
        }
        fn resolve_local(&self, _: &str) -> Option<&str> {
            None
        }
    }
    write_prefixed_bindings(sink, text, start, &[], &Authored, skips);
}

/// Copy `text[start..end]` into `sink` as authored source, skipping any bytes
/// that overlap the sorted `skips` ranges (TS syntax removed by `force_js`).
/// Each emitted sub-chunk maps to its precise file offset
/// (`inner_start + trim_offset + <offset within trimmed>`).
fn push_chunk_with_skips<S: ExprSink>(
    sink: &mut S,
    text: &str,
    start: usize,
    end: usize,
    skips: &[(usize, usize)],
    inner_start: u32,
    trim_offset: usize,
) {
    let src_of = |off: usize| inner_start + (trim_offset + off) as u32;
    if skips.is_empty() {
        sink.push_source(&text[start..end], src_of(start));
        return;
    }
    let mut pos = start;
    for &(ss, se) in skips {
        if se <= start || ss >= end {
            continue;
        }
        let effective_start = ss.max(start);
        let effective_end = se.min(end);
        if effective_start > pos {
            sink.push_source(&text[pos..effective_start], src_of(pos));
        }
        pos = effective_end;
    }
    if pos < end {
        sink.push_source(&text[pos..end], src_of(pos));
    }
}

/// For each non-ignored identifier of an expression, record its accessor
/// prefix before it and its suffix after it, in place in the source, resolved
/// with the occurrence's access. A shorthand property that gains a prefix or
/// suffix is expanded to `key: value` so the object literal stays valid.
pub(crate) fn collect_binding_patches<B: ExprBindings + ?Sized>(
    resolver: &B,
    bindings: &BindingExtractionResult<'_>,
    edits: &mut EditRecorder<'_>,
) {
    for binding in &bindings.bindings {
        if binding.ignore {
            continue; // v-for/v-slot locals — already in scope
        }

        let access = access_of(binding);
        let prefix = resolver.resolve_prefix(binding.name, access);
        let suffix = resolver.resolve_suffix(binding.name, access);

        // When a shorthand property `{ foo }` gets a prefix/suffix, expand
        // it to `{ foo: $setup.foo }` to keep valid JS. We prepend "foo: "
        // at the same position before the prefix; stable sort preserves order.
        if binding.is_shorthand && (!prefix.is_empty() || !suffix.is_empty()) {
            edits.prepend_fmt(binding.pos, format_args!("{}: ", binding.name));
        }

        if !prefix.is_empty() {
            edits.prepend_static(binding.pos, prefix);
        }

        if !suffix.is_empty() {
            edits.prepend_static(binding.pos + binding.span.len(), suffix);
        }
    }
}

