//! Shared expression-plan builder for resolved template expressions.
//!
//! Produces a [`MappedGeneratedText`] — the resolved expression string plus an
//! ordered segment plan marking which byte runs are authored source (mapped)
//! and which are resolver scaffolding (unmapped). This is the single
//! sourcemap-aware analogue of
//! [`build_prefixed_expr`](super::vapor::interpolation::build_prefixed_expr):
//! both walk the same OXC binding data and emit byte-identical text; the flat
//! builder discards positions while the segment builder records them.
//!
//! The flat `build_prefixed_expr` delegates here through a zero-overhead
//! [`StringSink`], so the runtime path and the sourcemap path can never drift in
//! their generated bytes.

use crate::template::code_gen::binding::{is_simple_ident, BindingResolver};
use crate::template::code_gen::types::MappedGeneratedText;
use crate::template::oxc::types::OxcParsedExpression;
use crate::utils::oxc::bindings::keywords::{is_global, is_keyword};

/// Ordered destination for the resolved-expression walk.
///
/// Two implementations: [`StringSink`] (flat string, ignores positions — the
/// runtime `build_prefixed_expr` path) and [`SegmentSink`] (records a
/// [`MappedGeneratedText`] plan). Keeping one walk over two sinks guarantees the
/// flat and segmented builders produce identical generated bytes.
pub(crate) trait ExprSink {
    /// Append authored source text whose first byte is at file offset
    /// `source_start`.
    fn push_source(&mut self, text: &str, source_start: u32);
    /// Append synthetic scaffolding text (binding prefix/suffix, keyword
    /// brackets, shorthand key) that must not map to source.
    fn push_synthetic(&mut self, text: &str);
}

/// Flat-string sink: both pushes append to the buffer; source positions are
/// discarded. Keeps `build_prefixed_expr` free of any segment-plan overhead.
pub(crate) struct StringSink<'a>(pub &'a mut String);

impl ExprSink for StringSink<'_> {
    #[inline]
    fn push_source(&mut self, text: &str, _source_start: u32) {
        self.0.push_str(text);
    }
    #[inline]
    fn push_synthetic(&mut self, text: &str) {
        self.0.push_str(text);
    }
}

/// Segment-recording sink: builds the [`MappedGeneratedText`] plan.
#[derive(Default)]
struct SegmentSink {
    out: MappedGeneratedText,
}

impl ExprSink for SegmentSink {
    #[inline]
    fn push_source(&mut self, text: &str, source_start: u32) {
        self.out.push(text, Some(source_start));
    }
    #[inline]
    fn push_synthetic(&mut self, text: &str) {
        self.out.push(text, None);
    }
}

/// Build the segmented plan for a resolved (possibly compound) expression.
///
/// `.text` is byte-identical to
/// `build_prefixed_expr(expr, inner_start, oxc, resolver, ts_skip_ranges)`.
pub fn build_prefixed_expr_segments(
    expr: &str,
    inner_start: u32,
    oxc: &OxcParsedExpression<'_>,
    resolver: &BindingResolver<'_>,
    ts_skip_ranges: &[(u32, u32)],
) -> MappedGeneratedText {
    let mut sink = SegmentSink::default();
    write_prefixed_expr(&mut sink, expr, inner_start, oxc, resolver, ts_skip_ranges);
    sink.out
}

/// Build the segmented plan for a simple-identifier expression with no OXC
/// binding data (the resolver-only path).
///
/// `.text` is byte-identical to `resolver.resolve_simple_expr(expr)`.
pub fn resolve_simple_expr_segments(
    resolver: &BindingResolver<'_>,
    expr: &str,
    inner_start: u32,
) -> MappedGeneratedText {
    let mut sink = SegmentSink::default();
    write_simple_expr(&mut sink, resolver, expr, inner_start);
    sink.out
}

/// Whether the non-ignored bindings are in strictly increasing, non-overlapping
/// source order — the precondition [`write_prefixed_expr`]'s compound walk
/// consumes. Ignored bindings carry no prefix and pass through inside a verbatim
/// run, so they place no constraint.
///
/// Not `#[cfg(debug_assertions)]`: `debug_assert!` gates on `cfg!`, a runtime
/// constant, so its body is still compiled in release and would fail to resolve
/// a debug-only callee. The `if false` leaves nothing behind.
fn is_source_ordered(bindings: &[crate::utils::oxc::Binding<'_>]) -> bool {
    let mut end = 0u32;
    for binding in bindings.iter().filter(|b| !b.ignore) {
        if binding.pos < end {
            return false;
        }
        end = binding.pos + binding.name.len() as u32;
    }
    true
}

/// Core resolved-expression walk shared by the flat and segmented builders.
///
/// Mirrors `build_prefixed_expr` exactly: simple identifiers route through
/// [`write_simple_expr`]; compound expressions walk the OXC bindings, emitting
/// each binding's synthetic prefix/suffix around the mapped identifier plus the
/// verbatim source chunks between bindings (with TS-skip ranges removed).
pub(crate) fn write_prefixed_expr<S: ExprSink>(
    sink: &mut S,
    expr: &str,
    inner_start: u32,
    oxc: &OxcParsedExpression<'_>,
    resolver: &BindingResolver<'_>,
    ts_skip_ranges: &[(u32, u32)],
) {
    let Some(bindings) = &oxc.bindings else {
        return write_simple_expr(sink, resolver, expr, inner_start);
    };
    if bindings.bindings.is_empty() {
        return write_simple_expr(sink, resolver, expr, inner_start);
    }

    // Single binding spanning the whole simple identifier → simple resolution.
    // An ignored single binding (v-for/v-slot local) stays a bare mapped
    // identifier with no prefix — UNLESS it's a Vapor v-for loop variable
    // with an active rename (`item` → `_for_item0.value`), in which case
    // the renamed accessor is synthetic scaffolding, not authored source
    // (mirrors official's real `context.withId(fn, idMap)` substitution).
    if bindings.bindings.len() == 1 && is_simple_ident(expr) {
        if bindings.bindings[0].ignore {
            let trimmed = expr.trim();
            if let Some(renamed) = resolver.resolve_for_local(trimmed) {
                sink.push_synthetic(renamed);
                return;
            }
            let trim_offset = (expr.len() - expr.trim_start().len()) as u32;
            sink.push_source(trimmed, inner_start + trim_offset);
            return;
        }
        return write_simple_expr(sink, resolver, expr, inner_start);
    }

    // Compound walk: insert prefix/suffix at expression-relative offsets.
    //
    // The walk copies the verbatim source run in front of each binding, so it is
    // only correct in source order — which `BindingExtractionResult` guarantees
    // by recording bindings in order (`push_binding`). This pins the precondition
    // at the point it is CONSUMED, so a result assembled by some other route
    // fails loudly here instead of emitting text that has lost a source run.
    debug_assert!(
        is_source_ordered(&bindings.bindings),
        "resolved-expression bindings must be in source order, got {:?} for {expr:?}",
        bindings
            .bindings
            .iter()
            .map(|b| (b.name, b.pos, b.ignore))
            .collect::<Vec<_>>(),
    );

    let expr_start = inner_start as usize;
    let trim_offset = expr.len() - expr.trim_start().len();
    let trimmed = expr.trim();
    let mut last_end = 0usize;

    // Convert expression-relative skip ranges to trimmed-relative.
    let trimmed_skips: Vec<(usize, usize)> = if ts_skip_ranges.is_empty() {
        Vec::new()
    } else {
        ts_skip_ranges
            .iter()
            .filter_map(|&(s, e)| {
                let ts = (s as usize).saturating_sub(trim_offset);
                let te = (e as usize).saturating_sub(trim_offset);
                if te > ts && ts < trimmed.len() {
                    Some((ts, te.min(trimmed.len())))
                } else {
                    None
                }
            })
            .collect()
    };

    for binding in &bindings.bindings {
        // An ignored binding (v-for/v-slot local) normally passes through
        // untouched inside a later verbatim chunk — UNLESS it's a Vapor
        // v-for loop variable with an active rename, in which case it needs
        // the SAME chunk-before + replacement-text + `last_end` handling as
        // a normal binding, just with synthetic renamed text instead of
        // `prefix + source + suffix`.
        let for_local_rename = if binding.ignore {
            let Some(renamed) = resolver.resolve_for_local(binding.name) else {
                continue;
            };
            Some(renamed)
        } else {
            None
        };

        // Convert file-relative pos to expr-trimmed-relative offset.
        let rel_pos = (binding.pos as usize)
            .saturating_sub(expr_start)
            .saturating_sub(trim_offset);

        if rel_pos > trimmed.len() {
            continue; // out of range
        }

        // Verbatim source chunk before this binding, skipping TS-only ranges.
        if rel_pos > last_end {
            push_chunk_with_skips(
                sink,
                trimmed,
                last_end,
                rel_pos,
                &trimmed_skips,
                inner_start,
                trim_offset,
            );
        }

        if let Some(renamed) = for_local_rename {
            sink.push_synthetic(renamed);
            last_end = rel_pos + binding.name.len();
            continue;
        }

        let prefix = resolver.resolve_prefix(binding.name);
        let suffix = resolver.resolve_suffix(binding.name);

        // Shorthand `{ total }` with a prefix/suffix expands to
        // `{ total: _ctx.total }`. The leading key duplication is synthetic.
        if binding.is_shorthand && (!prefix.is_empty() || !suffix.is_empty()) {
            sink.push_synthetic(binding.name);
            sink.push_synthetic(": ");
        }

        sink.push_synthetic(prefix);
        sink.push_source(binding.name, binding.pos);
        sink.push_synthetic(suffix);

        last_end = rel_pos + binding.name.len();
    }

    // Verbatim source tail after the last binding, skipping TS-only ranges.
    if last_end < trimmed.len() {
        push_chunk_with_skips(
            sink,
            trimmed,
            last_end,
            trimmed.len(),
            &trimmed_skips,
            inner_start,
            trim_offset,
        );
    }
}

/// Resolve a simple identifier (or pass-through) expression into `sink`.
///
/// Mirrors `BindingResolver::resolve_simple_expr` byte-for-byte: the prefix and
/// suffix (or keyword brackets) are synthetic; only the identifier itself maps.
pub(crate) fn write_simple_expr<S: ExprSink>(
    sink: &mut S,
    resolver: &BindingResolver<'_>,
    expr: &str,
    inner_start: u32,
) {
    let trimmed = expr.trim();
    let trim_offset = (expr.len() - expr.trim_start().len()) as u32;
    let name_pos = inner_start + trim_offset;

    if !is_simple_ident(trimmed) {
        // Non-identifier expression passes through verbatim as authored source.
        sink.push_source(trimmed, name_pos);
        return;
    }

    let is_kw = is_keyword(trimmed.as_bytes());

    // Keywords that are not registered bindings, globals, and `$event` pass
    // through unchanged (e.g. `true`, `false`, `window`).
    if (is_kw && resolver.get(trimmed).is_none())
        || is_global(trimmed.as_bytes())
        || trimmed == "$event"
    {
        sink.push_source(trimmed, name_pos);
        return;
    }

    let prefix = resolver.resolve_prefix(trimmed);
    let suffix = resolver.resolve_suffix(trimmed);

    if is_kw && !prefix.is_empty() {
        // Keyword member access uses bracket notation: `$props["class"]`.
        let base = prefix.trim_end_matches('.');
        sink.push_synthetic(base);
        sink.push_synthetic("[\"");
        sink.push_source(trimmed, name_pos);
        sink.push_synthetic("\"]");
        sink.push_synthetic(suffix);
    } else {
        sink.push_synthetic(prefix);
        sink.push_source(trimmed, name_pos);
        sink.push_synthetic(suffix);
    }
}

/// Copy `text[start..end]` into `sink` as authored source, skipping any bytes
/// that overlap the sorted `skips` ranges (TS syntax removed by `force_js`).
/// Each emitted sub-chunk maps to its precise file offset
/// (`inner_start + trim_offset + <offset within trimmed>`).
fn push_chunk_with_skips<S: ExprSink>(
    sink: &mut S,
    text: &str,
    start: usize,
    end: usize,
    skips: &[(usize, usize)],
    inner_start: u32,
    trim_offset: usize,
) {
    let src_of = |off: usize| inner_start + (trim_offset + off) as u32;
    if skips.is_empty() {
        sink.push_source(&text[start..end], src_of(start));
        return;
    }
    let mut pos = start;
    for &(ss, se) in skips {
        if se <= start || ss >= end {
            continue;
        }
        let effective_start = ss.max(start);
        let effective_end = se.min(end);
        if effective_start > pos {
            sink.push_source(&text[pos..effective_start], src_of(pos));
        }
        pos = effective_end;
    }
    if pos < end {
        sink.push_source(&text[pos..end], src_of(pos));
    }
}

