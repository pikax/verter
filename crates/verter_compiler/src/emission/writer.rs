//! The one writer: fragment pieces go straight into the artifact's single
//! destination buffer, and a mapped write records decoded segments and wire
//! tokens in the same pass. The text-only write holds no map state.

use std::ops::Range;

use verter_audit::observe::ObserveExec;

use super::correspondence::{classify, wire_tokens, Correspondence, WireCursor, WireSource};
use super::fragment::{EmissionFragment, FragmentToken};
use super::piece::{MarkerId, PieceText};
use super::source::QualifiedSource;
use super::walk::{walk, Fill, PieceVisitor, Visit};
use crate::assembly::map_input::{DecodedFragmentMap, SourcePayload, TablesId, WireSegment};
use crate::cursor::position::PositionResolver;
use crate::work_ledger::{CompilerWorkLedger, WorkKind};

/// How a decoded map segment relates generated bytes to source bytes.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MapSegmentKind {
    /// Every generated byte maps to the source byte at the same distance.
    Identity,
    /// Replacement text: the whole run stands for the span starting at
    /// `source_start`.
    Rewritten,
    /// Generated text standing for one source point.
    Anchor,
}

/// One mapped run of a written artifact.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DecodedMapSegment {
    pub generated: Range<u32>,
    /// Index into the artifact's source table.
    pub source: u32,
    pub source_start: u32,
    pub kind: MapSegmentKind,
}

/// The tables an external map brings into the artifact's map, appended
/// after the artifact's own sources and never merged with another input's.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct ExternalTables {
    pub(crate) sources: Vec<String>,
    pub(crate) sources_content: Vec<Option<String>>,
    pub(crate) names: Vec<String>,
    /// Ignore-listed rows, as indices of the artifact's source table.
    pub(crate) ignore_list: Vec<u32>,
}

/// What a write records beside the text.
pub(crate) trait EmissionSink<'s> {
    fn piece(&mut self, visit: &Visit<'_, 's>);
}

/// A text-only write: records nothing.
pub(crate) struct TextOnly;

impl<'s> EmissionSink<'s> for TextOnly {
    #[inline(always)]
    fn piece(&mut self, _visit: &Visit<'_, 's>) {}
}

/// The map facts of one write, in generated order.
pub(crate) struct MapParts {
    pub(crate) segments: Vec<DecodedMapSegment>,
    pub(crate) wire: Vec<WireSegment>,
    pub(crate) external: Vec<ExternalTables>,
}

/// A mapped write's sink. Position resolvers are built per source on its
/// first mapped piece only.
pub(crate) struct MapSink<'p, 's> {
    sources: &'p [QualifiedSource<'s>],
    resolvers: Vec<Option<PositionResolver<'s>>>,
    /// The fragment whose source index was resolved last, and that index.
    last_source: Option<(FragmentToken, Option<u32>)>,
    cursor: WireCursor,
    segments: Vec<DecodedMapSegment>,
    wire: Vec<WireSegment>,
    external: Vec<ExternalTables>,
    external_sources: u32,
    external_names: u32,
    /// Tables already written, with their source and name bases. Parts of
    /// one decoded map share its tables; separate inputs never do.
    written_tables: Vec<(TablesId, u32, u32)>,
}

impl<'p, 's> MapSink<'p, 's> {
    /// A sink for an artifact whose source table is `sources`.
    pub(crate) fn new(sources: &'p [QualifiedSource<'s>]) -> Self {
        Self {
            sources,
            resolvers: (0..sources.len()).map(|_| None).collect(),
            last_source: None,
            cursor: WireCursor::default(),
            segments: Vec::new(),
            wire: Vec::new(),
            external: Vec::new(),
            external_sources: 0,
            external_names: 0,
            written_tables: Vec::new(),
        }
    }

    pub(crate) fn finish(self) -> MapParts {
        MapParts {
            segments: self.segments,
            wire: self.wire,
            external: self.external,
        }
    }

    fn source_index(&mut self, fragment: &EmissionFragment<'s>) -> Option<u32> {
        let token = fragment.token();
        if let Some((last, index)) = self.last_source {
            if last == token {
                return index;
            }
        }
        let index = fragment.source().and_then(|source| {
            self.sources
                .iter()
                .position(|registered| registered.key.same(&source.key))
                .map(|index| index as u32)
        });
        self.last_source = Some((token, index));
        index
    }

    fn external_run(&mut self, visit: &Visit<'_, 's>, index: u32) {
        let Some(map) = visit.fragment.external(index) else {
            self.cursor.gap(&mut self.wire);
            self.cursor.advance(visit.text);
            return;
        };
        let (source_base, name_base) = match self
            .written_tables
            .iter()
            .find(|(tables, _, _)| *tables == map.tables())
        {
            Some(&(_, source_base, name_base)) => (source_base, name_base),
            None => self.append_tables(map),
        };
        // A table-only contribution has no generated bytes or mapping
        // events. Keep the incoming cursor state after retaining its tables.
        if visit.text.is_empty() && map.segments().is_empty() {
            return;
        }
        let origin = (self.cursor.line, self.cursor.column);
        let starts_at_origin = map
            .segments()
            .first()
            .is_some_and(|segment| segment.generated_line == 0 && segment.generated_column == 0);
        if !starts_at_origin && !visit.text.starts_with('\n') {
            self.cursor.gap(&mut self.wire);
        }
        for segment in map.segments() {
            let (generated_line, generated_column) = if segment.generated_line == 0 {
                (origin.0, origin.1 + segment.generated_column)
            } else {
                (origin.0 + segment.generated_line, segment.generated_column)
            };
            let payload = segment.payload.map(|payload| SourcePayload {
                source_index: payload.source_index + source_base,
                name_index: payload.name_index.map(|name| name + name_base),
                ..payload
            });
            self.wire.push(WireSegment {
                generated_line,
                generated_column,
                payload,
            });
        }
        self.cursor.advance(visit.text);
        // The run leaves a mapping active when its last token is on the line
        // the run ends on and names a source.
        self.cursor.mapped = map.segments().last().is_some_and(|segment| {
            segment.payload.is_some() && origin.0 + segment.generated_line == self.cursor.line
        });
    }
}

impl MapSink<'_, '_> {
    /// Append an external map's tables after the rows written so far.
    fn append_tables(&mut self, map: &DecodedFragmentMap) -> (u32, u32) {
        let source_base = self.sources.len() as u32 + self.external_sources;
        let name_base = self.external_names;
        self.external_sources += map.sources().len() as u32;
        self.external_names += map.names().len() as u32;
        self.external.push(ExternalTables {
            sources: map.sources().to_vec(),
            sources_content: map
                .sources_content()
                .map_or_else(|| vec![None; map.sources().len()], <[_]>::to_vec),
            names: map.names().to_vec(),
            ignore_list: map
                .ignore_list()
                .iter()
                .map(|entry| *entry as u32 + source_base)
                .collect(),
        });
        self.written_tables
            .push((map.tables(), source_base, name_base));
        (source_base, name_base)
    }
}

impl<'s> EmissionSink<'s> for MapSink<'_, 's> {
    fn piece(&mut self, visit: &Visit<'_, 's>) {
        let correspondence = classify(visit.piece);
        if let Correspondence::External(index) = correspondence {
            self.external_run(visit, index);
            return;
        }
        if visit.text.is_empty() {
            if visit.piece.text == PieceText::Empty
                && visit.piece.provenance == crate::emission::Provenance::Unmapped
            {
                wire_tokens(
                    correspondence,
                    visit.text,
                    None,
                    &[],
                    &mut self.cursor,
                    &mut self.wire,
                );
            }
            return;
        }
        let source = self.source_index(visit.fragment);
        if let Some(source) = source {
            let decoded = match correspondence {
                Correspondence::Identity { source_start } => {
                    Some((source_start, MapSegmentKind::Identity))
                }
                Correspondence::Rewritten { source } => {
                    Some((source.start, MapSegmentKind::Rewritten))
                }
                Correspondence::Anchor { source_offset } => {
                    Some((source_offset, MapSegmentKind::Anchor))
                }
                Correspondence::Unmapped | Correspondence::External(_) => None,
            };
            if let Some((source_start, kind)) = decoded {
                // An identity run has a token on every line; a rewritten or
                // anchored run has one, which ends with its line.
                let len = match kind {
                    MapSegmentKind::Identity => visit.text.len(),
                    MapSegmentKind::Rewritten | MapSegmentKind::Anchor => {
                        memchr::memchr(b'\n', visit.text.as_bytes())
                            .map_or(visit.text.len(), |newline| newline + 1)
                    }
                };
                self.segments.push(DecodedMapSegment {
                    generated: visit.at..visit.at + len as u32,
                    source,
                    source_start,
                    kind,
                });
            }
            let slot = &mut self.resolvers[source as usize];
            if slot.is_none() && !matches!(correspondence, Correspondence::Unmapped) {
                *slot = Some(PositionResolver::new_for_sourcemap(
                    self.sources[source as usize].text,
                ));
            }
        }
        let wire_source = source.and_then(|index| {
            self.resolvers[index as usize]
                .as_ref()
                .map(|resolver| WireSource { index, resolver })
        });
        let locations = visit
            .fragment
            .hints()
            .map_or(&[][..], |hints| hints.locations());
        wire_tokens(
            correspondence,
            visit.text,
            wire_source,
            locations,
            &mut self.cursor,
            &mut self.wire,
        );
    }
}

/// Writes fragments into one destination buffer, charging the ledger for
/// every byte and handing each piece to the sink.
pub(crate) struct Writer<'o, 'l, S, M: ObserveExec> {
    out: &'o mut String,
    ledger: &'l mut CompilerWorkLedger<M>,
    sink: S,
    markers: Option<Vec<(MarkerId, Range<u32>)>>,
}

impl<'o, 'l, S, M: ObserveExec> Writer<'o, 'l, S, M> {
    pub(crate) fn new(out: &'o mut String, ledger: &'l mut CompilerWorkLedger<M>, sink: S) -> Self {
        Self {
            out,
            ledger,
            sink,
            markers: None,
        }
    }

    /// Structural positions requested by a terminal consumer, independent
    /// of map capture. Ordinary artifact writes allocate no marker table.
    pub(crate) fn capture_markers(&mut self) {
        self.markers = Some(Vec::new());
    }

    pub(crate) fn take_markers(&mut self) -> Vec<(MarkerId, Range<u32>)> {
        self.markers.take().unwrap_or_default()
    }

    /// Bytes written so far.
    pub(crate) fn written(&self) -> u32 {
        self.out.len() as u32
    }

    pub(crate) fn ledger(&mut self) -> &mut CompilerWorkLedger<M> {
        &mut *self.ledger
    }

    pub(crate) fn into_sink(self) -> S {
        self.sink
    }
}

impl<'s, S: EmissionSink<'s>, M: ObserveExec> Writer<'_, '_, S, M> {
    /// Write `fragment` at the current end of the buffer, with `fills`
    /// (ordered by piece) in place of their marked pieces.
    pub(crate) fn write_fragment(
        &mut self,
        fragment: &EmissionFragment<'s>,
        fills: &[Fill<'_, 's>],
    ) {
        let at = self.written();
        walk(fragment, fills, at, self);
    }
}

impl<'s, S: EmissionSink<'s>, M: ObserveExec> PieceVisitor<'s> for Writer<'_, '_, S, M> {
    fn visit(&mut self, visit: Visit<'_, 's>) {
        verter_debug_assert_eq!(visit.at as usize, self.out.len());
        let bytes = visit.text.len() as u64;
        if let (Some(markers), Some(marker)) = (&mut self.markers, visit.piece.marker) {
            markers.push((marker, visit.at..visit.at + visit.text.len() as u32));
        }
        let kind = match visit.piece.text {
            PieceText::Source(_) => WorkKind::EmissionSourceSliceBytes,
            _ => WorkKind::EmissionGeneratedBytes,
        };
        self.ledger.record(kind, bytes);
        self.ledger.record(WorkKind::EmissionCopyBytes, bytes);
        self.out.push_str(visit.text);
        self.sink.piece(&visit);
    }
}
