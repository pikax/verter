//! The production IDE route's condition narrowing: structure, linear growth,
//! once-per-condition emission and authored mappings.
//!
//! Every fixture is a complete SFC from [`super::flow_check::ide_fixtures`]
//! (the contract cases the paired real-provider tests check) compiled through
//! the ordinary IDE compile. Work is read from [`take_flow_work`], which
//! counts operations where they happen.

use oxc_allocator::Allocator;

use super::flow::{take_flow_work, FlowWork};
use super::flow_check::fixtures::{self as reference, MATRIX_SIZES};
use super::flow_check::generator::GuardStrategy;
use super::flow_check::ide_fixtures::{self, SfcFixture};
use super::flow_check::seam::Span;

/// One production IDE compile.
struct Compiled {
    code: String,
    /// `(generated byte offset, authored byte offset)` of every mapped token.
    tokens: Vec<(u32, u32)>,
    work: FlowWork,
}

fn compile(fixture: &SfcFixture) -> Compiled {
    use crate::compile::legacy_test_support::{compile, CodegenOptions, VerterCompileOptions};
    let alloc = Allocator::new();
    let options = CodegenOptions {
        filename: Some(format!("{}.vue", fixture.name)),
        target: crate::compile::CompileTarget::TSX,
        embed_ambient_types: false,
        ..Default::default()
    };
    let verter_opts = VerterCompileOptions {
        source_map: true,
        ..Default::default()
    };
    take_flow_work();
    let result = compile(
        &fixture.source,
        &options,
        &verter_opts,
        &crate::compile::VueMacroSemanticInput::Unavailable,
        &alloc,
    );
    let work = take_flow_work();
    let tsx = result.tsx.as_ref().expect("the IDE route generates TSX");
    let map =
        oxc_sourcemap::SourceMap::from_json_string(&tsx.source_map).expect("valid source map JSON");
    let generated = LineIndex::new(&tsx.code);
    let authored = LineIndex::new(&fixture.source);
    let tokens = map
        .get_tokens()
        .filter(|token| token.get_source_id().is_some())
        .filter_map(|token| {
            Some((
                generated.offset(token.get_dst_line(), token.get_dst_col())?,
                authored.offset(token.get_src_line(), token.get_src_col())?,
            ))
        })
        .collect();
    Compiled {
        code: tsx.code.clone(),
        tokens,
        work,
    }
}

/// Line starts of a text, converting source-map `(line, UTF-16 column)`
/// positions to byte offsets.
struct LineIndex<'t> {
    text: &'t str,
    starts: Vec<usize>,
}

impl<'t> LineIndex<'t> {
    fn new(text: &'t str) -> Self {
        let mut starts = vec![0];
        starts.extend(text.match_indices('\n').map(|(at, _)| at + 1));
        Self { text, starts }
    }

    fn offset(&self, line: u32, utf16_column: u32) -> Option<u32> {
        let start = *self.starts.get(line as usize)?;
        let mut units = 0;
        for (index, ch) in self.text[start..].char_indices() {
            if units >= utf16_column || ch == '\n' {
                return (units == utf16_column).then_some((start + index) as u32);
            }
            units += ch.len_utf16() as u32;
        }
        (units == utf16_column).then_some(self.text.len() as u32)
    }
}

fn assert_parses(compiled: &Compiled, fixture: &SfcFixture) {
    let alloc = Allocator::new();
    let source_type = if fixture.typescript {
        oxc_span::SourceType::tsx()
    } else {
        oxc_span::SourceType::jsx()
    };
    let parsed = verter_parser::oxc_parse::Parser::new(&alloc, &compiled.code, source_type).parse();
    assert!(
        parsed.diagnostics.is_empty(),
        "{}: the generated carrier must parse: {:?}\n{}",
        fixture.name,
        parsed
            .diagnostics
            .iter()
            .map(ToString::to_string)
            .collect::<Vec<_>>(),
        compiled.code
    );
}

#[test]
fn every_contract_fixture_is_guarded_once_per_callback_and_condition() {
    for fixture in ide_fixtures::semantic_suite() {
        let compiled = compile(&fixture);
        assert_parses(&compiled, &fixture);
        assert_eq!(
            compiled.work.callbacks as usize, fixture.guarded_callbacks,
            "{}: every callback under a condition is guarded exactly once\n{}",
            fixture.name, compiled.code
        );
        assert_eq!(
            compiled.work.conditions as usize, fixture.conditions,
            "{}: every authored condition is resolved exactly once",
            fixture.name
        );
        assert_eq!(
            compiled.code.matches("throw 0;").count(),
            fixture.guarded_callbacks,
            "{}: one guard per guarded callback\n{}",
            fixture.name,
            compiled.code
        );
    }
}

#[test]
fn dropping_an_essential_condition_removes_exactly_its_branch() {
    // The removed opening condition is the only difference between the twins:
    // one condition and one branch fewer, every remaining callback still
    // guarded, so the provider-visible difference is exactly the narrowing the
    // removed condition supplied.
    for (complete, dropped) in [
        (
            ide_fixtures::flat_chain(ide_fixtures::SfcRoot::Reactive, 40, false),
            ide_fixtures::flat_chain(ide_fixtures::SfcRoot::Reactive, 40, true),
        ),
        (
            ide_fixtures::deep_positives(40, false),
            ide_fixtures::deep_positives(40, true),
        ),
        (
            ide_fixtures::component_ref_narrowing(40, false),
            ide_fixtures::component_ref_narrowing(40, true),
        ),
    ] {
        let full = compile(&complete);
        let without = compile(&dropped);
        assert_eq!(full.work.conditions, without.work.conditions + 1);
        assert_eq!(without.work.callbacks as usize, dropped.guarded_callbacks);
        assert!(
            without.code.len() < full.code.len(),
            "{}: removing a condition shrinks the surface",
            dropped.name
        );
    }
}

/// The largest ratio between consecutive sizes of `values`.
fn max_growth(values: &[(usize, u64)]) -> f64 {
    values
        .windows(2)
        .map(|pair| pair[1].1 as f64 / pair[0].1.max(1) as f64)
        .fold(0.0, f64::max)
}

/// Fails when any measured quantity more than 2.2x's per doubling of `n`.
fn assert_linear(label: &str, series: &[(&str, Vec<(usize, u64)>)]) -> Result<(), String> {
    for (quantity, values) in series {
        let growth = max_growth(values);
        if growth > 2.2 {
            return Err(format!(
                "{label}: {quantity} grows {growth:.3}x per doubling: {values:?}"
            ));
        }
    }
    Ok(())
}

fn production_series(
    build: impl Fn(usize) -> SfcFixture,
) -> Vec<(&'static str, Vec<(usize, u64)>)> {
    let mut bytes = Vec::new();
    let mut work = Vec::new();
    let mut snapshots = Vec::new();
    for &n in &MATRIX_SIZES {
        let fixture = build(n);
        let compiled = compile(&fixture);
        assert_parses(&compiled, &fixture);
        // Coverage: dropping a callback or a condition cannot pass.
        assert_eq!(
            compiled.work.callbacks as usize, fixture.guarded_callbacks,
            "{}: every callback guarded",
            fixture.name
        );
        assert_eq!(
            compiled.work.conditions as usize, fixture.conditions,
            "{}: every condition emitted once",
            fixture.name
        );
        bytes.push((n, compiled.code.len() as u64));
        let w = compiled.work;
        work.push((
            n,
            w.conditions
                + w.chain_members
                + w.scopes
                + w.callbacks
                + w.outer_refs
                + w.snapshots
                + w.component_branches
                + w.component_functions,
        ));
        snapshots.push((n, w.snapshots + w.outer_refs));
    }
    vec![
        ("generated bytes", bytes),
        ("construction work", work),
        ("snapshot and re-narrowing work", snapshots),
    ]
}

#[test]
fn flat_and_nested_matrices_grow_linearly() {
    assert_linear(
        "flat matrix",
        &production_series(|n| ide_fixtures::flat_matrix(n, false)),
    )
    .unwrap();
    assert_linear(
        "nested matrix",
        &production_series(|n| ide_fixtures::nested_matrix(n, false)),
    )
    .unwrap();
    assert_linear(
        "component matrix",
        &production_series(|n| ide_fixtures::component_matrix(n, false)),
    )
    .unwrap();
}

#[test]
fn component_functions_read_one_flow_of_every_branch() {
    // Each component function, its branch's navigator and each chain block is
    // emitted once, and no component function re-states a condition: a
    // dropped branch, navigator or component fails the counts.
    for &n in &MATRIX_SIZES {
        let compiled = compile(&ide_fixtures::component_matrix(n, false));
        // The root chain's members and the nested `v-if` of every non-`v-else`
        // branch.
        assert_eq!(compiled.work.component_branches as usize, 2 * n - 1);
        // The root chain function; per non-`v-else` branch its navigator, the
        // component's function, the nested chain's block, its navigator and
        // its component's function; the `v-else` navigator and function.
        assert_eq!(
            compiled.work.component_functions as usize,
            1 + 5 * (n - 1) + 2
        );
        assert_eq!(
            compiled.code.matches("function ___VERTER___Comp").count(),
            2 * n - 1,
            "every ref'd component, root branch and slot component has a function"
        );
        for i in 0..n - 1 {
            for condition in [
                format!("state.c{i} !== undefined"),
                format!("state.c{i}.length > 0"),
            ] {
                // Once in the template's flow and once in the component flow.
                assert_eq!(
                    compiled.code.matches(&condition).count(),
                    2,
                    "`{condition}` is emitted once per flow"
                );
            }
        }
        assert!(
            !compiled.code.contains("if(!("),
            "no component function guards with its condition path"
        );
    }
}

#[test]
fn the_growth_check_rejects_predecessor_replay() {
    // The same oracle applied to the reference generator's full predecessor
    // replay (every enclosing positive and predecessor negation re-emitted per
    // callback, as path replay does) must fail, while its snapshot strategy —
    // the representation the production emitter integrates — passes.
    for (label, build) in [
        (
            "flat",
            (|n| reference::flat_matrix(n, 1, false)) as fn(usize) -> reference::Fixture,
        ),
        ("nested", |n| reference::nested_matrix(n, false)),
    ] {
        let series = |strategy| {
            let mut bytes = Vec::new();
            for &n in &MATRIX_SIZES {
                let check = build(n).generate_with(strategy);
                bytes.push((n, check.layout.total_bytes as u64));
            }
            vec![("generated bytes", bytes)]
        };
        assert_linear(label, &series(GuardStrategy::Snapshot)).unwrap();
        assert!(
            assert_linear(label, &series(GuardStrategy::ReplayPath)).is_err(),
            "{label}: predecessor replay must fail the growth check"
        );
    }
}

#[test]
fn every_condition_is_emitted_exactly_once() {
    let n = 256;
    let compiled = compile(&ide_fixtures::flat_matrix(n, false));
    for i in 0..n - 1 {
        let condition = format!("state.c{i} !== undefined");
        assert_eq!(
            compiled.code.matches(&condition).count(),
            1,
            "`{condition}` must be emitted once"
        );
    }
    let compiled = compile(&ide_fixtures::nested_matrix(n, false));
    for i in 0..n / ide_fixtures::NESTED_BRANCHES {
        for value in ["a", "b", "c", "d", "e", "f", "g"] {
            let condition = format!("state.s{i} === '{value}'");
            assert_eq!(
                compiled.code.matches(&condition).count(),
                1,
                "`{condition}` must be emitted once"
            );
        }
    }
}

/// The tokens that place `span` exactly: a token at or before the span's
/// start whose mapped run copies the authored bytes through the span's end
/// (positions inside a run interpolate from its token, as the language server
/// maps them).
fn exact_tokens(source: &str, code: &str, tokens: &[(u32, u32)], span: Span) -> Vec<usize> {
    tokens
        .iter()
        .enumerate()
        .filter(|(_, &(generated, authored))| {
            authored <= span.start && {
                let len = (span.end - authored) as usize;
                let copied = code.get(generated as usize..generated as usize + len);
                copied.is_some() && copied == source.get(authored as usize..span.end as usize)
            }
        })
        .map(|(index, _)| index)
        .collect()
}

/// Every authored span is emitted in place with an exact mapping.
fn check_authored_mappings(
    source: &str,
    code: &str,
    tokens: &[(u32, u32)],
    spans: &[Span],
) -> Result<(), String> {
    for span in spans {
        if exact_tokens(source, code, tokens, *span).is_empty() {
            return Err(format!(
                "authored `{}` at {}..{} has no exact mapping",
                &source[span.start as usize..span.end as usize],
                span.start,
                span.end
            ));
        }
    }
    Ok(())
}

#[test]
fn authored_identifiers_keep_exact_mappings_and_scaffolding_stays_unmapped() {
    let fixture = ide_fixtures::mapping();
    let compiled = compile(&fixture);
    let spans: Vec<Span> = fixture
        .expected
        .iter()
        .filter(|e| e.authored != fixture.canary)
        .map(|e| e.authored)
        .collect();
    assert_eq!(spans.len(), 3, "the mapping fixture plants three reads");
    check_authored_mappings(&fixture.source, &compiled.code, &compiled.tokens, &spans).unwrap();

    // No generated byte of a snapshot declaration or a guard carries a token.
    for scaffold in ["const ___VERTER___o", "if (!___VERTER___flowNarrow("] {
        let mut from = 0;
        while let Some(at) = compiled.code[from..].find(scaffold) {
            let start = (from + at) as u32;
            let end = start + scaffold.len() as u32;
            assert!(
                !compiled
                    .tokens
                    .iter()
                    .any(|&(generated, _)| start <= generated && generated < end),
                "synthetic `{scaffold}` at {start} must be unmapped"
            );
            from = end as usize;
        }
    }

    // A mapping shifted by one authored byte must fail the same check.
    let mut perturbed = compiled.tokens.clone();
    for index in exact_tokens(&fixture.source, &compiled.code, &compiled.tokens, spans[0]) {
        perturbed[index].1 += 1;
    }
    assert!(
        check_authored_mappings(&fixture.source, &compiled.code, &perturbed, &spans).is_err(),
        "a perturbed mapping must fail the mapping check"
    );
}
