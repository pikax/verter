//! Deterministic growth counters for the full matrix.
//!
//! A live provider round trip proves exact diagnostics at one bounded size.
//! These counters prove the same linearity claim at [`super::fixtures::MATRIX_SIZES`]:
//! snapshot construction stays within 2.2× per doubling. Path replay failing
//! that bound is `restored_path_replay_fails_the_growth_oracle`.

use oxc_allocator::Allocator;

use super::fixtures::{self, Fixture, MATRIX_SIZES};
use super::generator::GuardStrategy;
use super::ide_fixtures::{self, SfcFixture};
use super::seam::GenerationWork;
use crate::compile::legacy_test_support::{self, CodegenOptions, VerterCompileOptions};
use crate::compile::VueMacroSemanticInput;
use crate::ide::template::flow::{take_flow_work, FlowWork};

const GROWTH_LIMIT: f64 = 2.2;

fn doubles(samples: &[(usize, u64)], limit: f64) -> Result<(), String> {
    for pair in samples.windows(2) {
        let (small, large) = (pair[0], pair[1]);
        if large.0 != small.0 * 2 {
            return Err(format!("sizes {} → {} do not double", small.0, large.0));
        }
        let ratio = large.1 as f64 / (small.1.max(1) as f64);
        if ratio > limit {
            return Err(format!(
                "{} → {}: {} → {} grows {ratio:.3}×",
                small.0, large.0, small.1, large.1
            ));
        }
    }
    Ok(())
}

fn reference(n: usize, nested: bool, strategy: GuardStrategy) -> (Fixture, GenerationWork, u64) {
    let fixture = if nested {
        fixtures::nested_matrix(n, false)
    } else {
        fixtures::flat_matrix(n, 1, false)
    };
    let check = fixture.generate_with(strategy);
    let bytes = check.layout.total_bytes as u64;
    (fixture, check.work, bytes)
}

fn assert_reference_metric(
    shape: &str,
    metric: &str,
    samples: &[(usize, u64)],
) -> Result<(), String> {
    doubles(samples, GROWTH_LIMIT).map_err(|error| format!("{shape} {metric}: {error}"))
}

/// Snapshot work at 128/256/512/1024 stays linear.
///
/// Path replay failing that bound is the compiler oracle
/// `restored_path_replay_fails_the_growth_oracle`. It is not repeated here:
/// replaying sizes 128/256/512 is quadratic and costs longer than one provider
/// test may spend.
pub fn assert_reference_matrix_growth() {
    for (shape, nested) in [("flat", false), ("nested", true)] {
        let mut bytes = Vec::new();
        let mut callbacks = Vec::new();
        let mut conditions = Vec::new();
        let mut outer_refs = Vec::new();
        let mut transform_ops = Vec::new();
        let mut predecessor_links = Vec::new();
        for &n in &MATRIX_SIZES {
            let (fixture, work, size) = reference(n, nested, GuardStrategy::Snapshot);
            assert_eq!(
                work.callbacks as usize, fixture.authored_callbacks,
                "{shape} {n}: every authored callback is counted"
            );
            assert_eq!(
                work.replayed_terms, 0,
                "{shape} {n}: snapshots never replay paths"
            );
            bytes.push((n, size));
            callbacks.push((n, work.callbacks));
            conditions.push((n, work.conditions));
            outer_refs.push((n, work.outer_refs));
            transform_ops.push((n, work.transform_ops));
            predecessor_links.push((n, work.predecessor_links));
        }
        for (metric, samples) in [
            ("generated bytes", &bytes),
            ("callbacks", &callbacks),
            ("conditions", &conditions),
            ("outer references", &outer_refs),
            ("transform operations", &transform_ops),
            ("predecessor links", &predecessor_links),
        ] {
            assert_reference_metric(shape, metric, samples)
                .unwrap_or_else(|error| panic!("{error}"));
        }
    }
}

fn production_work(fixture: &SfcFixture) -> (u64, FlowWork) {
    let alloc = Allocator::new();
    let options = CodegenOptions {
        filename: Some(format!("{}.vue", fixture.name)),
        target: crate::compile::CompileTarget::TSX,
        embed_ambient_types: false,
        ..CodegenOptions::default()
    };
    let verter_opts = VerterCompileOptions {
        source_map: true,
        ..VerterCompileOptions::default()
    };
    take_flow_work();
    let result = legacy_test_support::compile(
        &fixture.source,
        &options,
        &verter_opts,
        &VueMacroSemanticInput::Unavailable,
        &alloc,
    );
    let work = take_flow_work();
    let bytes = result
        .tsx
        .as_ref()
        .map(|tsx| tsx.code.len() as u64)
        .expect("the IDE route generates TSX");
    (bytes, work)
}

fn work_total(work: FlowWork) -> u64 {
    work.conditions
        + work.chain_members
        + work.scopes
        + work.callbacks
        + work.outer_refs
        + work.snapshots
        + work.component_branches
        + work.component_functions
        + work.scope_links
        + work.callback_discovery
}

type MatrixBuild = fn(usize, bool) -> SfcFixture;

/// Production IDE narrowing at 128/256/512/1024: every callback and condition
/// is counted, and bytes plus construction work stay linear per doubling.
pub fn assert_production_matrix_growth() {
    let shapes: [(&str, MatrixBuild); 4] = [
        ("flat", ide_fixtures::flat_matrix),
        ("nested", ide_fixtures::nested_matrix),
        ("component", ide_fixtures::component_matrix),
        ("nested component", ide_fixtures::nested_component_matrix),
    ];
    for (shape, build) in shapes {
        let mut bytes = Vec::new();
        let mut work_samples = Vec::new();
        for &n in &MATRIX_SIZES {
            let fixture = build(n, false);
            let (size, work) = production_work(&fixture);
            assert_eq!(
                work.callbacks as usize, fixture.guarded_callbacks,
                "{shape} {n}: every callback guarded"
            );
            assert_eq!(
                work.conditions as usize, fixture.conditions,
                "{shape} {n}: every condition emitted once"
            );
            assert!(
                work_total(work) > 0,
                "{shape} {n}: construction work is counted"
            );
            bytes.push((n, size));
            work_samples.push((n, work_total(work)));
        }
        doubles(&bytes, GROWTH_LIMIT).unwrap_or_else(|error| panic!("{shape} bytes: {error}"));
        doubles(&work_samples, GROWTH_LIMIT)
            .unwrap_or_else(|error| panic!("{shape} construction work: {error}"));
    }
}
