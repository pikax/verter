#[test]
fn mappings_are_exact_for_moved_and_non_ascii_authored_bytes() {
    let fixture = fixtures::mapping();
    let (plan, _) = fixture.plan().unwrap();
    let check = generate(&plan, &fixture.source).unwrap();
    check_mappings(&fixture.source, &check, &authored_spans(&plan)).unwrap();

    let mut after_non_ascii = 0;
    for expected in &fixture.expected {
        let generated = check.generated_offsets(expected.authored.start);
        assert_eq!(generated.len(), 1, "{expected:?}");
        let at = generated[0] as usize;
        assert_eq!(
            &check.code[at..at + expected.authored.len() as usize],
            &fixture.source[expected.authored.start as usize..expected.authored.end as usize]
        );
        let line = fixture.source[..expected.authored.start as usize]
            .lines()
            .last()
            .unwrap_or_default();
        if !line.is_ascii() {
            // The generated line differs in both byte and UTF-16 position.
            assert_ne!(at, expected.authored.start as usize);
            after_non_ascii += 1;
        }
    }
    assert_eq!(
        after_non_ascii, 2,
        "two reported identifiers follow non-ASCII text"
    );

    // `<li v-for="item in items" v-if="…">`: the condition is authored after
    // the `v-for` but emitted before it, and both keep exact mappings.
    let v_for = fixture.source.find("item in items").unwrap() as u32;
    let condition = fixture.source.rfind("u.kind === 'a'").unwrap() as u32;
    assert!(v_for < condition);
    let v_for_at = check.generated_offsets(v_for)[0];
    let condition_at = check.generated_offsets(condition)[0];
    assert!(condition_at < v_for_at, "the condition is moved ahead");

    // Synthetic scaffolding carries no authored provenance.
    for synthetic in [
        "__props.",
        "__VerterFlow.",
        "__verter_o0",
        "throw 0",
        "if (",
    ] {
        for (at, _) in check.code.match_indices(synthetic) {
            for offset in at..at + synthetic.len() {
                assert_eq!(
                    check.source_offset(offset as u32),
                    None,
                    "{synthetic} at {at}"
                );
            }
        }
    }
}

#[test]
fn a_perturbed_mapping_fails_the_mapping_oracle() {
    let fixture = fixtures::mapping();
    let (plan, _) = fixture.plan().unwrap();
    let check = generate(&plan, &fixture.source).unwrap();
    let spans = authored_spans(&plan);
    check_mappings(&fixture.source, &check, &spans).unwrap();

    for index in [0, check.mappings.len() / 2, check.mappings.len() - 1] {
        let mut shifted = check.clone();
        let Mapping { generated, source } = shifted.mappings[index];
        shifted.mappings[index] = Mapping {
            generated,
            source: Span::new(source.start + 1, source.end + 1),
        };
        assert!(
            check_mappings(&fixture.source, &shifted, &spans).is_err(),
            "shifting mapping {index} must be detected"
        );
    }
    let mut dropped = check.clone();
    dropped.mappings.remove(1);
    assert!(check_mappings(&fixture.source, &dropped, &spans).is_err());
}
