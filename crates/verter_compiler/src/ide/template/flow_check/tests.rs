/// The deepest fixtures nest a few hundred template levels; the template
/// parse recurses per level, so they run on a thread with room for it.
fn with_stack<T: Send + 'static>(run: impl FnOnce() -> T + Send + 'static) -> T {
    std::thread::Builder::new()
        .stack_size(64 << 20)
        .spawn(run)
        .expect("spawn the fixture thread")
        .join()
        .expect("the fixture thread completed")
}

fn walk<'p>(items: &'p [Item], visit: &mut impl FnMut(&'p Item)) {
    for item in items {
        visit(item);
        match item {
            Item::Chain(chain) => {
                for branch in &chain.branches {
                    walk(&branch.items, visit);
                }
            }
            Item::Frame(frame) => walk(&frame.items, visit),
            Item::Callback(_) | Item::Expr(_) => {}
        }
    }
}

fn callbacks(plan: &CheckPlan) -> Vec<&Callback> {
    let mut out = Vec::new();
    walk(&plan.items, &mut |item| {
        if let Item::Callback(callback) = item {
            out.push(callback);
        }
    });
    out
}

fn ref_texts(plan: &CheckPlan) -> Vec<Vec<String>> {
    callbacks(plan)
        .iter()
        .map(|callback| callback.outer_refs.iter().map(|r| r.text.clone()).collect())
        .collect()
}

fn expr_spans(expr: &ResolvedExpr, out: &mut Vec<Span>) {
    out.extend(expr.pieces.iter().filter_map(|piece| match piece {
        Piece::Authored(span) => Some(*span),
        Piece::Synthetic(_) => None,
    }));
}

/// Every authored span a plan carries into the check.
fn authored_spans(plan: &CheckPlan) -> Vec<Span> {
    let mut out = Vec::new();
    walk(&plan.items, &mut |item| match item {
        Item::Chain(chain) => {
            for branch in &chain.branches {
                if let Some(condition) = &branch.condition {
                    expr_spans(condition, &mut out);
                }
            }
        }
        Item::Frame(frame) => match &frame.binding {
            FrameBinding::VFor {
                aliases, source, ..
            } => {
                out.push(*aliases);
                expr_spans(source, &mut out);
            }
            FrameBinding::Slot { pattern, .. } => out.push(*pattern),
        },
        Item::Callback(callback) => match &callback.function {
            CallbackFunction::Authored { expr, .. } => expr_spans(expr, &mut out),
            CallbackFunction::Handler { body, .. } => expr_spans(body, &mut out),
        },
        Item::Expr(expr) => expr_spans(&expr.expr, &mut out),
    });
    out
}

fn rendered_len(expr: &ResolvedExpr) -> usize {
    expr.pieces
        .iter()
        .map(|piece| match piece {
            Piece::Authored(span) => span.len() as usize,
            Piece::Synthetic(text) => text.len(),
        })
        .sum()
}

/// The stated algorithmic bound on generated bytes: helpers, declarations
/// and header once; per chain 16 bytes, per branch 16 bytes plus its
/// resolved condition; per frame 64 bytes plus its aliases or pattern,
/// resolved source and contract; per value 32 bytes plus its contract; per
/// callback 64 bytes plus its contract and resolved function; per outer
/// reference 160 bytes plus three copies of its text. Path length appears
/// nowhere: a branch, frame or callback costs the same at any depth.
fn byte_bound(plan: &CheckPlan) -> usize {
    let mut bound = HELPERS.len() + plan.declarations.len() + plan.parameters.len() + 40;
    walk(&plan.items, &mut |item| {
        bound += match item {
            Item::Chain(chain) => {
                16 + chain
                    .branches
                    .iter()
                    .map(|b| 16 + b.condition.as_ref().map_or(0, rendered_len))
                    .sum::<usize>()
            }
            Item::Frame(frame) => match &frame.binding {
                FrameBinding::VFor {
                    aliases, source, ..
                } => 64 + aliases.len() as usize + rendered_len(source),
                FrameBinding::Slot { pattern, contract } => {
                    64 + pattern.len() as usize + contract.len()
                }
            },
            Item::Callback(callback) => {
                let function = match &callback.function {
                    CallbackFunction::Authored { expr, .. } => rendered_len(expr),
                    CallbackFunction::Handler { parameters, body } => {
                        parameters.len() + rendered_len(body)
                    }
                };
                64 + callback.contract.len()
                    + function
                    + callback
                        .outer_refs
                        .iter()
                        .map(|outer| 160 + 3 * outer.text.len())
                        .sum::<usize>()
            }
            Item::Expr(expr) => {
                32 + expr.contract.as_ref().map_or(0, String::len) + rendered_len(&expr.expr)
            }
        }
    });
    bound
}

