#[derive(Debug, Clone, Copy)]
struct Sample {
    n: usize,
    bytes: u64,
    helper_and_declaration_bytes: u64,
    transform_ops: u64,
    outer_refs: u64,
    conditions: u64,
    predecessor_links: u64,
    scope_links: u64,
    callbacks: u64,
    resolved_conditions: u64,
}

fn sample(
    fixture: &Fixture,
    n: usize,
    strategy: GuardStrategy,
) -> (Sample, CheckPlan, GeneratedCheck) {
    let (plan, work) = fixture.plan().unwrap();
    let check = generate_with(&plan, &fixture.source, strategy).unwrap();
    let sample = Sample {
        n,
        bytes: check.layout.total_bytes as u64,
        helper_and_declaration_bytes: (check.layout.helper_bytes + check.layout.declaration_bytes)
            as u64,
        transform_ops: check.work.transform_ops,
        outer_refs: check.work.outer_refs,
        conditions: check.work.conditions,
        predecessor_links: check.work.predecessor_links,
        scope_links: check.work.scope_links,
        callbacks: check.work.callbacks,
        resolved_conditions: work.conditions_resolved,
    };
    (sample, plan, check)
}

/// At most `limit` growth per doubling of the fixture size.
fn growth(samples: &[Sample], metric: fn(&Sample) -> u64, limit: f64) -> Result<(), String> {
    for pair in samples.windows(2) {
        let (small, large) = (&pair[0], &pair[1]);
        assert_eq!(large.n, small.n * 2, "samples double");
        let ratio = metric(large) as f64 / metric(small).max(1) as f64;
        if ratio > limit {
            return Err(format!(
                "{} → {}: {} → {} grows {ratio:.3}x",
                small.n,
                large.n,
                metric(small),
                metric(large)
            ));
        }
    }
    Ok(())
}

type Metric = (&'static str, fn(&Sample) -> u64);

const METRICS: [Metric; 9] = [
    ("generated bytes", |s| s.bytes),
    ("helper and declaration bytes", |s| {
        s.helper_and_declaration_bytes
    }),
    ("transform operations", |s| s.transform_ops),
    ("outer references", |s| s.outer_refs),
    ("emitted conditions", |s| s.conditions),
    ("predecessor links", |s| s.predecessor_links),
    ("scope links", |s| s.scope_links),
    ("callbacks", |s| s.callbacks),
    ("resolved conditions", |s| s.resolved_conditions),
];

#[test]
fn chains_and_nested_scopes_grow_linearly() {
    with_stack(|| {
        for shape in ["flat", "nested"] {
            let mut samples = Vec::new();
            for &n in &MATRIX_SIZES {
                let fixture = match shape {
                    "flat" => fixtures::flat_matrix(n, 1, false),
                    _ => fixtures::nested_matrix(n, false),
                };
                let (sample, plan, check) = sample(&fixture, n, GuardStrategy::Snapshot);
                assert_eq!(check.layout.callbacks.len(), n, "{}", fixture.name);
                assert_eq!(sample.callbacks, n as u64, "{}", fixture.name);
                assert!(
                    check
                        .layout
                        .callbacks
                        .iter()
                        .all(|site| site.outer_refs > 0),
                    "{}: every callback re-narrows what it reads",
                    fixture.name
                );
                assert_eq!(check.layout.helper_bytes, HELPERS.len());
                let bound = byte_bound(&plan);
                assert!(
                    check.layout.total_bytes <= bound,
                    "{}: {} bytes exceed the stated bound {bound}",
                    fixture.name,
                    check.layout.total_bytes
                );
                samples.push(sample);
            }
            for (name, metric) in METRICS {
                growth(&samples, metric, 2.2)
                    .unwrap_or_else(|e| panic!("{shape} {name}: {e}\n{samples:#?}"));
            }
        }
    });
}

#[test]
fn callback_count_scales_without_path_expansion() {
    with_stack(|| {
        let mut samples = Vec::new();
        for (index, callbacks) in [1, 2, 4, 8].into_iter().enumerate() {
            let fixture = fixtures::flat_matrix(256, callbacks, false);
            let (mut sample, _, check) = sample(&fixture, 1 << index, GuardStrategy::Snapshot);
            sample.bytes -= sample.helper_and_declaration_bytes;
            // A callback costs the same at the second branch as at the last:
            // no byte of a callback depends on how many branches precede it.
            let sites: Vec<u32> = check
                .layout
                .callbacks
                .iter()
                .map(|site| site.generated.len() - 3 * site.authored.len())
                .collect();
            let (min, max) = (sites.iter().min().unwrap(), sites.iter().max().unwrap());
            assert!(
                max - min <= 8,
                "{}: callback sizes {min}..{max}",
                fixture.name
            );
            samples.push(sample);
        }
        growth(&samples, |s| s.bytes, 2.2).unwrap();
        growth(&samples, |s| s.outer_refs, 2.2).unwrap();
    });
}

#[test]
fn restored_path_replay_fails_the_growth_oracle() {
    with_stack(|| {
        for shape in ["flat", "nested"] {
            let mut samples = Vec::new();
            for &n in &MATRIX_SIZES[..3] {
                let fixture = match shape {
                    "flat" => fixtures::flat_matrix(n, 1, false),
                    _ => fixtures::nested_matrix(n, false),
                };
                samples.push(sample(&fixture, n, GuardStrategy::ReplayPath).0);
            }
            assert!(
                growth(&samples, |s| s.bytes, 2.2).is_err(),
                "{shape}: replaying the path into every callback must fail the oracle: {samples:#?}"
            );
        }
    });
}

