#[test]
fn every_semantic_fixture_plans_and_generates_from_its_source() {
    for fixture in fixtures::semantic_suite() {
        let (plan, work) = fixture.plan().unwrap();
        let check = generate(&plan, &fixture.source).unwrap();

        let mut conditions = 0;
        walk(&plan.items, &mut |item| {
            if let Item::Chain(chain) = item {
                conditions += chain
                    .branches
                    .iter()
                    .filter(|b| b.condition.is_some())
                    .count() as u64;
            }
        });
        assert_eq!(work.conditions_resolved, conditions, "{}", fixture.name);
        assert_eq!(check.work.conditions, conditions, "{}", fixture.name);
        assert_eq!(
            work.callbacks as usize, fixture.authored_callbacks,
            "{}",
            fixture.name
        );
        assert_eq!(
            check.layout.callbacks.len(),
            fixture.authored_callbacks,
            "{}: every authored callback is emitted",
            fixture.name
        );
        check_mappings(&fixture.source, &check, &authored_spans(&plan))
            .unwrap_or_else(|e| panic!("{}: {e}", fixture.name));
        assert!(
            check.layout.total_bytes <= byte_bound(&plan),
            "{}",
            fixture.name
        );
    }
}

#[test]
fn the_plan_carries_every_callback_and_scope_shape() {
    let fixture = fixtures::contextual(Root::MutableProperty, false);
    let contextual = fixture.plan().unwrap().0;
    let shapes: Vec<&str> = callbacks(&contextual)
        .iter()
        .map(|callback| match &callback.function {
            CallbackFunction::Authored {
                guard: GuardSite::Expression { .. },
                ..
            } => "expression body",
            CallbackFunction::Authored {
                expr,
                guard: GuardSite::Block { .. },
            } => {
                if fixture.source[expr.span.start as usize..].starts_with("function") {
                    "function expression"
                } else {
                    "block body"
                }
            }
            CallbackFunction::Handler { parameters, .. } => {
                assert_eq!(parameters, "$event");
                "generated handler"
            }
        })
        .collect();
    for shape in [
        "expression body",
        "block body",
        "function expression",
        "generated handler",
    ] {
        assert!(shapes.contains(&shape), "missing {shape}: {shapes:?}");
    }

    let lexical = fixtures::lexical(Root::MutableProperty).plan().unwrap().0;
    let mut bindings = Vec::new();
    walk(&lexical.items, &mut |item| {
        if let Item::Frame(frame) = item {
            bindings.push(match &frame.binding {
                FrameBinding::VFor { arity, .. } => format!("v-for/{arity}"),
                FrameBinding::Slot { .. } => "v-slot".to_string(),
            });
        }
    });
    assert_eq!(bindings, ["v-for/1", "v-for/2", "v-slot"]);

    // A chain nested inside a branch, and a chain member that carries its own
    // `v-for` (the frame opens inside the branch, after its condition).
    let nested = fixtures::deep_positives(3, false).plan().unwrap().0;
    let Item::Chain(outer) = &nested.items[0] else {
        panic!("the outermost level is a chain")
    };
    assert!(matches!(outer.branches[0].items[1], Item::Chain(_)));
    let lifted = fixtures::mapping().plan().unwrap().0;
    let Item::Chain(member_with_v_for) = &lifted.items[1] else {
        panic!("the second element is its own chain")
    };
    assert!(matches!(
        member_with_v_for.branches[0].items[0],
        Item::Frame(_)
    ));
}

#[test]
fn outer_refs_follow_template_and_callback_lexical_identity() {
    let refs = ref_texts(&fixtures::lexical(Root::MutableProperty).plan().unwrap().0);
    // `v-for` alias: the alias and its member chain, every prefix first.
    assert_eq!(
        refs[0],
        ["take", "item", "__props.u", "item!.label", "__props.u!.a"]
    );
    // Destructured alias and index: plain template locals.
    assert_eq!(
        refs[1],
        ["take", "label", "index", "__props.u", "__props.u!.a"]
    );
    // Slot parameter.
    assert_eq!(
        refs[2],
        ["take", "row", "__props.u", "row!.note", "__props.u!.a"]
    );
    // A callback-local const is not an outer reference.
    assert_eq!(refs[3], ["__props.u", "take", "__props.u!.a"]);
    // A parameter shadowing the narrowed root is not the root.
    assert_eq!(refs[4], ["takeNumber"]);

    // A nested authored closure reads in its own flow: nothing inside it is
    // an outer reference of the callback.
    let refs = ref_texts(&fixtures::mutation_and_nested_closure().plan().unwrap().0);
    assert_eq!(refs[0], ["take", "__props.note"]);
    assert!(refs[1].is_empty(), "{:?}", refs[1]);
    assert_eq!(refs[2], ["take", "__props.note"]);
}

fn branches(plan: &mut CheckPlan) -> &mut Vec<Branch> {
    match &mut plan.items[0] {
        Item::Chain(chain) => &mut chain.branches,
        _ => panic!("the fixture opens with its chain"),
    }
}

#[test]
fn planted_branch_faults_are_refused() {
    let fixture = fixtures::flat_chain(Root::MutableProperty, 5, false);
    let source = &fixture.source;
    let plan = fixture.plan().unwrap().0;
    assert!(generate(&plan, source).is_ok());
    let first = branches(&mut plan.clone())[0].key;
    assert_eq!(branches(&mut plan.clone())[1].kind, BranchKind::ElseIf);

    let mut missing_link = plan.clone();
    branches(&mut missing_link)[2].predecessor = None;
    assert!(matches!(
        generate(&missing_link, source),
        Err(PlanError::PredecessorMismatch { found: None, .. })
    ));

    let mut wrong_link = plan.clone();
    branches(&mut wrong_link)[3].predecessor = Some(first);
    assert!(matches!(
        generate(&wrong_link, source),
        Err(PlanError::PredecessorMismatch { found: Some(found), .. }) if found == first
    ));

    let mut missing_condition = plan.clone();
    branches(&mut missing_condition)[1].condition = None;
    assert!(matches!(
        generate(&missing_condition, source),
        Err(PlanError::MissingCondition { .. })
    ));

    let mut else_condition = plan.clone();
    let condition = branches(&mut else_condition)[0].condition.clone();
    branches(&mut else_condition)[4].condition = condition;
    assert!(matches!(
        generate(&else_condition, source),
        Err(PlanError::ElseWithCondition { .. })
    ));

    let mut headless = plan.clone();
    branches(&mut headless).remove(0);
    branches(&mut headless)[0].predecessor = None;
    assert!(matches!(
        generate(&headless, source),
        Err(PlanError::ChainMustOpenWithIf { .. })
    ));

    let mut reordered = plan.clone();
    branches(&mut reordered).swap(3, 4);
    assert!(generate(&reordered, source).is_err());

    let mut stray_branch = plan.clone();
    branches(&mut stray_branch)[1].scope = ScopeKey(99);
    assert!(matches!(
        generate(&stray_branch, source),
        Err(PlanError::ScopeMismatch { .. })
    ));
}

fn first_branch_callback(plan: &mut CheckPlan, index: usize) -> &mut Callback {
    let Item::Chain(chain) = &mut plan.items[0] else {
        panic!("the fixture opens with its chain")
    };
    let Item::Callback(callback) = &mut chain.branches[0].items[index] else {
        panic!("item {index} of the first branch is a callback")
    };
    callback
}

#[test]
fn planted_context_faults_are_refused() {
    let fixture = fixtures::lexical(Root::MutableProperty);
    let plan = fixture.plan().unwrap().0;
    let source = &fixture.source;

    // A callback inside the `v-for` frame claimed by the root scope.
    let mut wrong_scope = plan.clone();
    let root = wrong_scope.root;
    let Item::Chain(chain) = &mut wrong_scope.items[0] else {
        panic!()
    };
    let Item::Frame(frame) = &mut chain.branches[0].items[0] else {
        panic!()
    };
    let Item::Chain(inner) = &mut frame.items[0] else {
        panic!()
    };
    let Item::Callback(callback) = &mut inner.branches[0].items[0] else {
        panic!()
    };
    callback.scope = root;
    assert!(matches!(
        generate(&wrong_scope, source),
        Err(PlanError::ScopeMismatch { .. })
    ));

    // A frame linked to the wrong parent scope.
    let mut wrong_parent = plan.clone();
    let Item::Chain(chain) = &mut wrong_parent.items[0] else {
        panic!()
    };
    let Item::Frame(frame) = &mut chain.branches[0].items[0] else {
        panic!()
    };
    frame.parent = frame.scope;
    assert!(matches!(
        generate(&wrong_parent, source),
        Err(PlanError::FrameParentMismatch { .. })
    ));

    // An outer reference taken from another callback.
    let mut foreign_ref = plan.clone();
    let other = callbacks(&plan)[4].outer_refs[0].clone();
    first_branch_callback(&mut foreign_ref, 3)
        .outer_refs
        .push(other);
    assert!(matches!(
        generate(&foreign_ref, source),
        Err(PlanError::OuterRefOutsideCallback { .. })
    ));

    // A callback with no contract.
    let mut no_contract = plan.clone();
    first_branch_callback(&mut no_contract, 3).contract.clear();
    assert!(matches!(
        generate(&no_contract, source),
        Err(PlanError::MissingContract { .. })
    ));

    // The same authored callback planned twice.
    let mut duplicated = plan.clone();
    let Item::Chain(chain) = &mut duplicated.items[0] else {
        panic!()
    };
    let copy = chain.branches[0].items[3].clone();
    chain.branches[0].items.push(copy);
    assert!(matches!(
        generate(&duplicated, source),
        Err(PlanError::AuthoredOverlap { .. })
    ));

    // A template whose callback has no contextual contract is not planned.
    let refused = build_plan(
        "<template><i @click=\"() => take(1)\"></i></template>",
        &PlanContext {
            declarations: "",
            parameters: "()",
            bindings: &[("take", BindingType::SetupConst)],
            contracts: &[],
        },
    );
    assert_eq!(
        refused.unwrap_err(),
        BuildError::MissingContract {
            key: "@click".into()
        }
    );
}

