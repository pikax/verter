/// The Verter disposition of a svelte-COMPILE axis.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum CompileDisposition {
    /// `derive_component_name(requested_name)` == the oracle's `emitted_name` for every
    /// row of this axis (the deconfliction UNION, oracle-derived). The DEFAULT for a
    /// svelte-compile axis.
    NameParity,
    /// svelte compiles + reserves the inner runtime reference, but Verter FAIL-CLOSES
    /// before projection: the shared `SourceType::tsx()` reparse rejects the `<T>x` angle
    /// assertion as JSX, so `build_component_scope_facts` returns `Err`. Name-parity is
    /// not asserted (there is no derived name to compare).
    VerterFailClosed,
}

/// The Verter disposition of a svelte-REJECT axis (svelte emits no component/name, so
/// this is a Verter/OXC CHARACTERIZATION, never a svelte-parity claim).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum RejectDisposition {
    /// Verter's projection DEFENSIVELY erases the svelte-hard-error construct, so the
    /// planted probe name(s) are NOT fabricated into the reserved set.
    DefensiveErase,
    /// Verter's projection PRESERVES the construct (a known reject-parity gap — svelte
    /// rejects the whole component; Verter does not).
    PreservedGap,
}

/// The explicit non-`NameParity` COMPILE axes. A svelte-compile axis absent here is
/// `NameParity`; a svelte-reject axis MUST instead appear in [`REJECT_CHARACTERIZATIONS`].
const COMPILE_DISPOSITION_OVERRIDES: &[(&str, CompileDisposition)] =
    &[("type_assertion_angle", CompileDisposition::VerterFailClosed)];

/// The EXACT Verter observation for each svelte-REJECT axis. `exact_conflicts` is the
/// COMPLETE `name_conflicts` set Verter's projection produces for the source — a
/// Verter/OXC characterization pinned so a LEAKED name REDs (exact-observation: not just `!contains`).
/// `erased_probes` are the planted names svelte would reserve if it compiled but Verter
/// must NOT fabricate (asserted absent, with a clearer message than the exact-set check).
struct RejectCharacterization {
    axis: &'static str,
    disposition: RejectDisposition,
    exact_conflicts: &'static [&'static str],
    erased_probes: &'static [&'static str],
}

