/// The kind name of an expression, for the pre/post-projection carrier assertions.
fn expr_kind_name(expr: &Expression<'_>) -> &'static str {
    match expr {
        Expression::TSAsExpression(_) => "TSAsExpression",
        Expression::TSSatisfiesExpression(_) => "TSSatisfiesExpression",
        Expression::TSNonNullExpression(_) => "TSNonNullExpression",
        Expression::TSInstantiationExpression(_) => "TSInstantiationExpression",
        Expression::TSTypeAssertion(_) => "TSTypeAssertion",
        Expression::Identifier(_) => "Identifier",
        _ => "other",
    }
}

/// The init expression kind of the first `const X = <init>;` statement of a program.
fn first_const_init_kind(program: &Program<'_>) -> &'static str {
    let Statement::VariableDeclaration(vd) = &program.body[0] else {
        panic!("expected a leading variable declaration");
    };
    let init = vd.declarations[0]
        .init
        .as_ref()
        .expect("the const has an initializer");
    expr_kind_name(init)
}

