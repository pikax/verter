//! The svelte component-name scope-view conformance matrix.
//!
//! This is the SINGLE authority tying [`SvelteScopeProjection`] to
//! svelte@[`SVELTE_ORACLE_VERSION`]. It has two independent halves:
//!
//! 1. A SOURCE-DERIVED handler rail over svelte's own `remove_typescript_nodes` visitor
//!    inventory: the OXC-parsed `const visitors` handler set is set-equal to the
//!    [`HandlerCoverage`] rows (bijection), every handler body carries a fingerprint
//!    drift tripwire, and every handler names ≥1 corpus AXIS it is exercised by.
//!
//! 2. An ORACLE-DERIVED name-parity matrix. The committed corpus
//!    (`tests/fixtures/svelte/name_parity_corpus.json`) is GENERATED by
//!    `scripts/gen-svelte-name-parity-corpus.mjs`, which plants an identifier per
//!    construct, sets `name=<planted identifier>`, runs the PINNED svelte compiler
//!    OFFLINE, and records SVELTE'S OWN outcome (the emitted component-function name, a
//!    reject code, or — for a construct svelte CRASHES uncoded on, e.g. a lone class index
//!    signature — a `crash` outcome). The emitted-name pins therefore come from svelte itself, NOT from
//!    reading the projection's output — so a projection that drops a reserved name REDs
//!    against svelte's own outcome instead of matching a stale hand-authored value (the
//!    prior hand-pinned three-set matrix was self-confirming: a buggy projection plus a
//!    matching wrong pin both passed).
//!
//! For a svelte-COMPILE row the matrix asserts Verter's observable name derivation
//! equals svelte's emitted name (the deconfliction UNION, oracle-derived). A svelte-
//! REJECT row carries NO svelte name (svelte emits no component), so name-parity is
//! VACUOUS: Verter's disposition is characterized SEPARATELY and honestly (a defensive
//! erase, or a preserved known-gap) with an EXACT reserved-set observation — a Verter/OXC
//! CHARACTERIZATION, never a svelte-parity claim. A svelte-CRASH row (a construct svelte
//! crashes uncoded on — e.g. a lone class index signature) is VACUOUS the same way: Verter
//! does NOT crash — it defensively erases the construct, characterized separately. The
//! `<T>x` angle assertion is a svelte-compile row Verter FAIL-CLOSES on (the shared
//! `SourceType::tsx()` reparse rejects it).
//!
//! Hermetic by default: the matrix consumes ONLY the vendored source + the committed
//! corpus + the production projection (no live svelte at test time, per the Testing-
//! Hermeticity rule). An optional `svelte-oracle`-gated freshness rail re-runs the
//! generator's `--check` against the installed pinned compiler.

