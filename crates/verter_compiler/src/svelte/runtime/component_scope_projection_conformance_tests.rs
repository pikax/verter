/// Slice `source` at `span`. When `source` is `'static` the returned slice is `'static`.
fn span_slice(source: &str, span: Span) -> &str {
    &source[span.start as usize..span.end as usize]
}

/// Normalize a handler body for fingerprinting: LF-normalize line endings (cross-
/// platform), keeping every content byte significant so a one-character edit trips the
/// tripwire.
fn normalize(body: &str) -> String {
    body.replace("\r\n", "\n")
}

/// A dependency-free, cross-platform-stable FNV-1a 64-bit fingerprint (16 hex chars).
fn fnv1a_hex(bytes: &[u8]) -> String {
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for &b in bytes {
        hash ^= u64::from(b);
        hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
    }
    format!("{hash:016x}")
}

/// Parse the vendored `const visitors = {...}` object with OXC and return, per handler,
/// a fingerprint of its normalized body source. The two aliased handlers
/// (`FunctionExpression` / `FunctionDeclaration` → `remove_this_param`) resolve to the
/// helper's body, so their fingerprints reflect the helper.
fn extract_handler_bodies() -> BTreeMap<String, String> {
    let alloc = Allocator::default();
    let program = reparse_module(&alloc, VENDORED_REMOVE_TS_NODES)
        .expect("vendored remove_typescript_nodes.js must parse cleanly under tsx");

    // The `remove_this_param` helper body (the alias target).
    let mut this_param_body: Option<&str> = None;
    for stmt in &program.body {
        if let Statement::FunctionDeclaration(func) = stmt {
            if func.id.as_ref().map(|id| id.name.as_str()) == Some("remove_this_param") {
                this_param_body = Some(span_slice(VENDORED_REMOVE_TS_NODES, func.span));
            }
        }
    }
    let this_param_body =
        this_param_body.expect("`remove_this_param` helper not found in vendored source");

    // The `const visitors = { ... }` object expression.
    let visitors = program
        .body
        .iter()
        .find_map(|stmt| {
            let Statement::VariableDeclaration(vd) = stmt else {
                return None;
            };
            let decl = vd.declarations.first()?;
            let BindingPattern::BindingIdentifier(id) = &decl.id else {
                return None;
            };
            if id.name.as_str() != "visitors" {
                return None;
            }
            match decl.init.as_ref()? {
                Expression::ObjectExpression(obj) => Some(obj),
                _ => None,
            }
        })
        .expect("`const visitors = {...}` object not found in vendored source");

    let mut out = BTreeMap::new();
    for property in &visitors.properties {
        let ObjectPropertyKind::ObjectProperty(prop) = property else {
            panic!("unexpected spread element in the visitors object");
        };
        let PropertyKey::StaticIdentifier(key) = &prop.key else {
            panic!("unexpected non-identifier visitor handler key");
        };
        let name = key.name.as_str().to_string();
        let body = match &prop.value {
            // `FunctionExpression: remove_this_param` / `FunctionDeclaration: remove_this_param`.
            Expression::Identifier(id) if id.name.as_str() == "remove_this_param" => {
                this_param_body
            }
            // A method-shorthand handler — its value is the function expression.
            other => span_slice(VENDORED_REMOVE_TS_NODES, other.span()),
        };
        let previous = out.insert(name.clone(), fnv1a_hex(normalize(body).as_bytes()));
        assert!(
            previous.is_none(),
            "duplicate visitor handler `{name}` in vendored source"
        );
    }
    out
}

/// Run the production scope-facts path over an instance-only `source`.
fn run_result(source: &str) -> Result<ComponentScopeFacts, UserImportSlot> {
    let alloc = Allocator::default();
    let imports = classify_script_imports_from_sources(None, Some(source));
    let template_decls = FxHashSet::default();
    let exprs = ExprArena::new();
    build_component_scope_facts(
        &alloc,
        None,
        Some(source),
        &imports,
        &template_decls,
        &exprs,
    )
}

/// Run the production path and require clean facts.
fn run(source: &str) -> ComponentScopeFacts {
    run_result(source)
        .unwrap_or_else(|slot| panic!("expected clean facts for {source:?}, got Err({slot:?})"))
}

/// An options carrier with an explicit `name` override (the deconfliction input).
fn opts_named(name: &str) -> SvelteRuntimeOptions {
    SvelteRuntimeOptions {
        filename: Some("App.svelte".to_string()),
        name: Some(name.to_string()),
        ..Default::default()
    }
}

/// Verter's OBSERVABLE derived component-function name for `requested_name` over
/// `source` — `derive_component_name(name, name_conflicts)`, the production derivation.
fn derived_name(source: &str, requested_name: &str) -> String {
    derive_component_name(&opts_named(requested_name), &run(source).name_conflicts())
}

/// Assert a fact SET equals the pinned exact set (complete equality, not `contains`).
fn assert_set_eq(actual: &FxHashSet<String>, expected: &[&str], source: &str, label: &str) {
    let actual_sorted: BTreeSet<&str> = actual.iter().map(String::as_str).collect();
    let expected_sorted: BTreeSet<&str> = expected.iter().copied().collect();
    assert_eq!(
        actual_sorted, expected_sorted,
        "{label} mismatch for source {source:?}"
    );
}

/// Wrap a script snippet in a minimal instance-script component. Verter's PUBLIC client
/// compile fails closed on a `<script lang="ts">` body (TypeScript emit is unsupported),
/// so the full-compile E2E rails drive a PLAIN `<script>` and use JS-compatible sources
/// (a JS snippet's `name` deconfliction is identical to the corpus's `lang="ts"` wrap —
/// the reserved surface is the same). The exhaustive TS name-parity is proven at the
/// scope-facts level (which DOES reparse TS), the rails prove the client-emit wiring.
fn wrap_component(source: &str) -> String {
    format!("<script>{source}</script><div></div>")
}

/// Drive Verter's PUBLIC client compile with an explicit `name`, returning the emitted
/// module code (or the fail-closed error).
fn compile_component(source: &str, name: &str) -> Result<String, ClientCompileError> {
    let wrapped = wrap_component(source);
    let alloc = Allocator::default();
    let parsed = parse_svelte(&wrapped);
    let opts = opts_named(name);
    compile_client(&wrapped, &parsed, &opts, &alloc, false, false).map(|module| module.code)
}

/// Extract the emitted component-function name from client JS: the `function <NAME>(`
/// whose first parameter is `$$anchor` (svelte-5 client component signature).
fn emitted_component_name(js: &str) -> Option<String> {
    for marker in ["export default function ", "function "] {
        let mut from = 0;
        while let Some(rel) = js[from..].find(marker) {
            let start = from + rel + marker.len();
            let rest = &js[start..];
            if let Some(paren) = rest.find('(') {
                let name = rest[..paren].trim();
                let after = rest[paren + 1..].trim_start();
                if after.starts_with("$$anchor") && !name.is_empty() {
                    return Some(name.to_string());
                }
            }
            from = start;
        }
    }
    None
}

