fn reject_characterization(axis: &str) -> Option<&'static RejectCharacterization> {
    REJECT_CHARACTERIZATIONS.iter().find(|r| r.axis == axis)
}

/// The EXACT Verter `name_conflicts` observation for each svelte-CRASH axis. svelte CRASHES
/// uncoded (an uncoded `TypeError`, not a typed diagnostic — e.g. a lone class index
/// signature), so name-parity is VACUOUS. Verter does NOT crash: its projection defensively
/// erases the construct and reserves EXACTLY these names (a leaked name REDs). A Verter/OXC
/// characterization, NEVER a svelte-parity claim.
const CRASH_CHARACTERIZATIONS: &[(&str, &[&str])] = &[("class_index_signature", &["C"])];

fn crash_characterization(axis: &str) -> Option<&'static [&'static str]> {
    CRASH_CHARACTERIZATIONS
        .iter()
        .find(|(a, _)| *a == axis)
        .map(|(_, c)| *c)
}

fn compile_disposition(axis: &str) -> CompileDisposition {
    COMPILE_DISPOSITION_OVERRIDES
        .iter()
        .find(|(a, _)| *a == axis)
        .map(|(_, d)| *d)
        .unwrap_or(CompileDisposition::NameParity)
}

