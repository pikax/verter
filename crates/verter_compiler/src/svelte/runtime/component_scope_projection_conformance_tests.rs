/// OPTIONAL provenance rail (gated under the `svelte-oracle` feature): the vendored
/// `.js` matches the installed svelte source (LF-normalized). The DEFAULT run consumes
/// ONLY the vendored source, so this never runs in the canonical suite.
#[cfg(feature = "svelte-oracle")]
#[test]
fn vendored_matches_installed_when_present() {
    let installed_path = workspace_root()
        .join("node_modules")
        .join(".pnpm")
        .join(format!("svelte@{SVELTE_ORACLE_VERSION}"))
        .join("node_modules")
        .join("svelte")
        .join("src")
        .join("compiler")
        .join("phases")
        .join("1-parse")
        .join("remove_typescript_nodes.js");
    let Ok(installed) = std::fs::read_to_string(&installed_path) else {
        // node_modules not installed — the vendored snapshot is authoritative.
        return;
    };
    let norm = |s: &str| s.replace("\r\n", "\n");
    assert_eq!(
        norm(VENDORED_REMOVE_TS_NODES),
        norm(&installed),
        "Svelte scope-view drift: the vendored remove_typescript_nodes snapshot diverged from the \
         installed svelte source at {}. Re-vendor and re-verify the projection.",
        installed_path.display()
    );
}

/// FRESHNESS rail (gated under the `svelte-oracle` feature): re-run the name-parity
/// generator's `--check` through the PINNED compiler. A zero exit means the committed
/// corpus is still byte-identical to a fresh regeneration (so svelte's outcomes have not
/// drifted). Opting into `--features svelte-oracle` asserts the live toolchain is present,
/// so a missing / failing node run is a HARD failure (never a silent skip). This is the
/// SAME gating as the parse-parity generator's freshness rail.
#[cfg(feature = "svelte-oracle")]
#[test]
fn pinned_compiler_still_yields_every_committed_name_parity_row() {
    let root = workspace_root();
    let script = root.join("scripts/gen-svelte-name-parity-corpus.mjs");
    assert!(
        script.exists(),
        "name-parity generator missing: {}",
        script.display()
    );
    let output = std::process::Command::new("node")
        .arg(&script)
        .arg("--check")
        .current_dir(&root)
        .output()
        .expect("run gen-svelte-name-parity-corpus.mjs --check (node must be on PATH)");
    assert!(
        output.status.success(),
        "the committed name-parity corpus drifted from the pinned svelte@{SVELTE_ORACLE_VERSION} \
         compiler:\nstdout:\n{}\nstderr:\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr),
    );
}

#[test]
fn projection_source_has_no_soft_carrier() {
    assert!(
        !PROJECTION_SOURCE.contains("_ =>"),
        "Svelte scope-view drift: a `_ =>` wildcard arm appeared in component_scope_facts.rs. The \
         projection's Statement / Expression / Declaration / ClassElement classifiers must stay \
         exhaustive so a new OXC TS carrier breaks the build instead of slipping through."
    );
    assert!(
        !PROJECTION_SOURCE.contains(".accessibility.is_some("),
        "Svelte scope-view drift: a soft `.accessibility.is_some()` check reappeared in \
         formal_parameter_is_scope_erased — use an EXHAUSTIVE match over TSAccessibility so a new \
         accessibility variant forces a decision."
    );
    for line in PROJECTION_SOURCE.lines() {
        assert!(
            !(line.contains("matches!(") && line.contains("accessibility")),
            "Svelte scope-view drift: a soft `matches!` over accessibility reappeared in \
             component_scope_facts.rs: {line}"
        );
    }
}
