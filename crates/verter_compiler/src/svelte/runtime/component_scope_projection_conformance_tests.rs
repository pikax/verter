#[derive(serde::Deserialize)]
struct NameParityCorpus {
    svelte_oracle_version: String,
    rows: Vec<CorpusRow>,
}

#[derive(serde::Deserialize)]
struct CorpusRow {
    axis: String,
    source: String,
    requested_name: String,
    outcome: CorpusOutcome,
}

#[derive(serde::Deserialize)]
#[serde(tag = "kind", rename_all = "lowercase")]
enum CorpusOutcome {
    /// svelte compiled: `emitted_name` is the component function name svelte emitted
    /// (`function <NAME>($$anchor)`) for `requested_name` — the bare name (not reserved)
    /// or `<name>_1` (reserved).
    Compile { emitted_name: String },
    /// svelte hard-errored with diagnostic `code`.
    Reject { code: String },
    /// svelte CRASHED uncoded (an uncoded `TypeError`, NOT a typed diagnostic — e.g. a lone
    /// class index signature). name-parity is vacuous; the matrix asserts Verter's
    /// disposition (Verter does not crash — it defensively erases the construct).
    Crash,
}

/// The fixed bare NEGATIVE-CONTROL name the generator probes for every compile
/// construct — absent from every source, so svelte always emits it bare. Its presence
/// as a bare row per source discriminates a reserved planted name (→ `_1`) from a non-
/// reserved one, so an over-reserving projection turns it into `Zz9Unrelated_1` and REDs.
const NEGATIVE_CONTROL: &str = "Zz9Unrelated";

fn load_corpus() -> NameParityCorpus {
    serde_json::from_str(NAME_PARITY_CORPUS_JSON)
        .expect("name_parity_corpus.json must be valid JSON (run the generator)")
}

// ─────────────────────────────────────────────────────────────────────────────
// Verter dispositions per axis — how Verter's OBSERVABLE behavior is characterized
