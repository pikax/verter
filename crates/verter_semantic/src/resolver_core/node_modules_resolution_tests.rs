#[test]
fn ancestor_dirs_walks_up_from_the_parent_and_stops_at_the_boundary() {
    let dirs = ancestor_dirs("/proj/src/deep/file.ts", Some("/proj"));
    assert_eq!(dirs, vec!["/proj/src/deep", "/proj/src", "/proj"]);
}

#[test]
fn ancestor_dirs_from_dir_includes_the_starting_directory_itself() {
    let dirs = ancestor_dirs_from_dir("/proj/src", None);
    assert_eq!(dirs, vec!["/proj/src", "/proj"]);
}

#[test]
fn split_package_specifier_handles_scoped_and_unscoped_names() {
    assert_eq!(
        split_package_specifier("@scope/pkg/sub/path"),
        Some(("@scope/pkg".to_string(), "sub/path"))
    );
    assert_eq!(
        split_package_specifier("lodash/fp"),
        Some(("lodash".to_string(), "fp"))
    );
    assert_eq!(split_package_specifier("./relative"), None);
    assert_eq!(split_package_specifier("/absolute"), None);
}

// ── resolve_node_modules_package_from_dirs ──

#[test]
fn resolves_via_package_exports_string_target() {
    let view = known_world_view(
        &["/proj/node_modules/lodash/index.js"],
        &[(
            "/proj/node_modules/lodash",
            manifest(ResolutionPackageManifest {
                exports: Some(json!({ ".": "./index.js" })),
                ..empty_manifest()
            }),
        )],
    );

    let outcome = resolve_node_modules_package_from_dirs(
        &view,
        basis(),
        vec!["/proj".to_string()],
        "lodash",
        esm_import_ctx(),
    );
    assert_eq!(
        unwrap_hit(outcome),
        (
            "/proj/node_modules/lodash/index.js".to_string(),
            crate::resolver_core::ResolutionKind::PackageExports
        )
    );
}

#[test]
fn promotes_to_the_manifest_types_entry_when_the_request_prefers_declarations() {
    // The exports resolution hits the plain runtime file (no ".d.ts"
    // companion exists), so the outer node_modules step must separately
    // consult package_json.types and PROMOTE to it — discriminates from
    // probe_path_for_context's own (unrelated) declaration-companion
    // mechanism, which never fires here because no companion file exists.
    let view = known_world_view(
        &[
            "/proj/node_modules/lodash/index.js",
            "/proj/node_modules/lodash/dist/index.d.ts",
        ],
        &[(
            "/proj/node_modules/lodash",
            manifest(ResolutionPackageManifest {
                exports: Some(json!({ ".": "./index.js" })),
                types: Some("./dist/index.d.ts".to_string()),
                ..empty_manifest()
            }),
        )],
    );

    let outcome = resolve_node_modules_package_from_dirs(
        &view,
        basis(),
        vec!["/proj".to_string()],
        "lodash",
        type_import_ctx(),
    );
    assert_eq!(
        unwrap_hit(outcome),
        (
            "/proj/node_modules/lodash/dist/index.d.ts".to_string(),
            crate::resolver_core::ResolutionKind::NodeModules
        )
    );
}

