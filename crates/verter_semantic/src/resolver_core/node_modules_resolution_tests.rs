#[test]
fn tries_the_next_ancestor_directory_when_the_first_fully_misses() {
    let view = known_world_view(
        &["/proj/node_modules/shared/index.js"],
        &[(
            "/proj/node_modules/shared",
            manifest(ResolutionPackageManifest {
                main: Some("./index.js".to_string()),
                ..empty_manifest()
            }),
        )],
    );

    // First directory ("/proj/packages/app") has neither a manifest nor
    // any file at all — a genuine, fully-exhausted miss — before the
    // second directory ("/proj") produces the hit.
    let outcome = resolve_node_modules_package_from_dirs(
        &view,
        basis(),
        vec!["/proj/packages/app".to_string(), "/proj".to_string()],
        "shared",
        esm_import_ctx(),
    );
    assert_eq!(
        unwrap_hit(outcome),
        (
            "/proj/node_modules/shared/index.js".to_string(),
            crate::resolver_core::ResolutionKind::NodeModules
        )
    );
}

