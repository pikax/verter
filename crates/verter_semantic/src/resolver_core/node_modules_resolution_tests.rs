#[test]
fn a_relative_specifier_misses_immediately_without_walking_any_directory() {
    let view = known_world_view(&[], &[]);

    let outcome = resolve_node_modules_package_from_dirs(
        &view,
        basis(),
        vec!["/proj".to_string()],
        "./local",
        esm_import_ctx(),
    );
    match outcome {
        AttemptOutcome::Complete(CompletedAttempt {
            value: None,
            output,
        }) => {
            // Discriminates: a port that walked the directory list anyway
            // (ignoring `split_package_specifier`'s None) would record
            // PathProbe/PackageManifest facts here; the real algorithm
            // never even enters the loop.
            assert!(output.consumed_resolution_observations().is_empty());
        }
        other => panic!("expected Complete(None) with no facts, got {other:?}"),
    }
}

#[test]
fn resolve_node_modules_package_wraps_ancestor_dirs_from_the_importer_id() {
    let view = known_world_view(
        &["/proj/node_modules/dep/index.js"],
        &[(
            "/proj/node_modules/dep",
            manifest(ResolutionPackageManifest {
                main: Some("./index.js".to_string()),
                ..empty_manifest()
            }),
        )],
    );

    // importer at /proj/src/main.ts -> ancestor_dirs walks
    // ["/proj/src", "/proj"]; the package only exists under /proj's
    // node_modules, proving the wrapper's importer-id -> ancestor-walk
    // wiring reaches past the first (miss) ancestor.
    let outcome = resolve_node_modules_package(
        &view,
        basis(),
        "/proj/src/main.ts",
        "dep",
        esm_import_ctx(),
        None,
    );
    assert_eq!(
        unwrap_hit(outcome),
        (
            "/proj/node_modules/dep/index.js".to_string(),
            crate::resolver_core::ResolutionKind::NodeModules
        )
    );
}

// ── resolve_package_imports / resolve_package_imports_from_dir ──

#[test]
fn resolve_package_imports_from_dir_resolves_a_wildcard_import_mapping() {
    let view = known_world_view(
        &["/proj/src/utils/format.ts"],
        &[(
            "/proj",
            manifest(ResolutionPackageManifest {
                imports: Some(json!({ "#utils/*": "./src/utils/*.ts" })),
                ..empty_manifest()
            }),
        )],
    );

    let outcome = resolve_package_imports_from_dir(
        &view,
        basis(),
        "/proj/src",
        "#utils/format",
        esm_import_ctx(),
        None,
    );
    match outcome {
        AttemptOutcome::Complete(CompletedAttempt {
            value: Some(resolved),
            ..
        }) => assert_eq!(resolved, "/proj/src/utils/format.ts"),
        other => panic!("expected Complete(Some(_)), got {other:?}"),
    }
}

