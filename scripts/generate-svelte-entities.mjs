#!/usr/bin/env node
/**
 * Generator — the HTML5 named-character-reference table for the Svelte runtime
 * static-attribute entity decode.
 *
 * Vendors the CANONICAL named-entity table the pinned official
 * `svelte@5.56.3` compiler uses (`src/compiler/phases/1-parse/utils/entities.js`,
 * ~2231 entries incl. the 106 legacy no-semicolon forms) into a committed Rust
 * data module. The runtime IR's static-attribute serializer decodes
 * `decode_character_references(raw, is_attribute_value=true)` against this table
 * so the `$.from_html` skeleton matches official EXACTLY (a valid named entity
 * decodes to its char; an unknown reference keeps its `&` escaped) — porting the
 * canonical source rather than guessing a subset.
 *
 * This mirrors `scripts/generate-html-intrinsics.js`: one idempotent command
 * rewrites the committed Rust data module; a freshness test
 * (`svelte_entity_table_in_sync`) re-runs this generator and byte-compares.
 *
 *     node scripts/generate-svelte-entities.mjs            # rewrite the table
 *     node scripts/generate-svelte-entities.mjs --check    # assert in sync
 *
 * The pinned svelte version is the SAME oracle pin the golden generator uses
 * (`SVELTE_ORACLE_VERSION`); a `svelte` bump re-pins both and regenerates.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { pathToFileURL } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const REPO_ROOT = join(__dirname, "..");

/** The pinned oracle version (kept in lockstep with gen-svelte-goldens.mjs). */
const SVELTE_ORACLE_VERSION = "5.56.3";

/** The committed Rust data module path. */
const OUT_PATH = join(REPO_ROOT, "crates/verter_compiler/src/svelte/runtime/entity_table.rs");

/** The pinned svelte `entities.js` path (pnpm content-addressed, exact version). */
function entitiesModulePath() {
  const pinnedDir = join(
    REPO_ROOT,
    "node_modules/.pnpm",
    `svelte@${SVELTE_ORACLE_VERSION}`,
    "node_modules/svelte",
  );
  const p = join(pinnedDir, "src/compiler/phases/1-parse/utils/entities.js");
  if (!existsSync(p)) {
    throw new Error(
      `pinned svelte@${SVELTE_ORACLE_VERSION} entities.js not found at ${p}. ` +
        `Run \`pnpm install\` (svelte is a pinned devDependency).`,
    );
  }
  return p;
}

/** Render the committed Rust data module from the canonical entity table. */
async function renderModule() {
  const mod = await import(pathToFileURL(entitiesModulePath()).href);
  const entities = mod.default;
  const keys = Object.keys(entities);
  // Every value is a single code point in the pinned table (verified: no
  // multi-codepoint array values). A future svelte table that adds a
  // multi-codepoint entry must extend the Rust value type — fail loudly here.
  for (const k of keys) {
    if (typeof entities[k] !== "number") {
      throw new Error(
        `entity ${JSON.stringify(k)} has a non-numeric value ${JSON.stringify(
          entities[k],
        )} — the Rust table value type (u32) must be extended.`,
      );
    }
  }
  // Sort by NAME (the entity reference text, e.g. `amp;`) for a binary-search
  // lookup. The decode does longest-match by scanning candidate lengths, so the
  // table just needs a deterministic by-name order.
  keys.sort();
  const longest = Math.max(...keys.map((k) => k.length));

  const rows = keys.map((k) => `    (${JSON.stringify(k)}, ${entities[k]}),`).join("\n");

  return `// This file is auto-generated by scripts/generate-svelte-entities.mjs
// The canonical HTML5 named-character-reference table from the pinned official
// svelte@${SVELTE_ORACLE_VERSION} compiler (phases/1-parse/utils/entities.js).
// Do NOT hand-edit — regenerate via the script and review the diff.
//
// Each row is (entity-reference-name, code-point). The name INCLUDES the trailing
// \`;\` for the standard forms (e.g. \`amp;\`); the ${keys.filter((k) => !k.endsWith(";")).length} legacy
// forms have no \`;\` (e.g. \`copy\`) and decode only when NOT followed by \`=\` or an
// alphanumeric in an attribute value (the HTML named-character-reference rule).
// Sorted by name for binary-search lookup.

/// The longest entity-reference name in the table (in bytes) — the upper bound on
/// the decode's longest-match scan window.
pub(crate) const LONGEST_ENTITY_NAME: usize = ${longest};

/// The canonical named-character-reference table, sorted by name. Each entry maps
/// an entity reference name (with or without a trailing \`;\`) to its code point.
pub(crate) const NAMED_ENTITIES: &[(&str, u32)] = &[
${rows}
];

/// Look up an entity reference NAME (the text between \`&\` and the optional \`;\`,
/// INCLUDING the \`;\` for a standard form) in the canonical table, returning its
/// code point. Binary search over the sorted table.
#[must_use]
pub(crate) fn lookup_named_entity(name: &str) -> Option<u32> {
    NAMED_ENTITIES
        .binary_search_by_key(&name, |(k, _)| *k)
        .ok()
        .map(|i| NAMED_ENTITIES[i].1)
}
`;
}

async function main() {
  const check = process.argv.includes("--check");
  const rendered = await renderModule();
  if (check) {
    const existing = existsSync(OUT_PATH) ? readFileSync(OUT_PATH, "utf8") : "";
    if (existing !== rendered) {
      console.error(
        `generate-svelte-entities --check: ${OUT_PATH} is OUT OF SYNC with svelte@${SVELTE_ORACLE_VERSION}. ` +
          `Run \`node scripts/generate-svelte-entities.mjs\` and review the diff.`,
      );
      process.exit(1);
    }
    console.log(
      `generate-svelte-entities --check: entity table in sync with svelte@${SVELTE_ORACLE_VERSION}.`,
    );
    return;
  }
  writeFileSync(OUT_PATH, rendered);
  console.log(`generate-svelte-entities: wrote ${OUT_PATH} from svelte@${SVELTE_ORACLE_VERSION}.`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
