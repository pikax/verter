#!/usr/bin/env bash
# Regenerates ../receiving-coverage-controls.md by actually running each negative control.
#
# A recorded claim that a control was observed firing is worth nothing unless the observation is in
# the tree and can be reproduced. This script plants a defect into a charter, re-runs the derivation,
# records the verdict, and RESTORES the charter — so the evidence is a transcript of real runs rather
# than a description of runs somebody says they did.
#
# It restores every charter it touches, including on failure, and verifies the restore before exiting.
set -uo pipefail
cd "$(dirname "$0")/.."
CH=../../charters/TCM1.md
BAK=$(mktemp)
cp "$CH" "$BAK"
restore() { cp "$BAK" "$CH"; }
trap restore EXIT

OUT=receiving-coverage-controls.md
TMP=$(mktemp)
w() { cat >> "$TMP" || { echo "write to the transcript failed" >&2; exit 3; }; }
verdicts() { node probes/receiving-coverage-derivation.mjs 2>/dev/null | grep -E "^\| $1 " | awk -F'|' '{printf "%-4s %s\n", $2, $5}'; }
plant() { python3 -c "
import io,sys
p='$CH'; s=io.open(p,encoding='utf-8').read()
io.open(p,'w',encoding='utf-8').write(s.replace('## 5. Forbidden', sys.argv[1]+'\n\n## 5. Forbidden', 1))" "$1"; }

{
  echo "# Negative controls for the receiving-coverage derivation"
  echo
  echo "Generated by \`probes/receiving-coverage-controls.sh\`. **Do not edit by hand**; re-run it."
  echo "Each block is a real run: a defect is planted in a charter, the derivation is re-run, the verdict"
  echo "is read, and the charter is restored. A claim that a control fired is worth nothing unless the"
  echo "observation is in the tree."
  echo
  echo "Baseline verdicts, no plant:"
  echo '```'
  verdicts "[AB][0-9]"
  echo '```'
} | w

emit() {
  local label="$1" ins="$2" row="$3"
  plant "$ins"
  { echo; echo "**$label**"; echo '```'
    echo "planted into TCM1: $ins"
    verdicts "$row"
    echo '```'; } | w
  restore
}

emit "False HIT — an EXEMPTING paragraph must not become a covering hit; the planted criterion 11 must be ABSENT from A1's row." \
     '11. **Probe.** `source_projection_map()` is exempt from COMPILER-ENFORCED DELETION.' "A1"
emit "False EXCLUDED — a criterion imposing the obligation while calling a DIFFERENT field out of scope in another sentence must NOT read as excluding; A3 stops being EXCLUDED." \
     '11. **Probe.** `FfiBlockOverrideEntry.source_map` is migrated here. A different field is out-of-scope.' "A3"
emit "Exclusion is load-bearing — a plain non-excluding mention flips the excluded part to covered." \
     '11. **Probe.** `FfiBlockOverrideEntry.source_map` is migrated here.' "A3"

{
  echo
  echo "**Drift — the committed derivation must not silently disagree with the charters.**"
  echo '```'
  printf 'edited by hand\n' >> receiving-coverage.md
  node probes/receiving-coverage-derivation.mjs --check 2>&1 | head -1
  node probes/receiving-coverage-derivation.mjs --check >/dev/null 2>&1; echo "exit=$?"
  node probes/receiving-coverage-derivation.mjs --write >/dev/null 2>&1
  echo '```'
} | w

# The transcript is only published if it is STRUCTURALLY complete. Without this, a truncated or empty
# build could still be moved into place, and a caller comparing hashes before and after would see a
# change and call it a successful regeneration.
blocks=$(grep -c 'planted into TCM1' "$TMP")
if [ "$blocks" -ne 3 ] || ! grep -q 'Baseline verdicts' "$TMP" || ! grep -q 'Drift' "$TMP"; then
  echo "REFUSING TO PUBLISH an incomplete transcript: ${blocks} planted blocks, expected 3" >&2
  rm -f "$TMP"; exit 4
fi
mv "$TMP" "$OUT" || { echo "could not publish the transcript" >&2; exit 5; }

restore
if ! cmp -s "$CH" "$BAK"; then echo "REFUSING TO EXIT DIRTY: $CH was not restored" >&2; exit 2; fi
node probes/receiving-coverage-derivation.mjs --write >/dev/null 2>&1
echo "regenerated $OUT; charter restored and verified"
